# 题目：1038 统计同成绩学生
#
# 题目描述：
#   本题要求读入 N 名学生的成绩，将获得某一给定分数的学生人数输出。
#
# 输入格式：
#   输入在第 1 行给出不超过 10^5 的正整数 N，即学生总人数。随后一行给出 N 名学生的百分制整数成绩，中间以空格分隔。最后一行给出要查询的分数个数 K（不超过 N 的正整数），随后是 K 个分数，中间以空格分隔。
#
# 输出格式：
#   在一行中按查询顺序给出得分等于指定分数的学生人数，中间以空格分隔，但行末不得有多余空格。
#
# 实现原理：
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   桶排序/计数：利用数组下标作为分数，
#   直接计数统计各分数人数。
#
import sys
from collections import Counter

data = list(map(int, sys.stdin.read().split())); n = data[0]; c = Counter(data[1:n+1]); print(*[c[x] for x in data[n+2:]])
