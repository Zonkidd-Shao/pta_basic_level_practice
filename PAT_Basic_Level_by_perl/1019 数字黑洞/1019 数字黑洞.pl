use strict;
use warnings;

# =====================================================================
# 题目：1019 数字黑洞
# 难度：简单
# 知识点：数字处理、排序、循环模拟
# =====================================================================
#
# 【题目描述】
#   给定一个各位数字不完全相同的 4 位正整数，将 4 个数字按非递增
#   和非递减排序，用大数减小数，得到一个新数字。重复此过程，
#   最终会停在 6174（Kaprekar 常数，卡普雷卡尔黑洞）。
#   若 4 位数字全相同，则一步得到 0000。
#
# 【实现原理】
#   1. 输入处理：
#      - 读取输入数字，用 sprintf('%04d', $n) 格式化为 4 位，
#        不足 4 位时前面补零（保证始终是 4 位数字处理）
#   2. 迭代过程：
#      - 将 4 位数字拆分为单个字符的数组
#      - 升序排序得到最小数（从小到大）
#      - 降序排序得到最大数（从大到小，即升序后反转）
#      - 计算差值：最大数 - 最小数
#      - 按格式输出："xxxx - xxxx = xxxx"
#   3. 终止条件：
#      - 差值为 6174 时停止（到达黑洞）
#      - 差值为 0000 时停止（4 位数字全相同的情况）
#   4. 时间复杂度：O(1)，因为最多 7 步就能到达 6174（已被数学证明）。
#   5. 空间复杂度：O(1)，仅使用常数空间。
#
# 【输入样例 1】 6767
# 【输出样例 1】
#   7766 - 6677 = 1089
#   9810 - 0189 = 9621
#   9621 - 1269 = 8352
#   8532 - 2358 = 6174
#
# 【输入样例 2】 2222
# 【输出样例 2】
#   2222 - 2222 = 0000
# =====================================================================

# 读取输入的 4 位整数
my $n = <STDIN>;
chomp $n;
$n =~ s/\s+//g;
# 格式化为 4 位数字，不足前面补零
# 例如输入 3 → 0003
$n = sprintf('%04d', $n);

# 循环执行数字黑洞过程
while (1) {
    # 将数字拆分为单个字符（即各位数字）
    my @d    = split //, $n;
    # 升序排序（从小到大）→ 组成最小数
    my @asc  = sort @d;
    # 降序排序（从大到小）→ 组成最大数
    my @desc = reverse @asc;

    # 升序排列组成的最小数（转为数值）
    my $small = join('', @asc)  + 0;
    # 降序排列组成的最大数（转为数值）
    my $big   = join('', @desc) + 0;
    # 计算差值
    my $diff  = $big - $small;

    # 按 4 位格式输出本步计算
    printf "%04d - %04d = %04d\n", $big, $small, $diff;

    # 终止条件：到达 6174 或 得到 0000
    last if $diff == 6174 || $diff == 0;

    # 将差值格式化为 4 位，作为下一轮的输入
    $n = sprintf('%04d', $diff);
}
