# 题目名称：完美数列
# 题目编号：PAT Basic 1030
# 实现原理：
#   1. 读取输入：数列长度n、参数p、以及数列元素
#   2. 将数列从小到大排序
#   3. 使用滑动窗口（双指针）法寻找最长的完美数列：
#      - i为窗口左端点，j为窗口右端点
#      - 对于每个i，向右移动j直到不满足a[j] <= a[i]*p
#      - 记录窗口的最大长度
#      - 因为数组已排序，j只需单向移动，不需要回溯
#   4. 输出最长完美数列的长度
# 时间复杂度：O(n log n)，排序需要O(n log n)，滑动窗口遍历需要O(n)
# 空间复杂度：O(1)，如果不计排序的栈空间则为常量空间
z<-scan("stdin",what=double(),quiet=TRUE);n<-z[1];p<-z[2];a<-sort(z[-c(1,2)]);best<-0L;j<-1L;for(i in seq_len(n)){while(j<=n&&a[j]<=a[i]*p)j<-j+1L;best<-max(best,j-i)};cat(best,"\n")
