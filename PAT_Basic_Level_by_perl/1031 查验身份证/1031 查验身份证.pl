use strict;
use warnings;

# =====================================================================
# 题目：1031 查验身份证
# 难度：简单
# 知识点：字符串处理, 权重求和, 取模
# =====================================================================
#
# 【题目描述】
#   合法身份证号码为 18 位，前 17 位为数字，第 18 位为校验码。
#   对前 17 位加权求和后对 11 取模得 Z，再按映射表得到校验码 M。
#   现给出若干身份证号码，验证其有效性，按输入顺序输出有问题的号码；
#   若全部正常则输出 All passed。
#
# 【实现原理】
#   1. 固定权重数组和校验码映射表（Z 值 -> M 值）。
#   2. 逐位求和：对前 17 位数字与对应权重相乘累加。
#   3. 校验：取模 11 得到 Z，与映射表的 M 比较最后一位。
#      同时检查前 17 位是否全为数字、长度是否为 18。
#   4. 收集非法号码并按序输出。
#
# 【输入样例】
#   4
#   320124198808240056
#   12010X198901011234
#   110108196711301866
#   37070419881216001X
# 【输出样例】
#   12010X198901011234
#   110108196711301866
#   37070419881216001X
# =====================================================================

# 前 17 位数字的权重
my @w = (7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2);
# Z 值 0-10 对应的校验码
my $check = '10X98765432';

# 读取身份证号码个数
my $n = <STDIN>;
chomp $n;

my @bad;

# 逐个处理身份证号码
for (1 .. $n) {
    my $s = <STDIN>;
    chomp $s;

    my $ok = 1;
    # 长度必须为 18，且前 17 位必须全为数字
    if (length($s) != 18) {
        $ok = 0;
    }
    elsif ($s !~ /^\d{17}/) {
        $ok = 0;
    }
    else {
        # 前 17 位加权求和
        my $sum = 0;
        for my $k (0 .. 16) {
            $sum += substr($s, $k, 1) * $w[$k];
        }
        # 比较计算出的校验码与最后一位
        if (substr($check, $sum % 11, 1) ne substr($s, 17, 1)) {
            $ok = 0;
        }
    }

    # 记录有问题的号码
    push @bad, $s unless $ok;
}

# 输出结果
if (@bad) {
    print "$_\n" for @bad;
}
else {
    print "All passed\n";
}