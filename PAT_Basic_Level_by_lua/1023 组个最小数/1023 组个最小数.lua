-- 题目编号: 1023 组个最小数
-- 实现原理: 先找出第一个非零的最小数字作为首位并消耗一个该数字的计数，然后按数字0~9的顺序将剩余数字依次拼接到末尾，从而组成最小数。

-- 存储0~9每个数字的个数
local c = {}
-- 读取10个数字，分别表示数字0到9的个数
for i = 0, 9 do
    c[i] = io.read("*n")
end

-- 存储结果数字的数组
local out = {}

-- 第一步：确定首位数字（不能是0）
-- 从1到9找第一个有剩余的数字（最小的非零数字）
for i = 1, 9 do
    if c[i] > 0 then
        -- 将该数字作为首位
        out[#out + 1] = i
        -- 该数字的个数减1
        c[i] = c[i] - 1
        -- 找到后就退出循环
        break
    end
end

-- 第二步：按从小到大的顺序，将剩余的所有数字依次拼接到后面
for i = 0, 9 do
    -- 有多少个就拼多少个
    for _ = 1, c[i] do
        out[#out + 1] = i
    end
end

-- 输出组成的最小数
print(table.concat(out))
