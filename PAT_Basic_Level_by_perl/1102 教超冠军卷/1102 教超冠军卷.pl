use strict;
use warnings;

# =====================================================================
# 题目：1102 教超冠军卷
# 难度：简单
# 知识点：循环, 最大值查找
# =====================================================================
#
# 【题目描述】
#   给出 N 份试卷的 ID、单价和购买人次，分别找出销量冠军（人次最多）
#   和销售额冠军（单价×人次最大），输出其 ID 及对应数值。
#
# 【实现原理】
#   1. 逐行读取试卷信息，实时比较：
#      - 销量 = 购买人次，找出最大者
#      - 销售额 = 单价 × 购买人次，找出最大者
#   2. 最后分两行输出两个冠军的 ID 和数值。
#
# 【输入样例】
#   4
#   zju007 39 10
#   pku2019 9 332
#   pat2018 95 79
#   qdu106 19 38
# 【输出样例】
#   pku2019 332
#   pat2018 7505
# =====================================================================

my $line = <STDIN>;
chomp $line;
my $n = $line + 0;

my ($sid, $smax) = ('', -1);    # 销量冠军的 ID 和销量
my ($mid, $mmax) = ('', -1);    # 销售额冠军的 ID 和销售额

for (1 .. $n) {
    my $l = <STDIN>;
    chomp $l;
    my ($id, $price, $cnt) = split / +/, $l;

    # 销量冠军：购买人次最大
    if ($cnt > $smax) { $smax = $cnt; $sid = $id; }
    # 销售额冠军：单价 × 人次最大
    my $sales = $price * $cnt;
    if ($sales > $mmax) { $mmax = $sales; $mid = $id; }
}

print "$sid $smax\n";
print "$mid $mmax\n";
