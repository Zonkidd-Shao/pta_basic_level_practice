# 题目名称：狼人杀-简单版
# 题目编号：PAT Basic 1089
# 实现原理：
#   暴力枚举所有可能的2人狼人组合，验证是否满足题目条件：恰好2人说谎，且1个狼人说谎、1个好人说谎。
#   关键步骤：
#   1. 读取玩家人数N和每个玩家的发言
#   2. 双层循环枚举所有可能的2人狼人组合(i,j)，i<j
#   3. 对每个组合，判断每个玩家是否说谎：
#      - 玩家k说v[k]号是狼人(v[k]<0)或好人(v[k]>0)
#      - 实际身份：abs(v[k])在狼人中就是狼人，否则是好人
#      - 说谎条件：(说的是狼人) != (实际是狼人)
#   4. 统计说谎人数和其中狼人的数量
#   5. 如果恰好2人说谎且其中恰有1个狼人，则找到解，按递增顺序输出
#   6. 按顺序枚举保证第一个找到的就是最小序列解
#   由于N≤100，C(100,2)=4950种组合，暴力枚举完全可行。
# 时间复杂度：O(N³)，枚举组合O(N²)，每个组合验证O(N)
# 空间复杂度：O(N)，存储玩家发言和说谎者列表
z<-as.integer(scan("stdin",quiet=TRUE));n<-z[1];v<-z[-1];for(i in 1:(n-1))for(j in (i+1):n){lie<-which(vapply(1:n,function(k)(v[k]<0)!=(abs(v[k])%in%c(i,j)),logical(1)));if(length(lie)==2&&sum(lie%in%c(i,j))==1){cat(i,j,"\n");quit()}};cat("No Solution\n")
