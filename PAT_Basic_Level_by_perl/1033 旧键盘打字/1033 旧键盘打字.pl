use strict;
use warnings;

# =====================================================================
# 题目：1033 旧键盘打字
# 难度：简单
# 知识点：字符串处理, 集合判断
# =====================================================================
#
# 【题目描述】
#   旧键盘坏掉几个键，敲文字时对应字符不会出现。给定坏掉的键和应输入的
#   文字，输出能打出的结果文字。坏键以大写给出；若上档键 '+' 坏掉，
#   则所有大写英文字母都无法打出。若一个字符都打不出，则输出空行。
#
# 【实现原理】
#   1. 输入处理：读取坏键串和文字串，坏键统一转为大写便于判断。
#   2. 判断上档键：检查坏键串是否包含 '+'.
#   3. 逐字符过滤：对文字中每个字符，若其大写形式属于坏键，
#      或上档键坏掉且该字符为大写字母，则跳过，否则输出。
#   4. 时间复杂度：O(n)，n 为文字长度（≤10^5）。
#
# 【输入样例】
#   7+IE.
#   7_This_is_a_test.
# 【输出样例】
#   _hs_s_a_tst
# =====================================================================

# 读取坏掉的键和应输入的文字（第一行可能为空）
my $broken = <STDIN>;
my $text   = <STDIN>;
chomp $broken;
chomp $text;

# 上档键 '+' 是否坏掉
my $has_shift = index($broken, '+') != -1;

# 逐字符过滤并输出
for my $c (split //, $text) {
    my $uc = uc $c;
    # 该字符（大写）是坏键
    my $skip = index($broken, $uc) != -1;
    # 或上档键坏掉且该字符为大写字母
    $skip = 1 if $has_shift && $c =~ /[A-Z]/;
    print $c unless $skip;
}
print "\n";