use strict;
use warnings;

# =====================================================================
# 题目：1103 缘分数
# 难度：中等
# 知识点：数学, 平方根判断
# =====================================================================
#
# 【题目描述】
#   若 a^3 - (a-1)^3 = c^2（c 为整数），且存在 b 使得
#   c = b^2 + (b-1)^2，则 (a,b) 是一对缘分数。
#   给定区间 [m,n]，按 a 升序输出所有缘分数对，无解输出 No Solution。
#
# 【实现原理】
#   1. 遍历 a 从 m 到 n，利用恒等式
#      a^3 - (a-1)^3 = 3a^2 - 3a + 1 精确计算 x。
#   2. 取 c = int(sqrt(x)) 并微调，判断是否 c*c == x。
#   3. 遍历 b 从 1 到 sqrt(c)，判断 b^2 + (b-1)^2 == c。
#   4. 命中即记录，最后按序输出。
#
# 【输入样例】
#   8 200
# 【输出样例】
#   8 3
#   105 10
# =====================================================================

my $line = <STDIN>;
chomp $line;
my ($m, $n) = split / +/, $line;

my @ans;
for my $a ($m .. $n) {
    # a^3 - (a-1)^3 = 3a^2 - 3a + 1，用整数运算保证精确
    my $x = 3 * $a * $a - 3 * $a + 1;
    # 求平方根并微调，避免浮点误差
    my $c = int(sqrt($x));
    $c++ while ($c + 1) * ($c + 1) <= $x;
    $c-- while $c * $c > $x;
    # c 必须是整数，即 c*c == x
    next unless $c * $c == $x;
    # 在 b 的可行范围内寻找 c = b^2 + (b-1)^2
    for my $b (1 .. int(sqrt($c))) {
        if ($b * $b + ($b - 1) ** 2 == $c) {
            push @ans, "$a $b";
            last;
        }
    }
}

if (@ans) {
    print join("\n", @ans), "\n";
} else {
    print "No Solution\n";
}
