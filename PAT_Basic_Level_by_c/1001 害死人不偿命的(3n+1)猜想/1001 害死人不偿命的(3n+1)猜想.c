/*
 * 题目：1001 害死人不偿命的(3n+1)猜想
 * 实现原理：
 *   根据卡拉兹猜想，对于任意正整数n：
 *   - 如果n是偶数，则n = n / 2
 *   - 如果n是奇数，则n = (3 * n + 1) / 2
 *   重复上述过程直到n变为1，统计所需的步骤数。
 *   本题采用循环迭代方式，每次迭代判断n的奇偶性并执行相应操作，同时累加计数器。
 */
#include <stdio.h>

int main() {
    int n, count = 0;            // n 为输入的正整数，count 统计所需步数
    scanf("%d", &n);
    while (n != 1) {             // 反复迭代直到 n 变为 1
        if (n % 2 == 0) {        // 偶数：直接减半
            n /= 2;
        } else {                 // 奇数：执行 (3n+1)/2
            n = (3 * n + 1) / 2;
        }
        count++;                 // 每迭代一次，步数加 1
    }
    printf("%d\n", count);       // 输出需要的步数
    return 0;
}