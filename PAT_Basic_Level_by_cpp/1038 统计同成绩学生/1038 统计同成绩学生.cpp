/*
 * 1038 统计同成绩学生
 *
 * 【实现原理】
 * 给定 N 个学生的成绩（范围 0~100），以及 K 个查询成绩，
 * 对每个查询成绩，输出获得该成绩的学生人数。
 *
 * 【算法思路】
 * 1. 使用计数数组 cnt[101]，以成绩作为索引，统计每个分数出现次数
 * 2. 读入所有成绩，在数组中对应位置累加
 * 3. 对每个查询，直接输出 cnt[q] 即可
 *
 * 【关键点】
 * - 成绩范围只有 0~100，使用固定大小数组即可
 * - 计数排序思想，O(1) 时间响应查询
 * - 输出格式要求：第一个查询前无空格，后续查询前加空格
 *
 * 【复杂度分析】
 * - 时间复杂度：O(N + K)，读入和查询均为线性时间
 * - 空间复杂度：O(1)，固定 101 个元素的数组
 */

#include <iostream>

using namespace std;

int main() {
    int n;
    if (!(cin >> n)) return 0;

    int cnt[101] = {0};  // 成绩范围 0~100，计数数组初始化为 0
    for (int i = 0; i < n; ++i) {
        int s; cin >> s;
        ++cnt[s];  // 统计该分数的学生数
    }

    int k;
    cin >> k;
    for (int i = 0; i < k; ++i) {
        int q; cin >> q;
        if (i) cout << ' ';  // 第一个输出前不加空格
        cout << cnt[q];      // 直接输出查询成绩的出现次数
    }
    cout << endl;
    return 0;
}