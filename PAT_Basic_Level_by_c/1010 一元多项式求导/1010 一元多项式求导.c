/*
 * 题目：1010 一元多项式求导
 * 实现原理：
 *   对一元多项式进行求导运算。多项式形式为：a0*x^0 + a1*x^1 + ... + an*x^n
 *   求导规则：对于项a*x^e，导数为a*e*x^(e-1)
 *   算法步骤：
 *   1. 循环读取每一项的系数和指数
 *   2. 若指数为0，则该项导数为0，跳过不输出
 *   3. 否则输出导数项：系数*指数 和 指数-1
 *   4. 特殊处理：若输入多项式只有常数项，则输出"0 0"
 *   使用first标志控制输出格式，确保项之间有空格分隔。
 */
#include <stdio.h>

int main() {
    int coeff, exp;             // 当前项的系数与指数
    int first = 1;              // 是否为首个输出项
    while (scanf("%d %d", &coeff, &exp) != EOF) {   // 不断读入系数和指数，直到文件结束
        if (exp == 0) continue;                     // 常数项导数为 0，跳过不输出
        if (!first) {
            printf(" ");                            // 非首项前输出空格分隔
        }
        printf("%d %d", coeff * exp, exp - 1);      // 求导结果：系数乘指数、指数减 1
        first = 0;
    }
    if (first) {                // 全程无输出（多项式只有常数项），需输出 "0 0"
        printf("0 0");
    }
    printf("\n");
    return 0;
}