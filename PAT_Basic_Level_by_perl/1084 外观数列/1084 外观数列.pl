use strict;
use warnings;

# =====================================================================
# 题目：1084 外观数列
# 难度：简单
# 知识点：字符串处理, 循环迭代
# =====================================================================
#
# 【题目描述】
#   外观数列的每一项是对前一项的描述：统计连续相同字符的个数。
#   从数字 d 开始，第 n+1 项描述第 n 项。
#   给定 d 和 N，输出外观数列的第 N 项。
#
# 【实现原理】
#   1. 读取 d 和 N
#   2. 重复 N-1 次：扫描当前字符串，统计连续相同字符的个数
#   3. 输出拼接结果"字符+个数"，作为下一项
#   4. 时间复杂度 O(N * 长度)
# =====================================================================
#
# 【输入样例】
#   1 8
# 【输出样例】
#   1123123111
# =====================================================================

# 读取 d 和 N
my @tok = split /\s+/, join('', <STDIN>);
my ($d, $n) = @tok;

my $a = $d;
# 迭代生成第 2 项到第 N 项
for (1 .. $n - 1) {
    my $out = '';
    my $i = 0;
    # 扫描当前字符串，统计连续相同字符
    while ($i < length $a) {
        my $ch = substr($a, $i, 1);
        my $j = $i;
        # 跳过所有与 $ch 相同的字符
        while ($j < length $a && substr($a, $j, 1) eq $ch) { $j++; }
        # 输出"字符 + 连续个数"
        $out .= $ch . ($j - $i);
        $i = $j;
    }
    $a = $out;
}

print "$a\n";
