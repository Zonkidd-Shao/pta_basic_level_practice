# 题目：1048 数字加密
#
# 题目描述：
#   本题要求实现一种数字加密方法。首先固定一个加密用正整数 A，对任一正整数 B，将其每 1 位数字与 A 的对应位置上的数字进行以下运算：对奇数位，对应位的数字相加后对 13 取余——这里用 J 代表 10、Q 代表 11、K 代表 12；对偶数位，用 B 的数字减去 A 的数字，若结果为负数，则再加 10。这里令个位为第 1 位。
#
# 输入格式：
#   输入在一行中依次给出 A 和 B，均为不超过 100 位的正整数，其间以空格分隔。
#
# 输出格式：
#   在一行中输出加密后的结果。
#
# 实现原理：
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   字符串处理与加密：按位进行加密运算，
#   注意奇偶位的不同处理方式。
#
import sys

a,b=sys.stdin.read().split(); a=a.zfill(max(len(a),len(b))); b=b.zfill(len(a)); out=[]
for i,(x,y) in enumerate(zip(a,b),1):
    z=int(x)+int(y)
    out.append(str((z%13) if z%13<10 else 'JQK'[z%13-10]) if i%2 else str(z%10))
print(''.join(out).lstrip('0') or '0')
