# 题目名称：最近的斐波那契数
# 题目编号：PAT Basic 1124
# 实现原理：
#   找出与给定正整数N最接近的斐波那契数。斐波那契数列F0=0,F1=1,Fn=Fn-1+Fn-2。
#   若有两个数距离相同（即N正好在两个斐波那契数中间），输出较小的那个。
#   解题思路：1. 递推生成斐波那契数，直到当前数≥N；
#   2. 此时前一个斐波那契数a=F_k < N，当前数b=F_{k+1} ≥ N；
#   3. 比较N-a和b-N：若N-a < b-N则a更近，若b-N < N-a则b更近；
#   4. 若相等则输出较小的那个（即a）。
#   斐波那契数增长是指数级的，即使N=10^8也只需约40次迭代。
# 时间复杂度：O(log N)，斐波那契数指数增长，迭代次数为对数级
# 空间复杂度：O(1)，只用两个变量滚动记录前两项
n<-as.numeric(scan("stdin",quiet=TRUE)[1]);a<-0;b<-1;while(b<n){t<-a+b;a<-b;b<-t};cat(if(n-a<=b-n)a else b,"\n")
