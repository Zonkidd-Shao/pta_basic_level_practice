# 题目名称：说反话
# 题目编号：PAT Basic 1009
# 实现原理：
#   读入一行字符串，先去除首尾空白，然后按空格分割成单词数组。
#   使用 rev 函数将单词数组反转，再用空格连接成倒序句子输出。
#   核心思想：字符串分割 → 数组反转 → 字符串拼接。
# 时间复杂度：O(n) - n 为字符串长度，分割、反转、拼接各需一次遍历
# 空间复杂度：O(n) - 存储分割后的单词数组
x <- readLines("stdin",warn=FALSE)[1]; w <- strsplit(trimws(x), "\\s+")[[1]]; cat(paste(rev(w),collapse=" "),"\n")
