use strict;
use warnings;

# =====================================================================
# 题目：1015 德才论
# 难度：中等
# 知识点：结构体排序、自定义排序规则、多关键字排序
# =====================================================================
#
# 【题目描述】
#   根据司马光的"德才论"对考生进行录取排名：
#   - 录取最低分数线 L：德分和才分均不低于 L 才有资格
#   - 优先录取线 H：
#     第一类（才德全尽）：德 >= H 且 才 >= H，按总分降序
#     第二类（德胜才）：德 >= H 且 L <= 才 < H，按总分降序
#     第三类（德胜才者）：L <= 德 < H 且 L <= 才 < H 且 德 >= 才，按总分降序
#     第四类（其他达标者）：其余达线考生，按总分降序
#   同类中：总分降序 → 德分降序 → 学号升序
#
# 【实现原理】
#   1. 数据筛选：
#      - 读取每个考生信息，检查德分和才分是否都 >= L
#      - 不达标者直接跳过
#   2. 分类判定：
#      - 按上述四类规则将达标考生分到不同类别
#      - 类别编号 1-4，数字越小优先级越高
#   3. 数据存储：
#      - 使用哈希引用（匿名哈希）存储每个学生的信息
#      - 字段：id（学号）、d（德分）、c（才分）、cat（类别）
#   4. 自定义排序：
#      - 使用 sort 函数配合多关键字比较
#      - 优先级：类别升序 → 总分降序 → 德分降序 → 学号升序
#      - 利用 Perl 的 || 运算符实现多重排序键
#        （前面的比较结果为 0 时才继续比较后面的键）
#   5. 输出结果：
#      - 先输出达标人数
#      - 再按排序后顺序输出每个学生
#   6. 时间复杂度：O(N log N)，排序是主要开销。
#   7. 空间复杂度：O(N)，存储所有达标学生信息。
#
# 【输入样例】
#   14 60 80
#   10000001 64 90
#   10000002 90 60
#   ... (共14个学生)
# 【输出样例】
#   12
#   10000013 90 99
#   10000012 80 100
#   ... (共12个达标学生)
# =====================================================================

# 读取第一行：N（考生总数）、L（最低分数线）、H（优先录取线）
my $line = <STDIN>;
chomp $line;
my ($N, $L, $H) = split /\s+/, $line;

# 存储达标学生信息的数组
my @stu;

# 逐行读取考生信息
while (my $l = <STDIN>) {
    chomp $l;
    # 跳过空行
    next if $l eq '';
    # 按空白分割为学号、德分、才分
    my ($id, $d, $c) = split /\s+/, $l;

    # 德分或才分低于最低线，不录取
    next if $d < $L || $c < $L;

    # 判定类别
    my $cat;
    if    ($d >= $H && $c >= $H)            { $cat = 1; }  # 第一类：才德全尽
    elsif ($d >= $H && $c >= $L)            { $cat = 2; }  # 第二类：德胜才
    elsif ($d >= $L && $c >= $L && $d >= $c) { $cat = 3; } # 第三类：德胜才者
    else                                    { $cat = 4; }  # 第四类：其他

    # 将学生信息存入数组（使用匿名哈希）
    # d+0 和 c+0 确保以数值形式存储
    push @stu, { id => $id, d => $d + 0, c => $c + 0, cat => $cat };
}

# 自定义排序：
#  1. 类别升序（cat 小的排前面）
#  2. 总分降序（d+c 大的排前面）
#  3. 德分降序（d 大的排前面）
#  4. 学号升序（id 小的排前面，字符串比较）
#
# Perl sort 的比较规则：
#   <=>  数值比较，返回 -1, 0, 1
#   cmp  字符串比较，返回 -1, 0, 1
#   ||   短路或，前面为 0 才执行后面
@stu = sort {
    $a->{cat} <=> $b->{cat}
    || ($b->{d} + $b->{c}) <=> ($a->{d} + $a->{c})
    || $b->{d} <=> $a->{d}
    || $a->{id} cmp $b->{id}
} @stu;

# 输出达标人数
print scalar(@stu), "\n";
# 输出每个学生信息
for my $s (@stu) {
    print "$s->{id} $s->{d} $s->{c}\n";
}
