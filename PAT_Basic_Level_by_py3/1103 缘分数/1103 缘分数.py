# 题目：1103 缘分数
#
# 题目描述：
#   所谓**缘分数**是指这样一对正整数 a 和 b，其中 a 和它的小弟 a-1 的立方差正好是另一个整数 c 的平方，而 c 正好是 b 和它的小弟 b-1 的平方和。例如 8^3 - 7^3 = 169 = 13^2，而 13 = 3^2 + 2^2，于是 8 和 3 就是一对缘分数。
#   给定 a 所在的区间 [m,n]，是否存在缘分数？
#
# 输入格式：
#   输入给出区间的两个端点 0<m<n\le 25000，其间以空格分隔。
#
# 输出格式：
#   按照 a 从小到大的顺序，每行输出一对缘分数，数字间以空格分隔。如果无解，则输出 `No Solution`。
#
# 实现原理：
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   因数与真因数和：计算两个数的真因数和，
#   判断是否互为缘分数（即你的真因数和等于我，我的真因数和等于你）。
#
import sys,math

m,n=map(int,sys.stdin.read().split());ans=[]
for a in range(m,n+1):
 c=math.isqrt(a**3-(a-1)**3)
 if c*c==a**3-(a-1)**3:
  for b in range(1,math.isqrt(c)+1):
   if b*b+(b-1)**2==c:ans.append((a,b))
print('\n'.join(f'{a} {b}' for a,b in ans) or 'No Solution')
