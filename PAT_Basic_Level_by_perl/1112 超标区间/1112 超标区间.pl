use strict;
use warnings;

# =====================================================================
# 题目：1112 超标区间
# 难度：简单
# 知识点：数组遍历, 连续区间统计
# =====================================================================
#
# 【题目描述】
#   给定 N 个数据点（横坐标 0 到 N-1）和阈值 T，找出所有纵坐标
#   严格大于 T 的连续区间，输出每个区间的左右端点。若无超标数据，
#   则输出所有数据的最大值。
#
# 【实现原理】
#   1. 从左到右遍历，找到第一个超标点作为区间左端。
#   2. 向右扩展直到下一个点不超标，形成区间 [A, B]。
#   3. 记录是否存在超标区间；若没有则输出最大值。
#
# 【输入样例】
#   11 25
#   21 15 25 28 35 27 20 24 18 32 23
# 【输出样例】
#   [3, 5]
#   [9, 9]
# =====================================================================

# 读取 N 和阈值 T
my ($n, $t) = split /\s+/, <STDIN>;
# 读取数据点
my @a = split /\s+/, <STDIN>;

my $i     = 0;
my $found = 0;

while ($i < $n) {
    if ($a[$i] > $t) {
        # 找到区间左端 i，向右扩展
        my $j = $i;
        while ($j + 1 < $n && $a[$j + 1] > $t) { $j++; }
        print "[$i, $j]\n";
        $found = 1;
        $i = $j + 1;
    }
    else {
        $i++;
    }
}

# 若没有超标数据，输出最大值
if (!$found) {
    my $mx = $a[0];
    for my $v (@a) { $mx = $v if $v > $mx; }
    print "$mx\n";
}
