use strict;
use warnings;

# =====================================================================
# 题目：1026 程序运行时间
# 难度：简单
# 知识点：模拟, 时间计算
# =====================================================================
#
# 【题目描述】
#   给定两次 clock() 的时钟打点数 C1、C2（CLK_TCK=100），
#   求函数运行时间，四舍五入到秒，并按 hh:mm:ss 格式输出。
#
# 【实现原理】
#   1. 差值除以 100 得到秒数，四舍五入。
#   2. 分解为时、分、秒，按 2 位补零输出。
#
# 【输入样例】
#   123 4577973
# 【输出样例】
#   12:42:59
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
my ($c1, $c2) = @tok;

my $t = int(($c2 - $c1) / 100 + 0.5);   # 四舍五入到秒
my $h = int($t / 3600);
my $m = int(($t % 3600) / 60);
my $s = $t % 60;

printf "%02d:%02d:%02d\n", $h, $m, $s;