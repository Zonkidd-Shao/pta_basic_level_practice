use strict;
use warnings;

# =====================================================================
# 题目：1004 成绩排名
# 难度：入门
# 知识点：循环结构、条件判断、最值查找
# =====================================================================
#
# 【题目描述】
#   读入 n 名学生的姓名、学号、成绩，分别输出成绩最高和成绩最低
#   学生的姓名和学号。
#
# 【实现原理】
#   1. 初始化最值变量：
#      - 最高分初始化为 -1（成绩范围 0-100，-1 保证第一个成绩必然更新）
#      - 最低分初始化为 101（同理，101 保证第一个成绩必然更新）
#   2. 遍历输入：每读入一个学生的信息，分别与当前最高、最低分比较，
#      若满足条件则更新对应的记录。
#   3. 一次遍历同时完成最大和最小值的查找，避免多次扫描数据。
#   4. 时间复杂度：O(n)，只需遍历一次所有学生数据。
#   5. 空间复杂度：O(1)，仅保存当前最值对应的学生信息。
#
# 【输入样例】
#   3
#   Joe Math990112 89
#   Mike CS991301 100
#   Mary EE990830 95
# 【输出样例】
#   Mike CS991301
#   Joe Math990112
# =====================================================================

# 读取学生人数 n
my $n = <STDIN>;
chomp $n;

# 初始化最高分记录：姓名、学号、分数
# 分数初始为 -1，确保第一个学生必然能更新
my ($max_name, $max_id, $max_s) = ('', '', -1);

# 初始化最低分记录：姓名、学号、分数
# 分数初始为 101，确保第一个学生必然能更新
my ($min_name, $min_id, $min_s) = ('', '', 101);

# 遍历 n 个学生
while ($n-- > 0) {
    # 读取一行学生信息
    my $line = <STDIN>;
    chomp $line;
    # 按空白分割为姓名、学号、成绩
    my ($name, $id, $score) = split /\s+/, $line;

    # 若当前成绩大于已记录的最高分，更新最高分记录
    if ($score > $max_s) { $max_s = $score; $max_name = $name; $max_id = $id; }
    # 若当前成绩小于已记录的最低分，更新最低分记录
    if ($score < $min_s) { $min_s = $score; $min_name = $name; $min_id = $id; }
}

# 输出最高分学生
print "$max_name $max_id\n";
# 输出最低分学生
print "$min_name $min_id\n";
