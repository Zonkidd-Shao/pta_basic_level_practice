use strict;
use warnings;

# =====================================================================
# 题目：1029 旧键盘
# 难度：简单
# 知识点：字符串处理, 集合去重
# =====================================================================
#
# 【题目描述】
#   旧键盘上坏了几个键，敲一段文字时对应的字符不会出现。
#   给定应该输入的文字和实际被输入的文字，列出肯定坏掉的那些键
#   （英文字母只输出大写，每个坏键只输出一次，按发现顺序输出）。
#
# 【实现原理】
#   1. 输入处理：读取两行字符串，分别表示应该输入的文字和实际输出的文字。
#   2. 逐个字符对比：遍历应该输入的文字，若该字符未出现在实际输出中，
#      则该键坏掉，按其大写形式输出并标记去重。
#   3. 时间复杂度：O(n*m)，n、m 为两串长度（≤80），规模很小。
#
# 【输入样例】
#   7_This_is_a_test
#   _hs_s_a_es
# 【输出样例】
#   7TI
# =====================================================================

# 读取应该输入的文字和实际被输入的文字
my $expected = <STDIN>;
my $actual = <STDIN>;
chomp $expected;
chomp $actual;

# 记录已输出的坏键（大写），用于去重
my %seen;

# 遍历应该输入的文字，找出缺失的字符（坏键）
for my $c (split //, $expected) {
    my $u = uc $c;
    # 该字符未出现在实际输出中，且尚未输出过该大写键
    if (index($actual, $c) == -1 && !$seen{$u}) {
        print $u;
        $seen{$u} = 1;
    }
}
print "\n";