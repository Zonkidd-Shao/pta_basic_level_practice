use strict;
use warnings;

# =====================================================================
# 题目：1065 单身狗
# 难度：简单
# 知识点：哈希表, 排序
# =====================================================================
#
# 【题目描述】
#   给出 N 对夫妻/伴侣的 ID 以及参加派对的 M 位客人 ID，
#   找出"落单"的客人（伴侣未到场或本身没有伴侣），
#   先输出人数，再按 ID 递增顺序输出其 ID（5 位数字，保留前导零）。
#
# 【实现原理】
#   1. 用哈希表记录每人的伴侣 ID。
#   2. 把到场客人存入哈希（集合），逐个判断其伴侣是否在场。
#   3. 伴侣不在场的客人即为落单者，按字符串排序（保持 5 位前导零）输出。
#
# 【输入样例】
#   3
#   11111 22222
#   33333 44444
#   55555 66666
#   7
#   55555 44444 10000 88888 22222 11111 23333
# 【输出样例】
#   5
#   10000 23333 44444 55555 88888
# =====================================================================

my $line = <STDIN>;
chomp $line;
my $n = $line + 0;

my %mate = ();
for (1 .. $n) {
    my $l = <STDIN>;
    chomp $l;
    my ($a, $b) = split /\s+/, $l;
    $mate{$a} = $b;
    $mate{$b} = $a;
}

# 剩余输入：M 以及 M 位客人的 ID
my @rest = split /\s+/, join('', <STDIN>);
shift @rest;   # 跳过 M

my %present = map { $_ => 1 } @rest;

my @single = ();
for my $x (@rest) {
    my $p = $mate{$x};
    # 无伴侣或伴侣未到场则为落单者
    push @single, $x if !defined($p) || !$present{$p};
}

print scalar(@single), "\n";
print join(' ', sort @single), "\n";