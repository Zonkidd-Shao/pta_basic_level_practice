// 1070 结绳
//
// 实现原理：
// 给定若干段绳子，每次将两段绳子打结连接，新绳子的长度为 (a+b)/2（向下取整）。
// 为使得最终绳子的长度最大，每次都应该选择当前最短的两段绳子进行连接。
// 这等价于：将绳子按长度升序排列，然后依次将最短的绳子与下一段合并。
//
// 数学推导：
// 设升序排列后的绳子长度为 a[0] ≤ a[1] ≤ ... ≤ a[n-1]，
// 最终长度 = (((a[0] + a[1])/2 + a[2])/2 + a[3])/2 + ...
// 由于每次除以 2 的操作，越早加入的绳子被缩放的次数越多，
// 所以应该让最短的绳子最早加入，这样损失的权重最小。
//
// 关键步骤：
// 1. 将所有绳子长度升序排序
// 2. 初始长度 len = a[0]
// 3. 从 i=1 到 n-1，依次合并：len = (len + a[i]) / 2
// 4. 输出最终长度（整数，向下取整）
//
// 复杂度分析：
// 时间复杂度：O(N logN)，主要开销在排序。
// 空间复杂度：O(N)，用于存储绳子长度。
#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

int main() {
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    sort(a.begin(), a.end());  // 升序排列，保证最短的绳子先合并

    // 贪心策略：每次合并最短的两根，使长度损失最小
    int len = a[0];
    for (int i = 1; i < n; ++i) len = (len + a[i]) / 2;  // 向下取整
    cout << len << endl;
    return 0;
}