/*
 * 题目：1076 WiFi密码
 * 实现原理：
 *   根据选择题选项推断WiFi密码。如果选项第三个字符是'T'，则该选项对应的序号即为密码的一位。
 *   规则：A=1, B=2, C=3, D=4
 *   算法步骤：
 *   1. 读取题目数量n
 *   2. 每组4个选项，检查每个选项的第三个字符
 *   3. 如果第三个字符是'T'，输出该选项对应的数字（A->1, B->2, C->3, D->4）
 */
#include <stdio.h>
#include <string.h>

int main() {
    int n;                  // 题目数量
    scanf("%d", &n);
    char s[20];             // 存放每个选项的字符串，如 "A-T"
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < 4; j++) {       // 每题固定4个选项
            scanf("%s", s);
            if (s[2] == 'T') {              // 第三个字符为'T'说明该选项是正确答案
                printf("%d", s[0] - 'A' + 1);   // 按 A=1, B=2, C=3, D=4 输出密码位
            }
        }
    }
    printf("\n");
    return 0;
}