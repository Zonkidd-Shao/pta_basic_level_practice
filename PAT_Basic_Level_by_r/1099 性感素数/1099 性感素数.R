# 题目名称：性感素数
# 题目编号：PAT Basic 1099
# 实现原理：
#   判断给定数N是否为性感素数（即N和N±6都是素数）。若是则输出Yes和配对的另一个素数（优先选小的）；
#   若不是则找出大于N的最小性感素数。
#   关键步骤：
#   1. 定义素数判断函数p(x)：试除法，检查2到sqrt(x)之间是否有因数
#   2. 首先判断N本身是否为素数，且N-6或N+6也是素数
#   3. 若是性感素数：优先输出N-6（较小的那个），否则输出N+6
#   4. 若不是：从N+1开始逐个递增查找，直到找到第一个性感素数
#   5. 输出No和找到的性感素数
#   试除法判断素数：若x能被2到sqrt(x)之间任意数整除则不是素数。
#   优先判断N-6是因为题目要求"若这样的数不唯一，输出较小的那个"。
# 时间复杂度：O(sqrt(N))，每次素数判断为O(sqrt(x))，查找次数取决于答案位置
# 空间复杂度：O(1)，仅使用常数额外空间
n<-as.integer(scan("stdin",quiet=TRUE)[1]);p<-function(x){x>1&&(x==2||!any(x%%2:floor(sqrt(x))==0))};if(p(n)&& (p(n-6)||p(n+6)))cat("Yes\n",if(p(n-6))n-6 else n+6,"\n") else {repeat{n<-n+1;if(p(n)&&(p(n-6)||p(n+6)))break};cat("No\n",n,"\n")}
