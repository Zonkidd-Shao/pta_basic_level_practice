use strict;
use warnings;

# =====================================================================
# 题目：1068 万绿丛中一点红
# 难度：中等
# 知识点：哈希表, 二维数组, 穷举
# =====================================================================
#
# 【题目描述】
#   在 M x N 的图像中找"万绿丛中一点红"：
#   颜色值独一无二，且与周围 8 个相邻像素的色差都超过 TOL。
#   输出格式为 (x, y): color；不唯一输出 Not Unique，不存在输出 Not Exist。
#
# 【实现原理】
#   1. 读入图像，用哈希统计每种颜色出现次数。
#   2. 遍历每个像素：先要求颜色唯一，再检查 8 邻域色差 > TOL。
#   3. 统计满足条件的像素个数并按要求输出。
#
# 【输入样例】
#   8 6 200
#   0 0 0 0 0 0 0 0
#   65280 65280 65280 16711479 65280 65280 65280 65280
#   16711479 65280 65280 65280 16711680 65280 65280 65280
#   65280 65280 65280 65280 65280 65280 165280 165280
#   65280 65280 16777015 65280 65280 165280 65480 165280
#   16777215 16777215 16777215 16777215 16777215 16777215 16777215 16777215
# 【输出样例】
#   (5, 3): 16711680
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
my $m   = shift @tok;   # 列数
my $n   = shift @tok;   # 行数
my $tol = shift @tok;   # 色差阈值

my @img;
my %cnt;
for my $i (0 .. $n-1) {
    for my $j (0 .. $m-1) {
        my $v = shift @tok;
        $img[$i][$j] = $v;
        $cnt{$v}++;
    }
}

my @ans;
for my $i (0 .. $n-1) {
    for my $j (0 .. $m-1) {
        my $x = $img[$i][$j];
        next unless $cnt{$x} == 1;   # 颜色必须独一无二
        my $ok = 1;
        for my $y ($i-1 .. $i+1) {
            next if $y < 0 || $y >= $n;
            for my $z ($j-1 .. $j+1) {
                next if $z < 0 || $z >= $m;
                next if $y == $i && $z == $j;   # 跳过自身
                if (abs($x - $img[$y][$z]) <= $tol) { $ok = 0; last; }
            }
            last unless $ok;
        }
        push @ans, [$j+1, $i+1, $x] if $ok;
    }
}

if (!@ans) {
    print "Not Exist\n";
} elsif (@ans > 1) {
    print "Not Unique\n";
} else {
    print "($ans[0][0], $ans[0][1]): $ans[0][2]\n";
}