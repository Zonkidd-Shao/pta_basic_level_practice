use strict;
use warnings;

# =====================================================================
# 题目：1101 B是A的多少倍
# 难度：简单
# 知识点：字符串处理, 模拟
# =====================================================================
#
# 【题目描述】
#   给定正整数 A 和位数 D，把 A 的最低 D 位截下放到最高位前面，
#   形成新数 B，求 B 是 A 的多少倍，输出小数点后 2 位。
#
# 【实现原理】
#   1. 用字符串切片取出最低 D 位 $last 和其余高位部分 $head。
#   2. 拼接成新数 B = $last . $head。
#   3. 用 printf 输出 B / A，保留 2 位小数。
#
# 【输入样例】
#   12345 2
# 【输出样例】
#   3.66
# =====================================================================

my $line = <STDIN>;
chomp $line;
my ($a, $d) = split / +/, $line;

# 最低 D 位
my $last = substr($a, -$d);
# 其余高位部分
my $head = substr($a, 0, length($a) - $d);
# 新数 B
my $b = $last . $head;

# 输出 B 是 A 的多少倍，保留 2 位小数
printf "%.2f\n", $b / $a;
