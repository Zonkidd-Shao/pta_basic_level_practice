use strict;
use warnings;

# =====================================================================
# 题目：1114 全素日
# 难度：简单
# 知识点：素数判断, 子串处理
# =====================================================================
#
# 【题目描述】
#   给定 YYYYMMDD 格式日期，从原串开始逐次去掉首位数字，得到一
#   系列子串。判断每个子串对应的数字是否为素数，并输出。若全部
#   为素数，则最后输出 All Prime!。
#
# 【实现原理】
#   1. 依次截取 s[i..末尾] 作为子串。
#   2. 用试除法判断子串对应数字是否为素数（0 和 1 均非素数）。
#   3. 记录是否全部为素数，全为素数则追加 All Prime!。
#
# 【输入样例】
#   20190523
# 【输出样例】
#   20190523 Yes
#   0190523 Yes
#   ...
#   All Prime!
# =====================================================================

# 素数判断函数
sub isprime {
    my $n = shift;
    return 0 if $n <= 1;
    for (my $i = 2; $i * $i <= $n; $i++) {
        return 0 if $n % $i == 0;
    }
    return 1;
}

# 读取日期字符串
my $s = <STDIN>;
chomp $s;

my $ok = 1;
# 从原串开始，逐次去掉首位
for (my $i = 0; $i < length($s); $i++) {
    my $x = substr($s, $i);
    my $q = isprime($x + 0);
    print "$x ", ($q ? 'Yes' : 'No'), "\n";
    $ok = 0 unless $q;
}

# 全为素数则输出
print "All Prime!\n" if $ok;
