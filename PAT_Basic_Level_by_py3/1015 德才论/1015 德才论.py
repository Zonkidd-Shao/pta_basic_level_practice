# 题目：1015 德才论
#
# 题目描述：
#   宋代史学家司马光在《资治通鉴》中有一段著名的“德才论”：“是故才德全尽谓之圣人，才德兼亡谓之愚人，德胜才谓之君子，才胜德谓之小人。凡取人之术，苟不得圣人，君子而与之，与其得小人，不若得愚人。”
#   现给出一批考生的德才分数，请根据司马光的理论给出录取排名。
#
# 输入格式：
#   输入第一行给出 3 个正整数，分别为：N（\le 10^5），即考生总数；L（\ge 60），为录取最低分数线，即德分和才分均不低于 L 的考生才有资格被考虑录取；H（< 100），为优先录取线——德分和才分均不低于此线的被定义为“才德全尽”，此类考生按德才总分从高到低排序；才分不到但德分到优先录取线的一类考生属于“德胜才”，也按总分排序，但排在第一类考生之后；德才分均低于 H，但是德分不低于才分的考生属于“才德兼亡”但尚有“德胜才”者，按总分排序，但排在第二类考生之后；其他达到最低线 L 的考生也按总分排序，但排在第三类考生之后。
#   随后 N 行，每行给出一位考生的信息，包括：`准考证号 德分 才分`，其中`准考证号`为 8 位整数，德才分为区间 [0, 100] 内的整数。数字间以空格分隔。
#
# 输出格式：
#   输出第一行首先给出达到最低分数线的考生人数 M，随后 M 行，每行按照输入格式输出一位考生的信息，考生按输入中说明的规则从高到低排序。当某类考生中有多人总分相同时，按其德分降序排列；若德分也并列，则按准考证号的升序输出。
#
# 实现原理：
#   - 排序算法
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   根据题目要求进行数据处理和计算，
#   使用适当的数据结构和算法提高效率。
#
import sys

n, low, high = map(int, sys.stdin.readline().split())
cats = [[] for _ in range(4)]
for _ in range(n):
    sid, de, cai = sys.stdin.readline().split(); de, cai = int(de), int(cai)
    if de < low or cai < low: continue
    k = 0 if de >= high and cai >= high else 1 if de >= high else 2 if de >= cai else 3
    cats[k].append((sid, de, cai))
ans = []
for cat in cats:
    ans += sorted(cat, key=lambda x: (-x[1]-x[2], -x[1], x[0]))
print(len(ans))
for x in ans: print(*x)
