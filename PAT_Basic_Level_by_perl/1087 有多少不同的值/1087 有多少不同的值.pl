use strict;
use warnings;

# =====================================================================
# 题目：1087 有多少不同的值
# 难度：简单
# 知识点：数学, 哈希表
# =====================================================================
#
# 【题目描述】
#   当自然数 n 依次取 1..N 时，算式 floor(n/2)+floor(n/3)+floor(n/5)
#   有多少个不同的值？
#
# 【实现原理】
#   1. 对每个 n 计算 floor(n/2)+floor(n/3)+floor(n/5)
#   2. 用哈希集合去重，统计不同值的个数
#   3. 输出集合大小
# =====================================================================
#
# 【输入样例】
#   2017
# 【输出样例】
#   1480
# =====================================================================

# 读取 N
my $n = <STDIN>;
chomp $n;

my %s;
# 对每个 n 计算算式值并去重
for my $i (1 .. $n) {
    $s{ int($i / 2) + int($i / 3) + int($i / 5) } = 1;
}

# 输出不同值的个数
print scalar(keys %s), "\n";
