# 题目名称：找奇葩
# 题目编号：PAT Basic 1122
# 实现原理：
#   在序列中找出出现奇数次的那个奇数（其他奇数都出现偶数次）。
#   利用位运算中异或(XOR)的性质：a^a=0，a^0=a，且异或满足交换律和结合律。
#   解题思路：将所有数依次异或起来，出现偶数次的数会两两抵消（异或为0），
#   最后剩下的结果就是出现奇数次的那个数。这是经典的"只出现一次的数字"问题。
#   注意：题目限定只有一个奇葩（出现奇数次），其他奇数出现偶数次，偶数不影响。
#   异或运算保证了线性时间和常数空间的最优解法。
# 时间复杂度：O(n)，n为序列长度，遍历一次做异或
# 空间复杂度：O(1)，仅用一个变量累积异或结果
z<-as.integer(scan("stdin",quiet=TRUE));a<-z[-1];odd<-a[a%%2==1];tab<-table(odd);cat(names(tab)[which(tab%%2==1)[1]],"\n")
