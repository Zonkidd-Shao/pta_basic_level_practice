use strict;
use warnings;

# =====================================================================
# 题目：1086 就不告诉你
# 难度：简单
# 知识点：字符串处理
# =====================================================================
#
# 【题目描述】
#   给定两个正整数 A 和 B，倒着输出 A 和 B 的乘积。
#   例如 5*7=35，倒着输出 53。
#
# 【实现原理】
#   1. 计算乘积 A*B
#   2. 将乘积转为字符串并反转
#   3. 去掉反转结果开头的 0；若结果为空则输出 0
# =====================================================================
#
# 【输入样例】
#   5 7
# 【输出样例】
#   53
# =====================================================================

# 读取 A 和 B
my @tok = split /\s+/, <STDIN>;
my $p = $tok[0] * $tok[1];

# 反转乘积的数字字符串
my $rev = reverse "$p";
# 去掉反转结果开头的 0（即去掉前导零）
$rev =~ s/^0+//;
# 若结果为空，输出 0
$rev = '0' if $rev eq '';

print "$rev\n";
