use strict;
use warnings;

# =====================================================================
# 题目：1024 科学计数法
# 难度：中等
# 知识点：字符串处理, 模拟
# =====================================================================
#
# 【题目描述】
#   将科学计数法形式的实数（如 +1.23400E-03）按普通数字表示法输出，
#   保留所有有效位，包括末尾的 0。
#
# 【实现原理】
#   1. 拆分出符号、尾数数字部分和指数 E。
#   2. 根据指数决定小数点位置，分三种情况输出：
#      指数使小数点前移（补 0）、后移（补 0）或位于数字中间。
#
# 【输入样例】
#   +1.23400E-03
# 【输出样例】
#   0.00123400
# =====================================================================

my $s = <STDIN>;
chomp $s;

my ($mantissa, $exp_str) = split /E/, $s;
my $sign = substr($s, 0, 1);          # 数字的正负号
my $exp  = $exp_str + 0;              # 转成整数

(my $digits = $mantissa) =~ s/\.//;   # 去掉小数点，得到纯数字串
$digits =~ s/^[+-]//;                 # 去掉符号

my $out = '';
if ($sign eq '-') { $out .= '-'; }

my $pos = 1 + $exp;                   # 小数点应放置的位置（0 开始计数）
if ($pos <= 0) {
    # 小数点前移，需在数字串前补 0
    $out .= '0.' . ('0' x -$pos) . $digits;
} elsif ($pos >= length($digits)) {
    # 小数点后移超出数字串，末尾补 0
    $out .= $digits . ('0' x ($pos - length($digits)));
} else {
    # 小数点落在数字串中间
    $out .= substr($digits, 0, $pos) . '.' . substr($digits, $pos);
}

print "$out\n";