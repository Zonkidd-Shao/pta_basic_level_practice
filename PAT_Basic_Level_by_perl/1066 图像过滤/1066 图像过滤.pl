use strict;
use warnings;

# =====================================================================
# 题目：1066 图像过滤
# 难度：简单
# 知识点：数组, 格式化输出
# =====================================================================
#
# 【题目描述】
#   把灰度值位于 [A, B] 区间内的像素替换为指定颜色值，
#   输出时每个灰度值占 3 位（不足补前导 0）。
#
# 【实现原理】
#   1. 读取分辨率 M、N、区间端点 A、B 及替换值。
#   2. 遍历每个像素，若 A <= 值 <= B 则替换。
#   3. 用 printf("%03d") 输出每个像素，保证占 3 位。
#
# 【输入样例】
#   3 5 100 150 0
#   3 189 254 101 119
#   150 233 151 99 100
#   88 123 149 0 255
# 【输出样例】
#   003 189 254 000 000
#   000 233 151 099 000
#   088 000 000 000 255
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
my $m   = shift @tok;   # 行数
my $n   = shift @tok;   # 列数
my $a   = shift @tok;   # 区间左端点
my $b   = shift @tok;   # 区间右端点
my $rep = shift @tok;   # 替换值

for my $i (1 .. $m) {
    my @row;
    for my $j (1 .. $n) {
        my $v = shift @tok;
        my $out = ($a <= $v && $v <= $b) ? $rep : $v;
        push @row, sprintf("%03d", $out);
    }
    print join(' ', @row), "\n";
}