/*
 * 题目：1027 打印沙漏
 * 实现原理：
 *   用给定字符打印沙漏形状，要求使用尽可能多的字符，但不超过n个。
 *   沙漏形状分析（以高度为3为例）：
 *     - 第1行：1个字符（居中）
 *     - 第2行：3个字符
 *     - 第3行：5个字符
 *     - 第2行：3个字符
 *     - 第1行：1个字符
 *   算法步骤：
 *   1. 计算最大层数i：满足1 + 2*(3+5+...+(2i-1)) <= n
 *   2. 从上到下打印上半部分（递减）
 *   3. 从下到上打印下半部分（递增）
 *   4. 输出剩余未使用的字符数
 */
#include <stdio.h>

int main() {
    int n;
    char c;
    scanf("%d %c", &n, &c);
    int i = 1, sum = 1;  // i：单侧层数（含中间一行）；sum：已累计使用的字符数
    while (sum + 2 * (2 * i + 1) <= n) {  // 再加一层（上下各 2i+1 个字符）后仍不超 n 则继续加层
        sum += 2 * (2 * i + 1);
        i++;
    }
    for (int j = i; j >= 1; j--) {  // 上半部分（含中间一行）：每层字符数 2j-1 递减
        for (int k = 0; k < i - j; k++) {  // 行首空格数 = i - j
            printf(" ");
        }
        for (int k = 0; k < 2 * j - 1; k++) {  // 打印本层字符
            printf("%c", c);
        }
        printf("\n");
    }
    for (int j = 2; j <= i; j++) {  // 下半部分：字符数递增（不含中间一行）
        for (int k = 0; k < i - j; k++) {
            printf(" ");
        }
        for (int k = 0; k < 2 * j - 1; k++) {
            printf("%c", c);
        }
        printf("\n");
    }
    printf("%d\n", n - sum);  // 输出剩余未使用的字符数
    return 0;
}