use strict;
use warnings;

# =====================================================================
# 题目：1016 部分A+B
# 难度：入门
# 知识点：字符串匹配、计数、字符串重复
# =====================================================================
#
# 【题目描述】
#   正整数 A 的"D_A 部分"定义为由 A 中所有 D_A 组成的新整数 P_A。
#   例如：A=3862767, D_A=6，则 P_A = 66（因为 A 中有 2 个 6）。
#   现给定 A、D_A、B、D_B，计算 P_A + P_B。
#
# 【实现原理】
#   1. 计数统计：
#      - 使用正则表达式 /$DA/g 全局匹配，统计数字 DA 在 A 中出现的次数
#      - Perl 中 () = $str =~ /pattern/g 的写法可以获取匹配次数
#        （列表上下文中返回所有匹配结果，赋值给空列表得到计数）
#   2. 构造 P_A 和 P_B：
#      - 若出现次数 ca > 0，则 P_A = DA 重复 ca 次组成的数字
#      - 若出现次数为 0，则 P_A = 0
#      - 使用字符串重复运算符 'x' 构造
#   3. 数值相加：
#      - Perl 自动将字符串转换为数值进行加法运算
#   4. 时间复杂度：O(len(A) + len(B))，即字符串长度。
#   5. 空间复杂度：O(1)。
#
# 【输入样例 1】 3862767 6 13530293 3
# 【输出样例 1】 399
#   解释：A 中有 2 个 6 → PA = 66；B 中有 3 个 3 → PB = 333；66 + 333 = 399
#
# 【输入样例 2】 3862767 1 13530293 8
# 【输出样例 2】 0
#   解释：A 中没有 1 → PA = 0；B 中没有 8 → PB = 0；0 + 0 = 0
# =====================================================================

# 读取一行：A DA B DB
my $line = <STDIN>;
chomp $line;
my ($A, $DA, $B, $DB) = split /\s+/, $line;

# 统计 DA 在 A 中出现的次数
# () =  在列表上下文中使用正则匹配，赋值给空列表得到匹配次数
my $ca = () = $A =~ /$DA/g;
# 统计 DB 在 B 中出现的次数
my $cb = () = $B =~ /$DB/g;

# 构造 P_A：若有 DA 则重复 ca 次，否则为 0
my $pa = $ca ? ($DA x $ca) : 0;
# 构造 P_B：若有 DB 则重复 cb 次，否则为 0
my $pb = $cb ? ($DB x $cb) : 0;

# 输出 P_A + P_B
print $pa + $pb, "\n";
