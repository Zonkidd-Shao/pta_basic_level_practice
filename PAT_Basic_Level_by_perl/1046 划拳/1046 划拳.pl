use strict;
use warnings;

# =====================================================================
# 题目：1046 划拳
# 难度：简单
# 知识点：简单模拟
# =====================================================================
#
# 【题目描述】
#   划拳时每人口中喊出一个数字，同时用手比划出一个数字。
#   若谁比划出的数字等于两人喊出数字之和，谁就赢，输家罚一杯酒。
#   若两人同赢或同输则不计。
#   给出 N 轮甲乙的记录，统计甲乙各喝了多少杯酒。
#
# 【实现原理】
#   1. 每轮读取：甲喊 a1、甲划 a2、乙喊 b1、乙划 b2。
#   2. 判断甲赢（a2 == a1+b1）与乙赢（b2 == a1+b1）。
#      - 只有一方赢时，输方喝酒（甲赢则乙喝，乙赢则甲喝）。
#   3. 累加甲乙喝酒杯数并输出。
#   4. 时间复杂度 O(N)，空间复杂度 O(1)。
#
# 【输入样例】
#   5
#   8 10 9 12
#   5 10 5 10
#   3 8 5 12
#   12 18 1 13
#   4 16 12 15
# 【输出样例】
#   1 2
# =====================================================================

# 读取轮数 N
my $n = <STDIN>;
chomp $n;

# a: 甲喝的杯数, b: 乙喝的杯数
my ($a, $b) = (0, 0);

for my $i (1 .. $n) {
    my $line = <STDIN>;
    chomp $line;
    # 甲喊 甲划 乙喊 乙划
    my ($a1, $a2, $b1, $b2) = split /\s+/, $line;

    # 喊出数字之和
    my $sum = $a1 + $b1;
    # 甲是否赢：甲划出数字 == 之和
    my $awin = ($a2 == $sum);
    # 乙是否赢：乙划出数字 == 之和
    my $bwin = ($b2 == $sum);

    # 仅一方赢时，输方喝酒
    if ($awin != $bwin) {
        $b++ if $awin;   # 甲赢，乙喝酒
        $a++ if $bwin;   # 乙赢，甲喝酒
    }
}

print "$a $b\n";
