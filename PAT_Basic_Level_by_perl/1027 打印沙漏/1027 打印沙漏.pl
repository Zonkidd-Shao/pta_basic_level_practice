use strict;
use warnings;

# =====================================================================
# 题目：1027 打印沙漏
# 难度：简单
# 知识点：模拟, 图形打印
# =====================================================================
#
# 【题目描述】
#   给定 N 个符号，打印出能使用尽可能多符号的最大沙漏，
#   沙漏共 2k-1 行，每行符号数从 2k-1 递减到 1 再递增，
#   最后输出剩余没用掉的符号数。
#
# 【实现原理】
#   1. 沙漏符号总数 = 2*k*k - 1，求满足 <= N 的最大 k。
#   2. 打印上半部分（从 k 行到 1 行）和下半部分（2 到 k 行）。
#   3. 输出 N - (2*k*k-1) 为剩余符号数。
#
# 【输入样例】
#   19 *
# 【输出样例】
#   *****
#    ***
#     *
#    ***
#   *****
#   2
# =====================================================================

my $line = <STDIN>;
chomp $line;
my ($n, $ch) = split / +/, $line;

# 求满足 2*k*k-1 <= N 的最大 k
my $k = 0;
$k++ while 2 * ($k + 1) * ($k + 1) - 1 <= $n;

# 上半部分：行号 i 从 k 递减到 1
for (my $i = $k; $i >= 1; $i--) {
    print ' ' x ($k - $i), $ch x (2 * $i - 1), "\n";
}
# 下半部分：行号 i 从 2 递增到 k
for (my $i = 2; $i <= $k; $i++) {
    print ' ' x ($k - $i), $ch x (2 * $i - 1), "\n";
}

print $n - (2 * $k * $k - 1), "\n";