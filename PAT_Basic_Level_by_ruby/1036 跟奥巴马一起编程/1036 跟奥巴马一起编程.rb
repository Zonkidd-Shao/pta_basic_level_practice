#
# 题目描述：
#   美国总统奥巴马不仅呼吁所有人都学习编程，甚至以身作则编写代码，成为美国历史上首位编写计算机代码的总统。2014 年底，为庆祝“计算机科学教育周”正式启动，奥巴马编写了很简单的计算机代码：在屏幕上画一个正方形。现在你也跟他一起画吧！
#
# 实现原理：
#   根据字符数和行数计算列数；按行列格式输出字符图案；处理四舍五入的列数计算
#

if __FILE__ == $PROGRAM_NAME
  n, c = gets.split
  n = n.to_i
  rows = (n + 1) / 2

  rows.times do |i|
    if i.zero? || i == rows - 1
      puts c * n
    else
      puts c + ' ' * (n - 2) + c
    end
  end
end
