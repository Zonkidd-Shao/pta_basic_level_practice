# 题目名称：胖达与盆盆奶
# 题目编号：PAT Basic 1119
# 实现原理：
#   一排胖达按体重分配盆盆奶，规则：更胖的奶更多，等胖的奶一样多；
#   每只最少200毫升；体重多出至少才能感觉"更多"（即差需≥某阈值才需要更多）。
#   求最少准备多少奶。这是经典的"分糖果"问题变种。
#   解题思路：1. 用两个数组l和r，l[i]表示从左往右看第i只胖达需要的"级别"；
#   2. 从左到右遍历：若当前比左边胖，则l[i]=l[i-1]+1，否则l[i]=1；
#   3. 从右到左遍历：若当前比右边胖，则r[i]=r[i+1]+1，否则r[i]=1；
#   4. 每只胖达的级别取max(l[i],r[i])，乘以200毫升就是奶量；
#   5. 所有奶量求和即为答案。
#   核心思想：两遍贪心，分别满足左右两边的约束。
# 时间复杂度：O(n)，n为胖达个数，两遍线性扫描
# 空间复杂度：O(n)，存储l和r两个数组
z<-as.integer(scan("stdin",quiet=TRUE));a<-z[-1];n<-length(a);l<-rep(1L,n);r<-rep(1L,n);if(n>1){for(i in 2:n)if(a[i]>a[i-1])l[i]<-l[i-1]+1L;for(i in (n-1):1)if(a[i]>a[i+1])r[i]<-r[i+1]+1L};cat(100L*sum(pmax(l,r)+1L),"\n")
