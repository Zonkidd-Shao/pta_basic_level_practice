use strict;
use warnings;

# =====================================================================
# 题目：1091 N-自守数
# 难度：简单
# 知识点：数学, 字符串处理
# =====================================================================
#
# 【题目描述】
#   若 N*K^2 的末尾几位数恰好等于 K，则 K 是 N-自守数。
#   对每个待检测数 K，找出最小的 N (1<=N<10) 使 K 为 N-自守数，
#   输出最小的 N 及 N*K^2；否则输出 No。
#
# 【实现原理】
#   1. 对每个 K，从 1 到 9 枚举 N
#   2. 计算 N*K^2，用字符串判断是否以 K 的十进制结尾
#   3. 找到最小的 N 即输出，否则输出 No
# =====================================================================
#
# 【输入样例】
#   3
#   92 5 233
# 【输出样例】
#   3 25392
#   1 25
#   No
# =====================================================================

# 一次性读取全部输入
my @tok = split /\s+/, join('', <STDIN>);
my $m = shift @tok;   # 待检测数字个数

# 处理每个待检测数字
for my $x (@tok) {
    my $found = 0;
    # 从小到大枚举 N（1..9）
    for my $k (1 .. 9) {
        my $val = $x * $x * $k;
        # 判断 N*K^2 的末尾是否等于 K
        if ("$val" =~ /$x$/) {
            print "$k $val\n";
            $found = 1;
            last;
        }
    }
    # 未找到合适的 N，输出 No
    print "No\n" unless $found;
}
