# 题目名称：就不告诉你
# 题目编号：PAT Basic 1086
# 实现原理：
#   计算两个数的乘积，然后将乘积的数字倒序输出，并去掉前导零。
#   关键步骤：
#   1. 读取两个正整数A和B
#   2. 计算乘积 A * B
#   3. 将乘积转为字符串并拆分为单个字符
#   4. 用 rev 函数反转字符顺序
#   5. 重新拼接成字符串
#   6. 用正则表达式 sub("^0+", "", s) 去掉前导零
#   7. 输出结果
#   注意：如果乘积末尾有0，反转后会变成前导零，需要去除。
# 时间复杂度：O(D)，其中D为乘积的数字位数
# 空间复杂度：O(D)，存储乘积的字符串表示
z<-as.integer(scan("stdin",quiet=TRUE));s<-paste0(rev(strsplit(as.character(z[1]*z[2]),"")[[1]]),collapse="");cat(sub("^0+","",s),"\n")
