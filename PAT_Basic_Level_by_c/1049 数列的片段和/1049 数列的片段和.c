/*
 * 题目：1049 数列的片段和
 * 实现原理：
 *   计算数列所有连续子序列的和。
 *   数学分析：第i个元素（1-based）在多少个子序列中出现？
 *   - 作为子序列第一个元素：有(N-i+1)种选择
 *   - 子序列起始位置可以是1~i：有i种选择
 *   - 所以第i个元素出现次数 = i * (N-i+1)
 *   算法步骤：
 *   1. 遍历每个元素，累加 num[i] * i * (N-i+1)
 *   2. 输出结果（保留两位小数）
 *   时间复杂度：O(n)
 */
#include <stdio.h>

int main() {
    int N;
    scanf("%d", &N);
    
    double sum = 0.0;  // 所有片段和的总和
    for (int i = 1; i <= N; i++) {  // i 为当前元素在数列中的位置（从 1 开始）
        double num;
        scanf("%lf", &num);
        sum += num * i * (N - i + 1);  // 第 i 个元素在所有片段中出现 i*(N-i+1) 次
    }
    
    printf("%.2lf\n", sum);  // 输出保留两位小数
    
    return 0;
}