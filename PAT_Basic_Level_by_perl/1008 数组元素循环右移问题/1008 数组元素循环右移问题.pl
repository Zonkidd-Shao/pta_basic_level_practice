use strict;
use warnings;

# =====================================================================
# 题目：1008 数组元素循环右移问题
# 难度：简单
# 知识点：数组操作、循环移位、模运算
# =====================================================================
#
# 【题目描述】
#   给定 N 个整数的数组 A，将数组循环向右移 M 个位置后输出。
#   即 A = (A_0 A_1 ... A_{N-1}) 变换为
#   (A_{N-M} ... A_{N-1} A_0 A_1 ... A_{N-M-1})。
#   注意 M 可能大于 N。
#
# 【实现原理】
#   1. 模运算优化移动位数：
#      - 循环右移 N 位等价于不移位（回到原位）
#      - 因此实际有效移动位数为 m = M % N
#      - 这一步避免了 M > N 时的冗余操作
#   2. 数组切片法：
#      - 循环右移 m 位的效果是：末尾 m 个元素移到数组最前面
#      - 利用数组切片操作，将数组分为两部分：
#        后 m 个元素 [n-m .. n-1] 和前 n-m 个元素 [0 .. n-m-1]
#      - 将两部分按"后段 + 前段"的顺序拼接，即得到右移后的数组
#   3. 边界情况：
#      - 当 m == 0 时（M 是 N 的倍数），数组不需要移动
#      - 当 n == 0 时（空数组），直接输出空
#   4. 时间复杂度：O(N)，数组切片和拼接操作都是线性时间。
#   5. 空间复杂度：O(N)，需要额外空间存储新数组。
#      （题目要求不允许使用另外数组时，可采用三次翻转法实现 O(1) 空间）
#
# 【输入样例】
#   6 2
#   1 2 3 4 5 6
# 【输出样例】
#   5 6 1 2 3 4
#   过程：后 2 个元素 [5, 6] 移到前面，前 4 个 [1, 2, 3, 4] 接在后面
# =====================================================================

# 读取第一行：N（数组长度）和 M（右移位数）
my $line = <STDIN>;
chomp $line;
my ($n, $m) = split /\s+/, $line;
# 读取第二行的 n 个整数
my @a = split /\s+/, join(' ', <STDIN>);

# 处理非空数组
if ($n > 0) {
    # 用模运算得到有效移动位数
    # 循环右移 n 位等价于不动，因此 m 对 n 取模
    $m %= $n;
    # 若 m != 0，执行循环右移
    # 数组切片：后 m 个元素 + 前 n-m 个元素
    if ($m) {
        @a = (@a[$n - $m .. $n - 1], @a[0 .. $n - $m - 1]);
    }
}

# 输出结果，空格分隔
print join(' ', @a), "\n";
