use strict;
use warnings;

# =====================================================================
# 题目：1118 如需挪车请致电
# 难度：简单
# 知识点：字符串解析, 正则匹配, 模拟计算
# =====================================================================
#
# 【题目描述】
#   给出 11 行计算式，每行计算出一个一位数字，将它们依次拼接成
#   电话号码。支持 + - * / % sqrt ^ 及 0-9 的汉语拼音。
#
# 【实现原理】
#   1. 用哈希表把汉语拼音映射为数字。
#   2. 若以 sqrt 开头则开平方（向下取整）。
#   3. 否则用正则解析 数 运算符 数 并计算结果。
#   4. 将所有一位结果拼接输出。
#
# 【输入样例】
#   2/2
#   3+2
#   ...
# 【输出样例】
#   15330333384
# =====================================================================

# 汉语拼音 -> 数字
my %words = (
    ling => 0, yi => 1,  er => 2,  san => 3, si => 4,
    wu => 5,  liu => 6,  qi => 7,  ba => 8,  jiu => 9,
);

my @out;

while (my $s = <STDIN>) {
    chomp $s;
    next if $s eq '';
    my $v;

    if (exists $words{$s}) {
        # 汉字拼音
        $v = $words{$s};
    }
    elsif ($s =~ /^sqrt(\d+)$/) {
        # 开平方
        $v = int(sqrt($1));
    }
    elsif ($s =~ /^(\d+)([+\-*\/%^])(\d+)$/) {
        # 普通运算
        my ($aa, $op, $bb) = ($1, $2, $3);
        if    ($op eq '+') { $v = $aa + $bb; }
        elsif ($op eq '-') { $v = $aa - $bb; }
        elsif ($op eq '*') { $v = $aa * $bb; }
        elsif ($op eq '/') { $v = int($aa / $bb); }
        elsif ($op eq '%') { $v = $aa % $bb; }
        elsif ($op eq '^') { $v = $aa ** $bb; }
    }
    push @out, $v;
}

# 拼接输出电话号码
print join('', @out), "\n";
