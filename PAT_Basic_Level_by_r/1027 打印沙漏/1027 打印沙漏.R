# 题目名称：打印沙漏
# 题目编号：PAT Basic 1027
# 实现原理：
#   1. 读取给定的字符总数n和要打印的字符ch
#   2. 计算沙漏上半部分（含中间一行）的行数k：
#      - 沙漏总字符数公式：2*k*k + 4*k + 1 = 2*(k+1)^2 - 1
#      - 解方程得 k = floor((sqrt(2*n-1)-1)/2)
#   3. 打印沙漏的上半部分（从k行到0行，每行字符递减）
#   4. 打印沙漏的下半部分（从1行到k行，每行字符递增）
#   5. 每行前面有k-i个空格，后面有2*i+1个字符
#   6. 最后输出剩余的字符数
# 时间复杂度：O(k^2) = O(n)，需要打印约sqrt(n)行，每行字符数也约为sqrt(n)
# 空间复杂度：O(1)，只使用固定数量的变量
z<-scan("stdin",what="",quiet=TRUE);n<-as.integer(z[1]);ch<-z[2];k<-floor((sqrt(2*n-1)-1)/2);for(i in c(k:0,1:k))cat(strrep(" ",k-i),strrep(ch,2*i+1),"\n",sep="");cat(n-(2*k*k+4*k+1),"\n")
