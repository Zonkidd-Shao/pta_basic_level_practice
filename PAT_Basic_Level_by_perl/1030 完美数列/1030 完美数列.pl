use strict;
use warnings;

# =====================================================================
# 题目：1030 完美数列
# 难度：中等
# 知识点：排序, 双指针, 滑动窗口
# =====================================================================
#
# 【题目描述】
#   给定正整数数列和参数 p，数列中最大值 M、最小值 m 满足 M <= m*p，
#   则称该数列为完美数列。从给定正整数中挑选尽可能多的数构成完美数列，
#   输出最多能选择的个数。
#
# 【实现原理】
#   1. 排序：将数列升序排序，使最小值在左、最大值在右。
#   2. 双指针/滑动窗口：维护左指针 i，对每个右指针 j，
#      若 a[j] > a[i]*p 则向右移动 i，窗口 [i, j] 始终满足完美数列条件，
#      记录并更新最大窗口长度。
#   3. 时间复杂度：O(N log N)（排序主导）。
#
# 【输入样例】
#   10 8
#   2 3 20 4 5 1 6 7 8 9
# 【输出样例】
#   8
# =====================================================================

# 读取第一行：N 和参数 p
my $line = <STDIN>;
chomp $line;
my ($n, $p) = split /\s+/, $line;

# 读取第二行并升序排序
my @arr = sort { $a <=> $b } split /\s+/, <STDIN>;

my $best = 0;   # 最长完美子序列长度
my $i = 0;      # 左指针

# 遍历每个右端点 j
for (my $j = 0; $j < @arr; $j++) {
    # 当前最小值 a[i] 乘以 p 小于最大值 a[j] 时，左指针右移
    while ($arr[$i] * $p < $arr[$j]) {
        $i++;
    }
    # 更新最长窗口长度
    my $len = $j - $i + 1;
    $best = $len if $len > $best;
}

print "$best\n";