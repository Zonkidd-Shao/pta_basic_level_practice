/*
 * 1101 B是A的多少倍
 *
 * 【实现原理】
 * 题目要求：给定两个正整数 A 和 B，计算 B 是 A 的百分之多少，即 (B / A) × 100，
 * 结果保留两位小数并在末尾输出百分号。
 *
 * 【算法思路】
 * 1. 读入两个浮点数 A 和 B。
 * 2. 计算 B / A * 100，使用 printf 格式化输出，保留两位小数，并在末尾添加 "%" 符号。
 * 3. 如果输入无效则直接返回。
 *
 * 【复杂度分析】
 * - 时间复杂度：O(1)，仅执行常数次运算。
 * - 空间复杂度：O(1)，仅使用常数个变量。
 */
#include <iostream>
#include <cstdio>

using namespace std;

int main() {
    double a, b;
    if (!(cin >> a >> b)) return 0;              // 读入 A 和 B，若失败则退出
    printf("B is %.2f%% of A.\n", b / a * 100.0); // 计算并输出百分比，保留两位小数
    return 0;
}