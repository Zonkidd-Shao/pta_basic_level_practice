# 题目名称：三人行
# 题目编号：PAT Basic 1088
# 实现原理：
#   枚举所有两位数的甲（从99到10，取最大解），根据题目条件验证是否满足关系，找到后比较三人能力值与你的能力值。
#   关键步骤：
#   1. 读取M（你的能力值）、X、Y三个参数
#   2. 从99到10倒序枚举甲的能力值（保证找到的第一个就是最大解）
#   3. 将甲的十位和个位互换得到乙的能力值
#   4. 验证条件：|甲-乙| / X = 乙 / Y，即 |甲-乙| * Y == 乙 * X？（或根据题意的比例关系）
#   5. 找到符合条件的甲后，计算丙的能力值
#   6. 分别比较甲、乙、丙与你的能力值，输出Cong/Ping/Gai
#   倒序枚举保证第一个找到的就是甲的最大解。
# 时间复杂度：O(1)，甲的范围固定为10-99，共90种可能
# 空间复杂度：O(1)，仅使用常数额外空间
z<-as.numeric(scan("stdin",quiet=TRUE));for(i in 99:10){a<-floor(i/10);b<-i%%10;if(a==b)next;if(abs((10*a+b)-(10*b+a))*z[2]==z[1]){cat(i," ",sprintf("%.2f",(10*b+a)/z[1]),"\n",sep="")}}
