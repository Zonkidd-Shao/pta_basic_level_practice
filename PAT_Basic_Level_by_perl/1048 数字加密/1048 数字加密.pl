use strict;
use warnings;

# =====================================================================
# 题目：1048 数字加密
# 难度：简单
# 知识点：字符串处理, 模拟
# =====================================================================
#
# 【题目描述】
#   给定加密用正整数 A 和任意正整数 B，将 B 的每一位与 A 对应位置的数字进行运算：
#   奇数位为两数相加后对 13 取余（10/11/12 分别用 J/Q/K 表示）；偶数位为 B 减 A，
#   若为负则加 10。个位为第 1 位。输出加密结果。
#
# 【实现原理】
#   1. 将 A、B 前面补零至相同长度（长度取两者较大者）。
#   2. 从左到右按位处理，第 i 位视为位置 i（i 从 1 开始）。
#   3. 奇数位按"加和取余13"处理，偶数位按"B-A，不足加10"处理。
#   4. 去掉结果前导零后输出；若全为 0 则输出 0。
#
# 【输入样例】
#   1234567 368782971
# 【输出样例】
#   3695Q8118
# =====================================================================

my @tok = split /\s+/, <STDIN>;   # 读取 A 和 B
my $a = $tok[0];
my $b = $tok[1];

my $len = length($a) > length($b) ? length($a) : length($b);
$a = ('0' x ($len - length($a))) . $a;  # 前面补零
$b = ('0' x ($len - length($b))) . $b;

my @chars = ('0'..'9', 'J', 'Q', 'K');  # 13 取余后 10/11/12 对应 J/Q/K
my $out = '';
for (my $i = 0; $i < $len; $i++) {
    my $pos = $i + 1;                 # 从右端个位开始编号
    my $idx = $len - 1 - $i;
    my $x = substr($a, $idx, 1);
    my $y = substr($b, $idx, 1);
    my $digit;
    if ($pos % 2 == 1) {              # 奇数位：相加后对 13 取余
        my $z = ($x + $y) % 13;
        $digit = $chars[$z];
    } else {                          # 偶数位：B - A，负数加 10
        my $z = $y - $x;
        $z += 10 if $z < 0;
        $digit = $z;
    }
    $out = $digit . $out;
}
print "$out\n";                      # 保留结果的完整位数，包括前导 0
