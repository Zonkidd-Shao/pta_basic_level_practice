use strict;
use warnings;

# =====================================================================
# 题目：1122 找奇葩
# 难度：简单
# 知识点：哈希表, 计数
# =====================================================================
#
# 【题目描述】
#   一个正整数序列中，所有奇数都出现了偶数次，
#   只有一个"奇葩"奇数出现了奇数次。找出这个奇葩。
#
# 【实现原理】
#   1. 用哈希表统计每个数字出现的次数。
#   2. 遍历哈希表，输出出现次数为奇数的那个数字。
#
# 【输入样例】
#   12
#   23 16 87 233 87 16 87 233 23 87 233 16
# 【输出样例】
#   233
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);

# 跳过第一行的 n（个数），统计其余数字的出现次数
my %cnt;
for my $idx (1 .. $#tok) {
    $cnt{ $tok[$idx] }++;
}

# 找出出现次数为奇数的数字并输出
for my $num (keys %cnt) {
    if ($num % 2 == 1 && $cnt{$num} % 2 == 1) {
        print $num, "\n";
        last;
    }
}
