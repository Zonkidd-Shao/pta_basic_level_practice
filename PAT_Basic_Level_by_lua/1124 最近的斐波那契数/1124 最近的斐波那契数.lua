-- 题目编号: 1124 最近的斐波那契数
-- 实现原理: 从a=0,b=1开始迭代生成斐波那契数列，直到b≥n，比较n与前后两个斐波那契数的距离，输出距离较近的那个。

local n = tonumber(io.read())  -- 读取输入的数n
local a, b = 0, 1               -- 斐波那契数列的相邻两项，初始为F(0)=0, F(1)=1

-- 迭代生成斐波那契数列，直到b >= n
while b < n do
    a, b = b, a + b  -- 移动到下一对相邻的斐波那契数
end

-- 比较n与前后两个斐波那契数的距离
-- a是小于等于n的最大斐波那契数，b是大于等于n的最小斐波那契数
-- 距离相等时输出较小的那个（题目默认规则）
if n - a <= b - n then
    print(a)
else
    print(b)
end
