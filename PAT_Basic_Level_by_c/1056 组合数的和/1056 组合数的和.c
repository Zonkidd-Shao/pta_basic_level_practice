/*
 * 题目：1056 组合数的和
 * 实现原理：
 *   给定N个数字，求所有可能的2位数组合的和。
 *   数学分析：每个数字出现的次数
 *   - 在十位上：每个数字可以与其余N-1个数字组合，出现N-1次
 *   - 在个位上：每个数字可以与其余N-1个数字组合，出现N-1次
 *   - 每个数字的贡献 = num * 11 * (N-1)
 *   算法步骤：
 *   1. 读取所有数字并求和sum
 *   2. 结果 = sum * 11 * (N-1)
 *   时间复杂度：O(n)
 */
#include <stdio.h>

int main() {
    int N, sum = 0, temp;  // sum: 所有给定数字之和; temp: 当前读入的数字
    scanf("%d", &N);
    for (int i = 0; i < N; i++) {  // 读入 N 个数字并求和
        scanf("%d", &temp);
        sum += temp;
    }
    printf("%d\n", sum * 11 * (N - 1));  // 每个数字在十位、个位各出现 N-1 次，贡献 num*11*(N-1)
    return 0;
}