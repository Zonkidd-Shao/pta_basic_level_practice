// 1023 组个最小数
// 给定数字 0~9 的个数，必须用完全部数字组成尽可能小的数（0 不能作首位）。
//
// 【实现原理】
// 算法思路：
//   1. 读入 0~9 每个数字的可用个数。
//   2. 为了组成最小数，首位必须取最小的非零数字（因为 0 不能作首位）。
//   3. 将选中的首位数字的可用个数减 1。
//   4. 剩余数字按升序输出（0 在最前面，然后 1, 2, ...），即可得到最小数。
// 关键点：
//   - 首位不能是 0，因此先从 1~9 中选最小的可用数字。
//   - 选完首位后，将所有剩余数字（包括 0）按升序输出，即可保证整体最小。
// 时间复杂度：O(Σcnt[i])，即所有数字的总个数。
// 空间复杂度：O(1)。
#include <iostream>

using namespace std;

int main() {
    int cnt[10];
    for (int i = 0; i < 10; ++i) cin >> cnt[i];

    // 首位取最小的非零数字
    int first = -1;
    for (int i = 1; i < 10; ++i) {
        if (cnt[i] > 0) { first = i; break; }
    }
    --cnt[first];

    cout << first;
    // 其余数字按升序输出（0 在前），即得最小数
    for (int i = 0; i < 10; ++i) {
        while (cnt[i] > 0) { cout << i; --cnt[i]; }
    }
    cout << endl;
    return 0;
}