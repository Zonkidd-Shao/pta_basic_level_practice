use strict;
use warnings;

# =====================================================================
# 题目：1110 区块反转
# 难度：中等
# 知识点：链表, 哈希表, 数组切片反转
# =====================================================================
#
# 【题目描述】
#   给定一个单链表 L，将每 K 个结点看成一个区块（最后不足 K 个结点
#   也看成一个区块），然后将所有区块的链接反转后输出整个链表。
#
# 【实现原理】
#   1. 用哈希表以地址为键存储 (数据, 下一地址)。
#   2. 从首地址出发按 Next 链收集结点地址到数组，得到链接顺序。
#   3. 将每 K 个结点看成一个区块，反转各区块之间的顺序
#      （区块内部顺序保持不变），再按新顺序输出。
#
# 【输入样例】
#   00100 8 3
#   71120 7 88666
#   ...
# 【输出样例】
#   71120 7 88666
#   88666 8 00000
#   ...
# =====================================================================

# 读取第一行：首地址、结点总数、区块大小
my $line = <STDIN>;
chomp $line;
my ($h, $n, $k) = split /\s+/, $line;

# 用哈希表存储每个结点：地址 => [数据, 下一地址]
my %d;
for (1 .. $n) {
    my $l = <STDIN>;
    chomp $l;
    my ($addr, $data, $next) = split /\s+/, $l;
    $d{$addr} = [$data, $next];
}

# 按 Next 链收集结点地址，得到链接顺序
my @a;
while ($h ne '-1') {
    push @a, $h;
    $h = $d{$h}[1];
}

# 将每 K 个结点作为一个区块，反转区块之间的顺序（区块内部不变）
my @new_a;
for (my $i = 0; $i < @a; $i += $k) {
    my $end = $i + $k;
    $end = @a if $end > @a;
    unshift @new_a, @a[$i .. $end - 1];
}
@a = @new_a;

# 按新顺序输出每个结点
for (my $i = 0; $i < @a; $i++) {
    my $next = ($i + 1 < @a) ? $a[$i + 1] : '-1';
    print "$a[$i] $d{$a[$i]}[0] $next\n";
}
