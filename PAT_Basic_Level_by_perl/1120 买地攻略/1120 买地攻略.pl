use strict;
use warnings;

# =====================================================================
# 题目：1120 买地攻略
# 难度：中等
# 知识点：滑动窗口, 前缀和
# =====================================================================
#
# 【题目描述】
#   一块块土地连续编号，各有标价。客户可以购买多块连续相邻的土地，
#   给定客户手中的现金量 M，统计有多少种不同的购买方案，
#   即有多少个连续子段的和不超过 M。
#
# 【实现原理】
#   1. 维护滑动窗口 [i, j]，使窗口内土地总价 s 不超过 M。
#   2. 若 s 超过 M，则从左端不断移出土地，直到 s <= M。
#   3. 以 j 结尾且满足条件的方案数为 j-i+1，累加到答案。
#
# 【输入样例】
#   5 85
#   38 42 15 24 9
# 【输出样例】
#   11
# =====================================================================

my $line = <STDIN>;
chomp $line;
my ($n, $m) = split /\s+/, $line;

my @a = split /\s+/, <STDIN>;

my ($ans, $i, $s) = (0, 0, 0);

# 枚举右端点 j，维护窗口左端点 i，保证窗口内和不超过 M
for (my $j = 0; $j < $n; $j++) {
    $s += $a[$j];
    while ($s > $m) {
        $s -= $a[$i];
        $i++;
    }
    $ans += $j - $i + 1;
}

print $ans, "\n";
