/*
 * 1049 数列的片段和
 *
 * 【实现原理】
 * 给定一个正数数列，求所有连续子段（子序列片段）的元素之和。
 * 每个片段是指原数列中连续的一段（长度 >= 1）。
 *
 * 【数学推导】
 * 对于数列第 i 个元素 a[i]（0-based 索引），它出现在多少个连续子段中？
 * - 子段的左端点可以选择的位置：0, 1, 2, ..., i（共 i+1 种选择）
 * - 子段的右端点可以选择的位置：i, i+1, ..., N-1（共 N-i 种选择）
 * - 因此 a[i] 出现在 (i+1) * (N-i) 个连续子段中
 * - 总和 = Σ a[i] * (i+1) * (N-i)
 *
 * 【算法思路】
 * 直接使用推导公式计算，避免枚举所有子段（O(N^2) 在 N 很大时不可行）
 *
 * 【关键点】
 * - 核心是推导出每个元素被包含的次数公式 (i+1)*(N-i)
 * - 使用 double 类型避免精度损失
 * - 由于 N 最大可达 10^5，直接枚举所有子段会超时，需使用公式 O(N)
 *
 * 【复杂度分析】
 * - 时间复杂度：O(N)，一次线性遍历
 * - 空间复杂度：O(N)，存储数列（也可边读边算优化到 O(1)）
 */

#include <iostream>
#include <vector>
#include <cstdio>

using namespace std;

int main() {
    int n;
    if (!(cin >> n)) return 0;
    vector<double> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];

    double sum = 0.0;
    for (int i = 0; i < n; ++i) {
        // a[i] 出现在 (i+1) * (n-i) 个连续子段中
        // 计算其贡献并累加
        sum += a[i] * (i + 1) * (n - i);
    }

    printf("%.2f\n", sum);  // 保留两位小数输出
    return 0;
}