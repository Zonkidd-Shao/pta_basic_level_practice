// 1021 个位数统计
// 统计一个不超过 1000 位的正整数中每种个位数字出现的次数，按数字升序输出 D:M。
//
// 【实现原理】
// 算法思路：
//   1. 以字符串形式读入大整数（最多 1000 位，远超内置整数范围）。
//   2. 使用长度为 10 的数组 cnt[10] 统计每个数字（0~9）出现的次数。
//   3. 遍历字符串，对每个字符 c，将 cnt[c - '0'] 加 1。
//   4. 遍历 cnt 数组，输出出现次数大于 0 的数字及其频次。
// 关键点：
//   - 数字可能很大，必须用字符串读入。
//   - 输出格式为 "D:M"，每行一个数字，按数字升序输出。
// 时间复杂度：O(L)，其中 L 为数字的位数。
// 空间复杂度：O(1)，仅使用固定大小的数组。
#include <iostream>
#include <string>

using namespace std;

int main() {
    string s;
    if (!(cin >> s)) return 0;

    int cnt[10] = {0};
    for (char c : s) ++cnt[c - '0'];

    for (int i = 0; i < 10; ++i) {
        if (cnt[i] > 0) cout << i << ':' << cnt[i] << endl;
    }
    return 0;
}