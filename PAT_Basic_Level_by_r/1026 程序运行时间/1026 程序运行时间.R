# 题目名称：程序运行时间
# 题目编号：PAT Basic 1026
# 实现原理：
#   1. 读取两个时钟打点数C1和C2
#   2. 计算时间差（C2 - C1），除以CLK_TCK（100）得到秒数
#   3. 使用floor(x + 0.5)实现四舍五入到整数秒
#   4. 将总秒数转换为时:分:秒格式：
#      - 小时 = 总秒数 / 3600
#      - 分钟 = (总秒数 % 3600) / 60
#      - 秒 = 总秒数 % 60
#   5. 使用sprintf格式化输出，确保每位都是2位数字
# 时间复杂度：O(1)，只需要常量时间的算术运算
# 空间复杂度：O(1)，只使用固定数量的变量
z<-as.numeric(scan("stdin",quiet=TRUE));t<-floor((z[2]-z[1])/100+0.5);cat(sprintf("%02d:%02d:%02d\n",t%/%3600,(t%%3600)%/%60,t%%60))
