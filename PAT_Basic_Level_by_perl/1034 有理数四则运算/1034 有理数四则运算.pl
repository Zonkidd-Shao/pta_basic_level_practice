use strict;
use warnings;

# =====================================================================
# 题目：1034 有理数四则运算
# 难度：较难
# 知识点：最大公约数, 分数运算, 格式化输出
# =====================================================================
#
# 【题目描述】
#   计算两个有理数（分数形式 a/b）的和、差、积、商，每行按
#   “有理数1 运算符 有理数2 = 结果” 输出。每个有理数须为最简形式
#   "k a/b"，负数的整体加括号；除法分母为 0 时结果输出 Inf。
#
# 【实现原理】
#   1. 约分：用辗转相除法求最大公约数，约分并保证分母为正、符号放分子。
#   2. 四则运算：利用分数运算法则（通分、相乘、颠倒相乘）计算，结果约分。
#   3. 格式化：拆出整数部分 k 和余数部分 r/d，按是否有整数部分拼装；
#      负数整体用括号包裹；除数为 0 时输出 Inf。
#
# 【输入样例】
#   2/3 -4/2
# 【输出样例】
#   2/3 + (-2) = (-1 1/3)
#   2/3 - (-2) = 2 2/3
#   2/3 * (-2) = (-1 1/3)
#   2/3 / (-2) = (-1/3)
# =====================================================================

# 最大公约数（辗转相除法）
sub gcd {
    my ($a, $b) = @_;
    $a = abs $a;
    $b = abs $b;
    ($a, $b) = ($b, $a % $b) while $b;
    return $a;
}

# 标准化分数：约分，分母为正，符号放到分子；分母 0 表示无穷
sub norm {
    my ($n, $d) = @_;
    return ($n, 0) if $d == 0;
    if ($d < 0) {
        $n = -$n;
        $d = -$d;
    }
    my $g = gcd($n, $d);
    return ($n / $g, $d / $g);
}

# 格式化有理数为 "k a/b" 形式，负数加括号
sub fmt {
    my ($n, $d) = @_;
    return 'Inf' if $d == 0;

    my $neg = $n < 0;
    $n = abs $n;

    my $k = int($n / $d);   # 整数部分
    my $r = $n % $d;        # 余数
    my $s;
    if ($r == 0) {
        $s = "$k";
    }
    elsif ($k == 0) {
        $s = "$r/$d";
    }
    else {
        $s = "$k $r/$d";
    }
    return $neg ? "(-$s)" : $s;
}

# 读取一行输入，按 '/' 和空白拆出分子分母
my $line = <STDIN>;
chomp $line;
my @tok = grep { length } split /[\/\s]+/, $line;
my ($a1, $b1, $a2, $b2) = @tok;

# 标准化两个有理数
my ($x1, $y1) = norm($a1, $b1);
my ($x2, $y2) = norm($a2, $b2);

# 四则运算（结果约分）
my ($s1, $s2) = norm($x1 * $y2 + $x2 * $y1, $y1 * $y2);  # 和
my ($d1, $d2) = norm($x1 * $y2 - $x2 * $y1, $y1 * $y2);  # 差
my ($p1, $p2) = norm($x1 * $x2,          $y1 * $y2);     # 积
my ($q1, $q2) = $x2 == 0 ? (0, 0) : norm($x1 * $y2, $y1 * $x2);  # 商

print fmt($x1, $y1), " + ", fmt($x2, $y2), " = ", fmt($s1, $s2), "\n";
print fmt($x1, $y1), " - ", fmt($x2, $y2), " = ", fmt($d1, $d2), "\n";
print fmt($x1, $y1), " * ", fmt($x2, $y2), " = ", fmt($p1, $p2), "\n";
print fmt($x1, $y1), " / ", fmt($x2, $y2), " = ", fmt($q1, $q2), "\n";