use strict;
use warnings;

# =====================================================================
# 题目：1063 计算谱半径
# 难度：简单
# 知识点：浮点运算, 循环迭代
# =====================================================================
#
# 【题目描述】
#   给定若干复数特征值的实部和虚部，其模为实部与虚部平方和的平方根，
#   谱半径即所有模中的最大值，四舍五入保留小数点后 2 位。
#
# 【实现原理】
#   1. 逐个读取实部虚部，计算模 sqrt(实部^2 + 虚部^2)。
#   2. 记录并更新最大模。
#   3. 用 printf 四舍五入输出两位小数。
#
# 【输入样例】
#   5
#   0 1
#   2 0
#   -1 0
#   3 3
#   0 -3
# 【输出样例】
#   4.24
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
shift @tok;                      # 去掉 N
my $max = 0;
for (my $i = 0; $i < $#tok; $i += 2) {
    my $r  = $tok[$i];
    my $im = $tok[$i + 1];
    my $mag = sqrt($r * $r + $im * $im);   # 复数模
    $max = $mag if $mag > $max;
}
printf "%.2f\n", $max;
