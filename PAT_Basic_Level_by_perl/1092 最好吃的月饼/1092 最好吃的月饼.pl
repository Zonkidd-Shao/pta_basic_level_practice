use strict;
use warnings;

# =====================================================================
# 题目：1092 最好吃的月饼
# 难度：简单
# 知识点：数组求和, 最大值
# =====================================================================
#
# 【题目描述】
#   给定 N 种月饼在 M 个城市的销量，统计每种月饼的总销量，
#   找出销量冠军（可能并列），并输出最大销量及并列的种类编号。
#
# 【实现原理】
#   1. 逐行累加 M 行数据，每行第 i 个数累加到第 i 种月饼的总销量
#   2. 求最大销量，输出所有销量等于最大值的种类编号（递增）
#
# 【输入样例】
#   5 3
#   1001 992 0 233 6
#   8 0 2018 0 2008
#   36 18 0 1024 4
# 【输出样例】
#   2018
#   3 5
# =====================================================================

my ($n, $m) = split /\s+/, <STDIN>;          # n 种月饼，m 个城市
my @sum = (0) x $n;                          # 每种月饼的总销量

for (1 .. $m) {
    my @row = split /\s+/, <STDIN>;          # 一行中第 i 个数是第 i 种月饼的销量
    $sum[$_] += $row[$_] for 0 .. $n - 1;    # 累加各种月饼销量
}

my $max = $sum[0];                           # 求最大销量
for (@sum) {
    $max = $_ if $_ > $max;
}

my @best;                                    # 收集销量并列冠军的种类编号
push @best, $_ + 1 for grep { $sum[$_] == $max } 0 .. $n - 1;

print "$max\n";
print join(' ', @best), "\n";