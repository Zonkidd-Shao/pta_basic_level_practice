use strict;
use warnings;

# =====================================================================
# 题目：1051 复数乘法
# 难度：中等
# 知识点：复数运算, 浮点精度
# =====================================================================
#
# 【题目描述】
#   给定两个复数的极坐标形式 (R1,P1)、(R2,P2)，求两数乘积的常规形式 A+Bi。
#   实部 = R1*R2*cos(P1+P2)，虚部 = R1*R2*sin(P1+P2)。
#
# 【实现原理】
#   1. 按复数的三角形式计算乘积的实部与虚部。
#   2. 实部虚部均保留 2 位小数，注意 -0.00 要输出为 0.00。
#   3. 虚部为负时写成 "A-|B|i" 的形式。
#
# 【输入样例】
#   2.3 3.5 5.2 0.4
# 【输出样例】
#   -8.68-8.23i
# =====================================================================

my @tok = split /\s+/, <STDIN>;
my ($r1, $p1, $r2, $p2) = @tok;

my $mul = $r1 * $r2;
my $a = $mul * cos($p1 + $p2);   # 实部
my $b = $mul * sin($p1 + $p2);   # 虚部

my $ra = abs($a) < 0.005 ? 0 : $a;    # 避免输出 -0.00
my $rb = abs($b) < 0.005 ? 0 : $b;

printf "%s%.2f%s%.2fi\n",
    $ra < 0 ? '' : '',     # 实部本身带负号
    $ra,
    $rb >= 0 ? '+' : '-',  # 虚部符号
    abs($rb);