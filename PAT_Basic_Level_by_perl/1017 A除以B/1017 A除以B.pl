use strict;
use warnings;

# =====================================================================
# 题目：1017 A除以B
# 难度：简单
# 知识点：大整数除法、模拟竖式除法
# =====================================================================
#
# 【题目描述】
#   计算 A/B，其中 A 是不超过 1000 位的正整数，B 是 1 位正整数。
#   输出商数 Q 和余数 R，使得 A = B * Q + R。
#
# 【实现原理】
#   1. 大整数处理：
#      - A 最多 1000 位，远超普通整型范围，必须用字符串存储
#      - B 是 1 位整数（1-9），可以用普通整型存储
#   2. 模拟竖式除法：
#      - 从高位到低位逐位处理 A 的每一位数字
#      - 每一步：rem = rem * 10 + 当前位数字
#      - 当前位的商：q = int(rem / B)
#      - 更新余数：rem = rem % B
#   3. 商的前导零处理：
#      - 第一位商可能是 0（例如 123 / 7，第一位商 0）
#      - 需要跳过前导零，不加入结果
#      - 但若商为 0（即 A < B），需要输出 0 而不是空
#   4. 时间复杂度：O(L)，L 为 A 的位数。
#   5. 空间复杂度：O(L)，存储商的结果。
#
# 【输入样例】 123456789050987654321 7
# 【输出样例】 17636684150141093474 3
#   过程（前几位示意）：
#     1/7 = 0 余 1   → 商首位为 0，跳过
#     12/7 = 1 余 5  → 商 = "1"
#     53/7 = 7 余 4  → 商 = "17"
#     44/7 = 6 余 2  → 商 = "176"
#     ... 依次类推
# =====================================================================

# 读取 A 和 B（A 作为字符串处理，B 是 1 位整数）
my $line = <STDIN>;
chomp $line;
my ($A, $B) = split /\s+/, $line;

# 余数，初始为 0
my $rem = 0;
# 商的字符串，初始为空
my $quo = '';

# 从高位到低位逐位处理 A 的每一位
for my $ch (split //, $A) {
    # 当前位的被除数 = 上一步的余数 * 10 + 当前位数字
    $rem = $rem * 10 + $ch;
    # 当前位的商
    my $q = int($rem / $B);
    # 将商加入结果字符串
    # 注意：跳过前导零（商为空且当前位商为 0 时不加入）
    $quo .= $q if ($quo ne '' || $q != 0);
    # 更新余数
    $rem = $rem % $B;
}

# 若商为空（即 A < B，商为 0），设为 "0"
$quo = '0' if $quo eq '';

# 输出商和余数
print "$quo $rem\n";
