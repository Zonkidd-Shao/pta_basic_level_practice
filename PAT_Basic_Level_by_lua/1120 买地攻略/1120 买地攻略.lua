-- 题目编号: 1120 买地攻略
-- 实现原理: 滑动窗口法求连续子数组和不大于预算m的方案数。维护窗口左右指针，窗口和超过m时右移左指针，每次窗口内以r结尾的子数组个数为r-l+1。

local n, m = io.read("*n"), io.read("*n")  -- n块地，预算m
local a = {}                                 -- 存储每块地的价格

-- 读取每块地的价格
for i = 1, n do
    a[i] = io.read("*n")
end

local l = 1      -- 窗口左指针
local s = 0      -- 当前窗口内元素的和
local c = 0      -- 符合条件的子数组总数

-- 滑动窗口右指针r遍历数组
for r = 1, n do
    s = s + a[r]  -- 将当前元素加入窗口
    -- 如果窗口和超过预算，右移左指针，直到和不超过预算
    while s > m do
        s = s - a[l]
        l = l + 1
    end
    -- 当前窗口内以r结尾的子数组都满足条件，个数为r-l+1
    c = c + r - l + 1
end

print(c)
