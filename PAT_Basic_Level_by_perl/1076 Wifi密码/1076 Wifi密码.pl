use strict;
use warnings;

# =====================================================================
# 题目：1076 Wifi密码
# 难度：简单
# 知识点：字符串处理, 循环
# =====================================================================
#
# 【题目描述】
#   每道选择题有 A/B/C/D 四个选项，其中被标记为 T 的即为正确答案。
#   A 对应数字 1，B 对应 2，C 对应 3，D 对应 4。
#   给定 N 道题的选项，输出所有正确答案对应数字组成的 wifi 密码。
#
# 【实现原理】
#   1. 读取选项行，按空格拆分出各个选项。
#   2. 找出以 'T' 结尾的那个选项，其对应的字母（A/B/C/D）即密码数字（A=1..D=4）。
#   3. 将所有数字拼接成密码输出。
#
# 【输入样例】
#   8
#   A-T B-F C-F D-F
#   ...
# 【输出样例】
#   13224143
# =====================================================================

# 读取题目数量 N（随后 N 行是各题选项）
my $n = <STDIN>; chomp $n;

my @out;   # 存储各题答案对应的数字

# 逐行处理每道题的选项
while (my $line = <STDIN>) {
    chomp $line;
    my @tok = split /\s+/, $line;
    # 遍历本行 4 个选项，找被标记为 T 的选项
    for my $tok (@tok) {
        if (substr($tok, -1, 1) eq 'T') {
            # 根据选项字母 A/B/C/D 得到密码数字 1/2/3/4
            my $letter = substr($tok, 0, 1);
            push @out, ord($letter) - ord('A') + 1;
            last;
        }
    }
}

print join('', @out), "\n";
