use strict;
use warnings;

# =====================================================================
# 题目：1040 有几个PAT
# 难度：中等
# 知识点：动态规划, 计数统计
# =====================================================================
#
# 【题目描述】
#   给定只含 P、A、T 三种字母的字符串，问一共可以组成多少个
#   形如 "PAT"（P 在 A 前，A 在 T 前）的三元组。
#   结果较大，对 1000000007 取余后输出。
#
# 【实现原理】
#   1. 先统计整串中 T 的总数 t_total。
#   2. 从左到右扫描字符串：
#      - 遇到 P，p_seen 加一（可作为 A 的左端）；
#      - 遇到 T，t_seen 加一（该 T 已过，不能作右端）；
#      - 遇到 A，则以该 A 为中点的 PAT 数为
#        已见P数 * (T总数 - 已见T数)，累加到答案并取模。
#   3. 时间复杂度 O(L)，空间复杂度 O(1)。
#
# 【输入样例】
#   APPAPT
# 【输出样例】
#   2
# =====================================================================

# 读取一行字符串
my $s = <STDIN>;
chomp $s;

# p_seen: 已扫描到的 P 数量（可作为 A 的左端）
# t_seen: 已扫描到的 T 数量
# t_total: 字符串中 T 的总数
# ans: 组成的 PAT 总数
my $t_total = () = $s =~ /T/g;  # 统计 T 的总数（不改动原串）
my $p_seen = 0;
my $t_seen = 0;
my $ans = 0;

# 从左到右扫描每个字符
for my $ch (split //, $s) {
    if ($ch eq 'P') {
        # 记录可作为 A 左端的 P
        $p_seen++;
    } elsif ($ch eq 'T') {
        # 记录已扫描到的 T
        $t_seen++;
    } else {
        # 遇到 A，作为中点：
        # 左端可选已见 P，右端可选尚未扫描到的 T（t_total - t_seen）
        my $t_after = $t_total - $t_seen;
        $ans = ($ans + $p_seen * $t_after) % 1000000007;
    }
}

print "$ans\n";
