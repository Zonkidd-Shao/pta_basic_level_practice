use strict;
use warnings;

# =====================================================================
# 题目：1121 祖传好运
# 难度：简单
# 知识点：字符串, 整除判断
# =====================================================================
#
# 【题目描述】
#   一个大于 9 的数字 N 具有"祖传好运"，如果它的每个前缀
#   （长度为 i 的前缀）都能被 i 整除。判断给定数字是否为祖传好运数。
#
# 【实现原理】
#   1. 对每个数字，从长度 1 到全长逐位检查前缀。
#   2. 若某前缀不能被其长度整除，则输出 No，否则输出 Yes。
#
# 【输入样例】
#   5
#   123 7 43 2333 56160
# 【输出样例】
#   Yes
#   Yes
#   No
#   No
#   Yes
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);

# 跳过第一行的 K（个数），对每个数字判断
for my $idx (1 .. $#tok) {
    my $s = $tok[$idx];
    my $ok = 1;
    # 检查每个长度 i 的前缀是否能被 i 整除
    for (my $i = 1; $i <= length($s); $i++) {
        my $pre = substr($s, 0, $i);
        if ($pre % $i != 0) {
            $ok = 0;
            last;
        }
    }
    print $ok ? "Yes\n" : "No\n";
}
