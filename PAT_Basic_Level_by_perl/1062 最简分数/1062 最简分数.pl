use strict;
use warnings;

# =====================================================================
# 题目：1062 最简分数
# 难度：中等
# 知识点：最大公约数, 分数比较
# =====================================================================
#
# 【题目描述】
#   给定两个不相等的正分数 N1/M1 和 N2/M2，以及正整数分母 K，列出
#   两分数之间所有分母为 K 的最简分数，按从小到大、空格分隔输出。
#
# 【实现原理】
#   1. 比较两个分数大小，确定下界和上界。
#   2. 枚举分子 i (1..K-1)，判断 i/K 是否严格位于两分数之间。
#   3. 用辗转相除法求 gcd(i,K)，gcd 为 1 即为最简分数。
#
# 【输入样例】
#   7/18 13/20 12
# 【输出样例】
#   5/12 7/12
# =====================================================================

my $line = <STDIN>;
chomp $line;
my @tok = split ' ', $line;
my ($n1, $m1) = split '/', $tok[0];
my ($n2, $m2) = split '/', $tok[1];
my $k = $tok[2];

# 确定两个分数的下界与上界
my ($lo_n, $lo_m, $hi_n, $hi_m);
if ($n1 / $m1 < $n2 / $m2) {
    ($lo_n, $lo_m, $hi_n, $hi_m) = ($n1, $m1, $n2, $m2);
} else {
    ($lo_n, $lo_m, $hi_n, $hi_m) = ($n2, $m2, $n1, $m1);
}

# 辗转相除法求最大公约数
sub gcd {
    my ($a, $b) = @_;
    ($a, $b) = ($b, $a % $b) while $b;
    return $a;
}

my @res;
for my $i (1 .. $k - 1) {
    my $v = $i / $k;
    if ($v > $lo_n / $lo_m && $v < $hi_n / $hi_m) {
        push @res, "$i/$k" if gcd($i, $k) == 1;   # 分子分母互质
    }
}
print join(' ', @res), "\n";
