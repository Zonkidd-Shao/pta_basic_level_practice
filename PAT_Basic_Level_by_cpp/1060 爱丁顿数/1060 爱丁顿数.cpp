// 1060 爱丁顿数
//
// 实现原理：
// 爱丁顿数 E 定义为：存在至少 E 天的骑车距离超过 E 公里，且 E 的最大可能值。
// 给定 N 天的骑车距离数据，求 E。
//
// 算法思路：
// 将距离数组按降序排列。对于排序后的数组 a[0..N-1]（a[0] 最大），
// 检查 a[i-1] > i 是否成立。这个条件的含义是：
//   第 i 大的元素 > i，说明至少有 i 天的骑车距离大于 i 公里。
// 遍历 i=1..N，记录最后一个满足条件的 i 即为最大 E。
//
// 举例说明：
//   若降序排列后为 [10, 9, 8, 7, 6, 1]：
//     i=1: a[0]=10>1 → 至少 1 天 >1
//     i=2: a[1]=9>2  → 至少 2 天 >2
//     i=3: a[2]=8>3  → 至少 3 天 >3
//     i=4: a[3]=7>4  → 至少 4 天 >4
//     i=5: a[4]=6>5  → 至少 5 天 >5
//     i=6: a[5]=1>6? 不满足，停止
//   因此 E=5。
//
// 复杂度分析：
// 时间复杂度：O(NlogN)，主要开销在排序。
// 空间复杂度：O(N)，用于存储距离数组。
#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

int main() {
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    sort(a.rbegin(), a.rend()); // 降序排列

    int ans = 0;
    // 检查：第 i 大的数是否 > i（i 从 1 到 n）
    for (int i = 1; i <= n; ++i) {
        if (a[i - 1] > i) ans = i; // 第 i 大元素 > i，说明至少 i 天 > i
    }
    cout << ans << endl;
    return 0;
}