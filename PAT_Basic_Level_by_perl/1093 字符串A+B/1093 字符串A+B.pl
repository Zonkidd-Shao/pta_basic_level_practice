use strict;
use warnings;

# =====================================================================
# 题目：1093 字符串A+B
# 难度：简单
# 知识点：字符串处理, 集合去重
# =====================================================================
#
# 【题目描述】
#   给定两个字符串 A 和 B，输出 A+B 的并集：先输出 A 再输出 B，
#   但重复出现的字符只保留第一次出现的那个。
#
# 【实现原理】
#   1. 拼接两个输入行得到完整字符串
#   2. 用一个哈希表记录已出现的字符，重复字符跳过
#
# 【输入样例】
#   This is a sample test
#   to show you_How it works
# 【输出样例】
#   This ampletowyu_Hrk
# =====================================================================

my $a = <STDIN>; chomp $a;
my $b = <STDIN>; chomp $b;

my $s = $a . $b;                             # 拼接 A 和 B
my %seen;                                    # 记录已输出的字符
my $out = '';

for my $c (split //, $s) {                   # 逐字符遍历
    next if $seen{$c}++;                     # 重复字符剔除
    $out .= $c;
}

print "$out\n";