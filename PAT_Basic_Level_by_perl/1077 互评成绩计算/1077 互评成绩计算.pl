use strict;
use warnings;

# =====================================================================
# 题目：1077 互评成绩计算
# 难度：简单
# 知识点：排序, 四舍五入, 数组操作
# =====================================================================
#
# 【题目描述】
#   每个组有一份老师评分和若干份其他组的评分。将其他组评分中不合法
#   （超出 [0,M] 区间）的忽略，去掉一个最高分和一个最低分后取平均得到 G1，
#   再与老师评分 G2 平均，四舍五入取整即为该组最终得分。
#
# 【实现原理】
#   1. 每行第一个是老师评分，其余为其他组评分。
#   2. 过滤出合法评分并排序，去掉首（最小）尾（最大）两个。
#   3. 求平均后与老师评分加权平均，再 +0.5 取整实现四舍五入。
#
# 【输入样例】
#   6 50
#   42 49 49 35 38 41
#   ...
# 【输出样例】
#   42
#   ...
# =====================================================================

# 读取分组数 N 和满分 M
my $line = <STDIN>; chomp $line;
my ($n, $m) = split /\s+/, $line;

for (1..$n) {
    my $l = <STDIN>; chomp $l;
    my @a = split /\s+/, $l;

    my $teacher = shift @a;   # 第一个是老师评分

    # 过滤合法评分（[0,M] 内）并升序排列
    my @peers = sort { $a <=> $b } grep { $_ >= 0 && $_ <= $m } @a;
    shift @peers;   # 去掉最低分
    pop @peers;     # 去掉最高分

    # 计算其他组评分的平均分
    my $sum = 0;
    $sum += $_ for @peers;
    my $avg = $sum / @peers;

    # (G1+G2)/2 后四舍五入取整
    my $res = int(($teacher + $avg) / 2 + 0.5);
    print "$res\n";
}
