# 题目：1110 区块反转
#
# 题目描述：
#   给定一个单链表 L，我们将每 K 个结点看成一个**区块**（链表最后若不足 K 个结点，也看成一个区块），请编写程序将 L 中所有区块的链接反转。例如：给定 L 为 1→2→3→4→5→6→7→8，K 为 3，则输出应该为 7→8→4→5→6→1→2→3。
#
# 输入格式：
#   每个输入包含 1 个测试用例。每个测试用例第 1 行给出第 1 个结点的地址、结点总个数正整数 N (\le 10^5)、以及正整数 K (\le N)，即区块的大小。结点的地址是 5 位非负整数，NULL 地址用 -1 表示。
#   接下来有 N 行，每行格式为：
#   ```
#   Address Data Next
#   ```
#   其中 `Address` 是结点地址，`Data` 是该结点保存的整数数据，`Next` 是下一结点的地址。
#
# 输出格式：
#   对每个测试用例，顺序输出反转后的链表，其上每个结点占一行，格式与输入相同。
#
# 实现原理：
#   - 使用字典(Dict)存储键值对映射
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   字符串反转：将输入按单词分割后逆序输出，
#   利用列表反转和字符串拼接实现。
#
import sys

h,n,k=sys.stdin.readline().split();k=int(k);d={}
for _ in range(int(n)):
 a,x,b=sys.stdin.readline().split();d[a]=(x,b)
a=[]
while h!='-1':a.append(h);h=d[h][1]
for i in range(0,len(a),k):a[i:i+k]=a[i:i+k][::-1]
for i,x in enumerate(a):print(x,d[x][0],a[i+1] if i+1<len(a) else '-1')
