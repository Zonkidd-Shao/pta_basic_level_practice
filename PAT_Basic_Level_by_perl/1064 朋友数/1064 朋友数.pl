use strict;
use warnings;

# =====================================================================
# 题目：1064 朋友数
# 难度：简单
# 知识点：数位求和, 集合去重, 排序
# =====================================================================
#
# 【题目描述】
#   若两个整数各位数字之和相同，则称它们为朋友数，公共的和为朋友证号。
#   给定若干整数，统计不同朋友证号的个数，并按递增顺序输出。
#
# 【实现原理】
#   1. 对每个数求各位数字之和。
#   2. 用哈希表对朋友证号去重。
#   3. 输出去重后的个数，再按递增顺序输出各朋友证号。
#
# 【输入样例】
#   8
#   123 899 51 998 27 33 36 12
# 【输出样例】
#   4
#   3 6 9 26
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
shift @tok;                     # 去掉 N
my %set;
for my $x (@tok) {
    my $sum = 0;
    $sum += $_ for split //, $x;   # 各位数字之和
    $set{$sum} = 1;
}
my @keys = sort { $a <=> $b } keys %set;
print scalar(@keys), "\n";
print join(' ', @keys), "\n";
