# 题目名称：有多少不同的值
# 题目编号：PAT Basic 1087
# 实现原理：
#   计算自然数1到N中，每个数n对应的算式 ⌊n/2⌋ + ⌊n/3⌋ + ⌊n/5⌋ 的值，统计不同值的个数。
#   关键步骤：
#   1. 读取正整数N和序列数据
#   2. 计算每个位置的绝对差值
#   3. 用 unique 函数去除重复的差值
#   4. 统计不同值的个数并输出
#   利用R语言向量化运算特性，可以一次性计算所有值，再用unique去重。
# 时间复杂度：O(N)，遍历一次计算并去重
# 空间复杂度：O(N)，存储所有计算结果
n<-as.integer(scan("stdin",quiet=TRUE)[1]);v<-floor(1:n/2)+floor(1:n/3)+floor(1:n/5);cat(length(unique(v)),"\n")
