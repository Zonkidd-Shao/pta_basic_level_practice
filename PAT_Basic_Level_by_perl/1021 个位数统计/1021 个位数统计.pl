use strict;
use warnings;

# =====================================================================
# 题目：1021 个位数统计
# 难度：简单
# 知识点：字符串处理, 计数
# =====================================================================
#
# 【题目描述】
#   给定一个不超过 1000 位的正整数 N，统计其中每种数字出现的次数，
#   按数字升序输出。
#
# 【实现原理】
#   1. 逐字符遍历 N，用数组下标统计 0-9 各自出现次数。
#   2. 按数字从小到大输出出现次数不为 0 的数字。
#
# 【输入样例】
#   100311
# 【输出样例】
#   0:2
#   1:3
#   3:1
# =====================================================================

my $line = <STDIN>;
chomp $line;

my @cnt = (0) x 10;              # 0-9 各数字出现次数
for my $c (split //, $line) {
    $cnt[$c]++;
}

for my $d (0 .. 9) {
    print "$d:$cnt[$d]\n" if $cnt[$d] > 0;
}