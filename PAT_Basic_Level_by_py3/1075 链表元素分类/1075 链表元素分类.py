# 题目：1075 链表元素分类
#
# 题目描述：
#   给定一个单链表，请编写程序将链表元素进行分类排列，使得所有负值元素都排在非负值元素的前面，而 [0, K] 区间内的元素都排在大于 K 的元素前面。但每一类内部元素的顺序是不能改变的。例如：给定链表为 18→7→-4→0→5→-6→10→11→-2，K 为 10，则输出应该为 -4→-6→-2→7→0→5→10→18→11。
#
# 输入格式：
#   每个输入包含一个测试用例。每个测试用例第 1 行给出：第 1 个结点的地址；结点总个数，即正整数N (\le 10^5)；以及正整数K (\le 10^3)。结点的地址是 5 位非负整数，NULL 地址用 -1 表示。
#   接下来有 N 行，每行格式为：
#   ```
#   Address Data Next
#   ```
#   其中 `Address` 是结点地址；`Data` 是该结点保存的数据，为 [-10^5, 10^5] 区间内的整数；`Next` 是下一结点的地址。题目保证给出的链表不为空。
#
# 输出格式：
#   对每个测试用例，按链表从头到尾的顺序输出重排后的结果链表，其上每个结点占一行，格式与输入相同。
#
# 实现原理：
#   - 使用字典(Dict)存储键值对映射
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   链表处理：使用字典存储节点地址映射，
#   先遍历链表得到节点顺序，
#   再按K个一组进行反转，最后重新连接输出。
#
import sys

head,n,k=sys.stdin.readline().split(); k=int(k); d={}
for _ in range(int(n)):
 a,x,b=sys.stdin.readline().split();d[a]=(int(x),b)
groups=[[],[],[]]
while head!='-1':
 x,nxt=d[head];groups[0 if x<0 else 1 if x<=k else 2].append((head,x));head=nxt
a=sum(groups,[])
for i,(p,x) in enumerate(a): print(p,x,a[i+1][0] if i+1<len(a) else '-1')
