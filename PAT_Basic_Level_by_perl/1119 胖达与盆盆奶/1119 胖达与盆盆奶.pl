use strict;
use warnings;

# =====================================================================
# 题目：1119 胖达与盆盆奶
# 难度：中等
# 知识点：贪心算法, 两次遍历
# =====================================================================
#
# 【题目描述】
#   给一排胖达分配盆盆奶，要求更胖的胖达得到更多的奶，
#   等胖的得到一样多的奶。每只胖达最少吃 200 毫升，
#   多出的奶至少 100 毫升才会被感觉到"更多"。
#   计算在保持给定队形的前提下至少需要准备多少毫升奶。
#
# 【实现原理】
#   1. 从左向右遍历：若当前体重大于前一只，则 left 加一。
#   2. 从右向左遍历：若当前体重大于后一只，则 right 加一。
#   3. 每只胖达的奶量取 max(left,right)，乘以 100 再加 100，求和。
#
# 【输入样例】
#   10
#   180 160 100 150 145 142 138 138 138 140
# 【输出样例】
#   3000
# =====================================================================

my $line = <STDIN>;
chomp $line;
my $n = $line;

my @a = split /\s+/, <STDIN>;

# left[i]：从左往右看需要的相对奶量增量
# right[i]：从右往左看需要的相对奶量增量
my @left  = (1) x $n;
my @right = (1) x $n;

# 从左向右遍历：体重上升则递增
for (my $i = 1; $i < $n; $i++) {
    if ($a[$i] > $a[$i - 1]) {
        $left[$i] = $left[$i - 1] + 1;
    }
}

# 从右向左遍历：体重上升则递增
for (my $i = $n - 2; $i >= 0; $i--) {
    if ($a[$i] > $a[$i + 1]) {
        $right[$i] = $right[$i + 1] + 1;
    }
}

# 每只胖达取左右约束的最大值，转换为奶量并求和
my $sum = 0;
for (my $i = 0; $i < $n; $i++) {
    my $max = $left[$i] > $right[$i] ? $left[$i] : $right[$i];
    $sum += $max * 100 + 100;
}

print $sum, "\n";
