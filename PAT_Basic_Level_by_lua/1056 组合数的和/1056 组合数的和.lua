-- 题目编号: 1056 组合数的和
-- 实现原理: 给定N个非零个位数字，每个数字在十位和个位各出现(N-1)次。因此总和 = Σ(每个数字) * (N-1) * 11。直接求和后乘以(N-1)*11即可。
-- 读取数字个数n，s用于累加所有数字之和
local n, s = io.read("*n"), 0
-- 读取n个数字并累加
for i = 1, n do
    s = s + io.read("*n")
end
-- 数学公式：每个数字在十位出现(n-1)次，在个位出现(n-1)次
-- 因此总和 = s * (n-1) * 10 + s * (n-1) = s * (n-1) * 11
print(s * (n - 1) * 11)
