# 题目：1083 是否存在相等的差
#
# 题目描述：
#   给定 N 张卡片，正面分别写上 1、2、……、N，然后全部翻面，洗牌，在背面分别写上 1、2、……、N。将每张牌的正反两面数字相减（大减小），得到 N 个非负差值，其中是否存在相等的差？
#
# 输入格式：
#   输入第一行给出一个正整数 N（2 \le N \le 10 000），随后一行给出 1 到 N 的一个洗牌后的排列，第 i 个数表示正面写了 i 的那张卡片背面的数字。
#
# 输出格式：
#   按照“差值 重复次数”的格式从大到小输出重复的差值及其重复的次数，每行输出一个结果。
#
# 实现原理：
#   - 排序算法
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   统计与排序：计算每个位置的数值与位置的差，
#   统计出现多次的差值。
#
import sys
from collections import Counter

a=list(map(int,sys.stdin.read().split()))[1:];c=Counter(abs(x-i) for i,x in enumerate(a,1))
for x in sorted(c,reverse=True):
 if c[x]>1:print(x,c[x])
