use strict;
use warnings;

# =====================================================================
# 题目：1001 害死人不偿命的(3n+1)猜想
# 难度：入门
# 知识点：循环结构、条件判断、数学模拟
# =====================================================================
#
# 【题目描述】
#   对给定的不超过 1000 的正整数 n，计算将其按照卡拉兹(Callatz)猜想
#   的规则砍到 1 需要多少步。
#   规则：
#     - 若 n 为偶数：n = n / 2
#     - 若 n 为奇数：n = (3 * n + 1) / 2
#
# 【实现原理】
#   1. 输入处理：从标准输入读取 n，去除空白字符确保数据干净。
#   2. 循环迭代：使用 while 循环，当 n 不等于 1 时持续执行：
#      - 根据奇偶性选择对应的变换规则
#      - 每完成一次变换，步数计数器 steps 加 1
#   3. 终止条件：当 n 变为 1 时退出循环，输出步数。
#   4. 时间复杂度：O(log n)，因为每次操作至少让 n 减半，
#      步数与 n 的对数成正比。
#   5. 空间复杂度：O(1)，仅使用常数个变量。
#
# 【输入样例】 3
# 【输出样例】 5
#   推导过程：
#     3 -> (3*3+1)/2 = 5  (第1步)
#     5 -> (3*5+1)/2 = 8  (第2步)
#     8 -> 8/2 = 4        (第3步)
#     4 -> 4/2 = 2        (第4步)
#     2 -> 2/2 = 1        (第5步)
# =====================================================================

# 从标准输入读取一行数据
my $n = <STDIN>;
# 去除行尾换行符
chomp $n;
# 去除所有空白字符（空格、制表符等），确保输入纯净
$n =~ s/\s+//g;

# 步数计数器，初始为 0
my $steps = 0;

# 当 n 不等于 1 时，继续执行卡拉兹变换
while ($n != 1) {
    # 偶数则除以 2
    if ($n % 2 == 0) {
        $n = $n / 2;
    }
    # 奇数则 (3n+1)/2
    else {
        $n = (3 * $n + 1) / 2;
    }
    # 每完成一次变换，步数加 1
    $steps++;
}

# 输出最终步数
print "$steps\n";
