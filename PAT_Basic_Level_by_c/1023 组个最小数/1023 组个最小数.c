/*
 * 题目：1023 组个最小数
 * 实现原理：
 *   给定0-9每个数字的个数，组成最小的数。
 *   算法步骤：
 *   1. 首先找到第一个非零数字（从1到9），输出它并减少计数
 *   2. 然后按从小到大的顺序输出剩余所有数字
 *   这样保证了最小的首位数字和最小的整体排列。
 *   例如：输入2 2 1 0 0 0 0 0 0 0（表示2个0，2个1，1个2）
 *   输出：10012
 */
#include <stdio.h>

int main() {
    int cnt[10];                    // cnt[i] 记录数字 i 的个数
    for (int i = 0; i < 10; i++) {
        scanf("%d", &cnt[i]);
    }
    for (int i = 1; i < 10; i++) {  // 选最小的非零数字作首位，避免前导 0
        if (cnt[i] > 0) {
            printf("%d", i);
            cnt[i]--;               // 消耗掉一个该数字
            break;
        }
    }
    for (int i = 0; i < 10; i++) {  // 其余数字按从小到大全部输出
        for (int j = 0; j < cnt[i]; j++) {
            printf("%d", i);
        }
    }
    printf("\n");
    return 0;
}