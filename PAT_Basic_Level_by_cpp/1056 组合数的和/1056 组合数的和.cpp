// 1056 组合数的和
//
// 实现原理：
// 给定 N 个非零数字，任选两个不同位置的数字可以组成一个两位数（两个数字可互换十位和个位）。
// 要求所有可能组成的两位数之和。
//
// 算法推导：
// 每个数字在十位出现的次数恰好为 (N-1) 次（与其余 N-1 个数字各组合一次），
// 每个数字在个位出现的次数也恰好为 (N-1) 次。
// 因此，所有两位数的总和 = (数字之和) × 10 × (N-1) + (数字之和) × 1 × (N-1)
//                        = (数字之和) × 11 × (N-1)
//
// 关键步骤：
// 1. 读取 N 个数字并累加求和
// 2. 直接套用公式 sum * 11 * (N-1) 输出结果
//
// 复杂度分析：
// 时间复杂度：O(N)，遍历一次即可。
// 空间复杂度：O(1)，只使用常数额外空间。
#include <iostream>

using namespace std;

int main() {
    int n;
    if (!(cin >> n)) return 0;
    int sum = 0, x;
    for (int i = 0; i < n; ++i) {
        cin >> x;
        sum += x;
    }
    // 每个数字作为十位和个位各出现 N-1 次，总和 = 数字和 × 11 × (N-1)
    cout << sum * 11 * (n - 1) << endl;
    return 0;
}