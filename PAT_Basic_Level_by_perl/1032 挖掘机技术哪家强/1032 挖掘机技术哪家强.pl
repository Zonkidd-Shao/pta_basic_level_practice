use strict;
use warnings;

# =====================================================================
# 题目：1032 挖掘机技术哪家强
# 难度：简单
# 知识点：哈希表统计, 遍历求最大值
# =====================================================================
#
# 【题目描述】
#   根据比赛结果统计技术最强的学校。给出 N 位参赛者的学校编号和成绩，
#   输出总得分最高的学校编号及其总分（答案唯一，无并列）。
#
# 【实现原理】
#   1. 数据统计：用哈希表按学校编号累加总分。
#   2. 求最大值：遍历哈希表，找出总分最高的学校编号和总分。
#   3. 输出结果：按“编号 总分”格式输出。
#
# 【输入样例】
#   6
#   3 65
#   2 80
#   1 100
#   2 70
#   3 40
#   3 0
# 【输出样例】
#   2 150
# =====================================================================

# 读取参赛人数
my $n = <STDIN>;
chomp $n;

# 哈希表：学校编号 -> 总分
my %score;

# 逐行累加每个学校的总分
for (1 .. $n) {
    my $line = <STDIN>;
    chomp $line;
    my ($id, $v) = split /\s+/, $line;
    $score{$id} += $v;
}

# 找出总分最高的学校
my ($best_id, $best_score) = (0, -1);
for my $k (keys %score) {
    if ($score{$k} > $best_score) {
        $best_score = $score{$k};
        $best_id = $k;
    }
}

print "$best_id $best_score\n";