use strict;
use warnings;

# =====================================================================
# 题目：1094 谷歌的招聘
# 难度：中等
# 知识点：素数判定, 滑动窗口
# =====================================================================
#
# 【题目描述】
#   从长度为 L 的数字串中找出最早出现的、由 K 位连续数字组成的素数。
#   找不到则输出 404；原始数字中的前导零也计入位数（候选串需保留前导零）。
#
# 【实现原理】
#   1. 用滑动窗口依次取 K 位连续子串
#   2. 转成整数做素数判定（试除法，界为平方根），找到第一个即输出
#
# 【输入样例】
#   20 5
#   23654987725541023819
# 【输出样例】
#   49877
# =====================================================================

my ($L, $K) = split /\s+/, <STDIN>;          # 数字串长度和窗口大小
my $N = <STDIN>; chomp $N;

# 素数判定：x 为 2 及以上且无因子即素数
sub is_prime {
    my $x = shift;
    return 0 if $x < 2;                      # 0、1 不是素数
    return 1 if $x == 2;
    return 0 if $x % 2 == 0;                 # 偶数直接排除
    for (my $i = 3; $i * $i <= $x; $i += 2) {
        return 0 if $x % $i == 0;
    }
    return 1;
}

my $ans = '404';                             # 默认输出 404
for (my $i = 0; $i + $K <= $L; $i++) {
    my $cand = substr($N, $i, $K);           # 取 K 位连续子串（保留前导零）
    if (is_prime(0 + $cand)) {               # 转整数后判断素数
        $ans = $cand;                        # 输出原始子串，保留前导零
        last;                                # 找最早出现的即可
    }
}

print "$ans\n";