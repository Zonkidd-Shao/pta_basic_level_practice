/*
 * 1040 有几个PAT
 *
 * 【实现原理】
 * 给定一个由 'P'、'A'、'T' 三种字母组成的字符串，统计其中 "PAT" 子序列的个数。
 * 子序列不要求字符连续，但字符的相对顺序必须保持不变（下标递增）。
 * 结果对 1000000007 取模。
 *
 * 【算法思路】
 * 使用动态规划思想，一次遍历完成统计：
 * 1. 维护三个变量：
 *    - p：当前位置之前 'P' 的个数
 *    - pa：当前位置之前可以组成 "PA" 子序列的个数
 *    - pat：当前位置之前可以组成 "PAT" 子序列的个数
 * 2. 遍历每个字符 c：
 *    - 若 c == 'P'：p++，即多了一个可能的 'P' 开头
 *    - 若 c == 'A'：当前位置作为 'A'，可以与之前的所有 'P' 组成 "PA"，
 *      因此 pa += p
 *    - 若 c == 'T'：当前位置作为 'T'，可以与之前的所有 "PA" 组成 "PAT"，
 *      因此 pat += pa
 * 3. 所有运算均对 MOD 取模
 *
 * 【关键点】
 * - 核心思想：每个 'T' 能组成的 "PAT" 子序列数 = 其前面所有能组成 "PA" 的子序列数
 * - 同理，每个 'A' 能组成的 "PA" 子序列数 = 其前面 'P' 的个数
 * - 这个递推关系利用了子序列的"组合"性质，将 O(N^3) 的暴力枚举优化为 O(N)
 *
 * 【复杂度分析】
 * - 时间复杂度：O(N)，一次线性遍历
 * - 空间复杂度：O(1)，仅使用三个变量
 */

#include <iostream>
#include <string>

using namespace std;

int main() {
    string s;
    if (!(cin >> s)) return 0;

    const int MOD = 1000000007;
    long long p = 0;    // 统计已遍历部分中 'P' 的个数
    long long pa = 0;   // 统计已遍历部分中 "PA" 子序列的个数
    long long pat = 0;  // 统计已遍历部分中 "PAT" 子序列的个数

    for (char c : s) {
        if (c == 'P') {
            ++p;  // 遇到 P，P 的计数加一
        } else if (c == 'A') {
            // 遇到 A，这个 A 可以与前面所有 P 组成 PA 子序列
            pa = (pa + p) % MOD;
        } else if (c == 'T') {
            // 遇到 T，这个 T 可以与前面所有 PA 子序列组成 PAT 子序列
            pat = (pat + pa) % MOD;
        }
    }

    cout << pat << endl;
    return 0;
}