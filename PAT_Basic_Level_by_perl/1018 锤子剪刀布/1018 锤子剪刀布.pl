use strict;
use warnings;

# =====================================================================
# 题目：1018 锤子剪刀布
# 难度：简单
# 知识点：哈希表、胜负判定、统计计数
# =====================================================================
#
# 【题目描述】
#   给出 N 次锤子剪刀布的交锋记录，统计甲乙双方的胜、平、负次数，
#   并给出双方获胜次数最多的手势。
#   C=锤子(ChuiZi), J=剪刀(JianDao), B=布(Bu)
#   胜负规则：B胜C，C胜J，J胜B
#   若获胜次数最多的手势不唯一，输出按字母序最小的解（B < C < J）。
#
# 【实现原理】
#   1. 胜负判定：
#      - 使用哈希 %win 建立"手势 → 它能战胜的手势"的映射
#      - 即 $win{$a} 是甲出 $a 时能战胜的乙手势
#   2. 胜负判断逻辑：
#      - 甲乙手势相同 → 平局
#      - 甲的手势能战胜乙的手势（$win{$a} eq $b）→ 甲胜
#      - 否则 → 乙胜
#   3. 统计计数：
#      - wa: 甲胜次数，wb: 乙胜次数，ti: 平局次数
#      - %ca: 甲各手势的出场次数
#      - %cb: 乙各手势的出场次数
#   4. 找出场次数最多的手势：
#      - 按 B, C, J 顺序遍历，严格大于时才更新
#      - 这样次数相同时，先遍历到的（字母序较小的）保留
#      - 符合题目"字母序最小的解"的要求
#   5. 时间复杂度：O(N)，每次交锋 O(1) 处理。
#   6. 空间复杂度：O(1)，哈希表大小固定为 3。
#
# 【输入样例】
#   10
#   C J
#   J B
#   C B
#   B B
#   B C
#   C C
#   C B
#   J B
#   B C
#   J J
# 【输出样例】
#   5 3 2
#   2 3 5
#   B B
# =====================================================================

# 读取交锋次数 N
my $N = <STDIN>;
chomp $N;

# %ca: 甲各手势的获胜次数计数
# %cb: 乙各手势的获胜次数计数
my (%ca, %cb);
# wa: 甲胜次数, wb: 乙胜次数, ti: 平局次数
my ($wa, $wb, $ti) = (0, 0, 0);

# 胜负映射：键是手势，值是它能战胜的手势
# C(锤子) 胜 J(剪刀)
# J(剪刀) 胜 B(布)
# B(布) 胜 C(锤子)
my %win = ('C' => 'J', 'J' => 'B', 'B' => 'C');

# 处理 N 次交锋
while ($N-- > 0) {
    my $l = <STDIN>;
    chomp $l;
    # 读取甲的手势 $a 和乙的手势 $b
    my ($a, $b) = split /\s+/, $l;

    # 判断胜负
    if    ($a eq $b)       { $ti++; }        # 手势相同，平局
    elsif ($win{$a} eq $b) { $wa++; $ca{$a}++; }  # 甲胜
    else                   { $wb++; $cb{$b}++; }  # 乙胜
}

# 输出甲的胜、平、负次数
print "$wa $ti $wb\n";
# 输出乙的胜、平、负次数（乙的胜=甲的负，乙的负=甲的胜）
print "$wb $ti $wa\n";

# 找出场次数最多的手势
# 按 B, C, J 顺序遍历，严格大于时更新，保证并列时返回字母序最小的
sub best {
    # 接收哈希引用，拷贝为局部哈希
    my %h = %{ shift() };
    my $best = 'B';      # 初始最佳手势为 B（字母序最小）
    my $bc   = -1;       # 初始最佳次数为 -1
    # 按 B, C, J 顺序遍历（字母序升序）
    for my $g (qw(B C J)) {
        # 当前手势次数大于最佳次数时更新
        # 用严格大于确保次数相同时保留先遍历到的（字母序小的）
        my $count = $h{$g} || 0;
        if ($count > $bc) { $bc = $count; $best = $g; }
    }
    return $best;
}

# 输出甲乙获胜次数最多的手势
print best(\%ca), " ", best(\%cb), "\n";
