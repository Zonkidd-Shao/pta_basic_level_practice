# 题目名称：岩洞施工
# 题目编号：PAT Basic 1098
# 实现原理：
#   计算岩洞每个采样点处顶部与底部的高度差，找到最小高度差即为管道最大直径。
#   若最小高度差≥1则可以施工，否则需要削掉至少1-最小高度差的高度。
#   关键步骤：
#   1. 读取采样点数N
#   2. 读取顶部和底部的纵坐标数据
#   3. 对每个采样点，计算顶部高度 - 底部高度 = 可用高度
#   4. 找到所有可用高度的最小值，这就是管道的最大直径
#   5. 若最小值≥1，输出Yes和最大值；否则输出No和至少需要削掉的高度
#   管道直径取决于最窄的位置（木桶效应）。
#   需要削掉的高度 = 1 - 最小高度（如果最小高度<1）
# 时间复杂度：O(N)，遍历N个采样点计算高度差并找最小值
# 空间复杂度：O(N)，存储顶部和底部高度数据
z<-as.numeric(scan("stdin",quiet=TRUE));n<-z[1];top<-z[2:(n+1)];bot<-z[(n+2):(2*n+1)];gap<-min(top-bot);if(gap>=1)cat("Yes",gap,"\n",sep=" ")else cat("No",1-gap,"\n",sep=" ")
