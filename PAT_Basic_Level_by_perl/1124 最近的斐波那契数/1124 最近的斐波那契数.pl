use strict;
use warnings;

# =====================================================================
# 题目：1124 最近的斐波那契数
# 难度：简单
# 知识点：斐波那契数列
# =====================================================================
#
# 【题目描述】
#   给定整数 N，找出与 N 差的绝对值最小的斐波那契数；
#   若解不唯一，输出较小的那个数。
#
# 【实现原理】
#   1. 生成斐波那契数列，直到某项不小于 N。
#   2. 得到两个相邻的斐波那契数 a、b（b >= N），
#      分别比较距离，a 更近或相等时输出 a，否则输出 b。
#
# 【输入样例】
#   305
# 【输出样例】
#   233
# =====================================================================

my $line = <STDIN>;
chomp $line;
my $n = $line;

# 生成斐波那契数列，a、b 为相邻两项且 b >= n
my ($a, $b) = (0, 1);
while ($b < $n) {
    ($a, $b) = ($b, $a + $b);
}

# a 更近或两者等距时选较小的 a，否则选 b
if ($n - $a <= $b - $n) {
    print $a, "\n";
} else {
    print $b, "\n";
}
