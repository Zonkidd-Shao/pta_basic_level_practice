use strict;
use warnings;

# =====================================================================
# 题目：1005 继续(3n+1)猜想
# 难度：简单
# 知识点：哈希表(集合)、卡拉兹猜想、标记法
# =====================================================================
#
# 【题目描述】
#   给定 K 个互不相同的正整数，找出其中的"关键数"。
#   关键数定义：不能被数列中其他数字的卡拉兹过程所覆盖的数。
#   覆盖定义：对数字 x 做卡拉兹变换，过程中经过的所有数（不含 x 自身）
#            都称为被 x 覆盖的数。
#   输出关键数，按从大到小排列。
#
# 【实现原理】
#   1. 标记法思想：
#      - 使用哈希表 %covered 记录所有被覆盖过的数字
#      - 对每个输入数字 x，执行完整的卡拉兹过程
#      - 将过程中经过的每一个数（不含起点 x）标记为"已覆盖"
#   2. 筛选关键数：
#      - 遍历所有输入数字
#      - 若某个数字不在 %covered 中，说明它没有被其他数字覆盖
#      - 这样的数字就是关键数
#   3. 排序输出：按从大到小排序后输出
#   4. 时间复杂度：O(K * log n)，K 为输入数字个数，每个数字的卡拉兹
#      过程步数与数字大小的对数成正比。
#   5. 空间复杂度：O(M)，M 为所有卡拉兹过程中出现过的不同数字总数。
#
# 【注意】
#   虽然输入数字都 <= 100，但卡拉兹过程中数字可能会超过 100，
#   因此哈希表的键可能大于 100，但不影响结果判断，因为我们只关心
#   输入数字是否被覆盖。
#
# 【输入样例】
#   6
#   3 5 6 7 8 11
# 【输出样例】
#   7 6
#   解释：
#     3 的覆盖: 5, 8, 4, 2, 1
#     5 的覆盖: 8, 4, 2, 1  (但 5 已被 3 覆盖)
#     6 的覆盖: 3, 5, 8, 4, 2, 1  (但 6 未被覆盖)
#     7 的覆盖: 11, 17, 26, 13, 20, 10, 5, 8, 4, 2, 1  (7 未被覆盖)
#     8 的覆盖: 4, 2, 1  (但 8 已被 3 覆盖)
#     11 的覆盖: 17, 26, 13, 20, 10, 5, 8, 4, 2, 1  (但 11 已被 7 覆盖)
#     关键数为 7 和 6，降序排列为 7 6
# =====================================================================

# 读取数字个数 K
my $n = <STDIN>;
chomp $n;
# 读取第二行所有数字
# join(' ', <STDIN>) 读取剩余所有行并用空格连接（防止数据跨行）
my @nums = split /\s+/, join(' ', <STDIN>);

# 哈希表：记录所有被覆盖过的数字
my %covered;

# 对每个输入数字执行卡拉兹过程，标记沿途经过的数字
for my $x (@nums) {
    my $v = $x;
    while ($v != 1) {
        # 执行一步卡拉兹变换
        if ($v % 2 == 0) { $v = $v / 2; }
        else             { $v = (3 * $v + 1) / 2; }
        # 将变换后得到的数字标记为已覆盖
        # 注意：起点 x 本身不加入 covered
        $covered{$v} = 1;
    }
}

# 筛选关键数：不在 covered 中的输入数字
my @key = grep { !$covered{$_} } @nums;

# 按从大到小排序（数值降序）
@key = sort { $b <=> $a } @key;

# 输出结果，空格分隔
print join(' ', @key), "\n";
