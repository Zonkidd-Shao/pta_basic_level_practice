use strict;
use warnings;

# =====================================================================
# 题目：1074 宇宙无敌加法器
# 难度：中等
# 知识点：进制转换, 大数加法, 字符串处理
# =====================================================================
#
# 【题目描述】
#   PAT 数的每一位都有各自独立的进制（0 表示十进制，或为 2~9 的整数），
#   进制表长度不超过 20 位。给定进制表以及两个不超过 N 位的非负 PAT 数，
#   求它们的和并输出（去除结果前导 0）。
#
# 【实现原理】
#   1. 从最低位（个位）开始逐位相加，每一位依据进制表对应位置的进制取模并记录进位。
#   2. 超出进制表长度的高位按十进制处理；进位数继续以十进制写出。
#   3. 将结果逆序输出，去除前导 0；若结果全为 0 则输出 "0"。
#
# 【输入样例】
#   30527
#   06203
#   415
# 【输出样例】
#   7201
# =====================================================================

# 读取三行：进制表、加数 A、加数 B
my $base = <STDIN>; chomp $base;
my $a    = <STDIN>; chomp $a;
my $b    = <STDIN>; chomp $b;

my @ans;            # 存储每一位的结果（从低位到高位）
my $carry = 0;      # 进位
my $maxlen = length($a) > length($b) ? length($a) : length($b);

# 从最低位开始逐位相加；如果仍有进位，还要继续处理更高位的进制
for (my $i = 1; $i <= $maxlen || $carry; $i++) {
    # 取 A 和 B 对应位（不足则视为 0）
    my $x = $i <= length($a) ? substr($a, -$i, 1) : 0;
    my $y = $i <= length($b) ? substr($b, -$i, 1) : 0;
    my $z = $x + $y + $carry;

    # 取该位的进制（超出进制表按十进制，0 也代表十进制）
    my $d = $i <= length($base) ? substr($base, -$i, 1) : 10;
    $d = 10 if $d == 0;

    push @ans, $z % $d;
    $carry = int($z / $d);
}

# 逆序拼接并去除前导 0
my $res = join('', reverse @ans);
$res =~ s/^0+//;
$res = '0' if $res eq '';

print "$res\n";
