use strict;
use warnings;

# =====================================================================
# 题目：1047 编程团体赛
# 难度：简单
# 知识点：哈希表, 数组累加
# =====================================================================
#
# 【题目描述】
#   每个参赛队由若干队员组成，所有队员独立比赛，参赛队成绩为所有队员成绩之和。
#   给定所有队员的比赛成绩，找出成绩最高的冠军队，输出其编号和总成绩。
#
# 【实现原理】
#   1. 读取 N 以及 N 行"队伍编号-队员编号 成绩"记录。
#   2. 用哈希表按队伍编号累加成绩。
#   3. 遍历哈希表找出总成绩最高的队伍并输出。
#
# 【输入样例】
#   6
#   3-10 99
#   11-5 87
#   102-1 0
#   102-3 100
#   11-9 89
#   3-2 61
# 【输出样例】
#   11 176
# =====================================================================

my @lines = <STDIN>;            # 读取全部输入
my %score;                      # 队伍编号 -> 总成绩
for my $i (1 .. $#lines) {      # 跳过第一行 N，逐行处理
    my $line = $lines[$i];
    chomp $line;
    my ($id, $s) = split /\s+/, $line;  # 格式：队伍编号-队员编号 成绩
    my ($team) = split /-/, $id;        # 取队伍编号
    $score{$team} += $s;
}

my ($best_team, $best_score) = ('', -1);
while (my ($team, $s) = each %score) {  # 找出总成绩最高的队伍
    if ($s > $best_score) {
        $best_team  = $team;
        $best_score = $s;
    }
}
print "$best_team $best_score\n";