use strict;
use warnings;

# =====================================================================
# 题目：1006 换个格式输出整数
# 难度：入门
# 知识点：数位分解、字符串重复操作
# =====================================================================
#
# 【题目描述】
#   给定一个不超过 3 位的正整数 n，用规定格式输出：
#   - 百位：用 'B' 重复表示（有几个百就输出几个 B）
#   - 十位：用 'S' 重复表示（有几个十就输出几个 S）
#   - 个位：用 123...k 输出（个位是几就从 1 输出到几）
#   例如：234 -> BBSSS1234
#
# 【实现原理】
#   1. 数位分解：
#      - 百位 h = int(n / 100)，取整数除法结果
#      - 十位 t = int((n % 100) / 10)，先取余再整除
#      - 个位 o = n % 10，直接取余
#   2. 字符串构造：
#      - 百位：使用字符串重复运算符 'x'，'B' x $h 得到 h 个 B
#      - 十位：同理 'S' x $t 得到 t 个 S
#      - 个位：若 o > 0，生成 1..o 的序列并用 join 连接成字符串
#   3. 按高位到低位顺序拼接输出。
#   4. 时间复杂度：O(1)，数字最多 3 位，操作次数固定。
#   5. 空间复杂度：O(1)，输出长度不超过 9+9+9=27。
#
# 【输入样例 1】 234
# 【输出样例 1】 BBSSS1234
# 【输入样例 2】 23
# 【输出样例 2】 SS123
# =====================================================================

# 读取正整数 n
my $n = <STDIN>;
chomp $n;
$n =~ s/\s+//g;

# 分解出百位、十位、个位
# int(n/100) 取百位数字
my $h = int($n / 100);
# 先对 100 取余得到后两位，再除以 10 取十位
my $t = int(($n % 100) / 10);
# 对 10 取余得到个位
my $o = $n % 10;

# 按格式输出：
#   'B' x $h   — 百位，重复 $h 个 'B'
#   'S' x $t   — 十位，重复 $t 个 'S'
#   个位：若 $o > 0 则输出 1 到 $o 的连续数字，否则输出空
print 'B' x $h, 'S' x $t, ($o > 0 ? join('', 1 .. $o) : ''), "\n";
