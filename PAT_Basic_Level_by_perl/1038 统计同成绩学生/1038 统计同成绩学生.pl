use strict;
use warnings;

# =====================================================================
# 题目：1038 统计同成绩学生
# 难度：简单
# 知识点：计数排序, 哈希表
# =====================================================================
#
# 【题目描述】
#   读入 N 名学生的成绩，对于给定的 K 个查询分数，
#   分别输出获得该分数的学生人数。
#
# 【实现原理】
#   1. 桶计数：利用数组下标作为分数（0~100），直接统计各分数人数。
#   2. 读取查询分数，按下标查表输出对应人数。
#   3. 时间复杂度 O(N)，空间复杂度 O(101)。
#
# 【输入样例】
#   10
#   60 75 90 55 75 99 82 90 75 50
#   3 75 90 88
# 【输出样例】
#   3 2 0
# =====================================================================

# 一次读取所有数字 token
my @tok = split /\s+/, join('', <STDIN>);

# 第一个数是学生人数 N
my $n = shift @tok;

# 桶计数：统计各分数（0~100）的人数
my @cnt = (0) x 101;
for my $i (0 .. $n - 1) {
    my $score = shift @tok;
    $cnt[$score]++;
}

# 弹出查询分数个数 K
my $k = shift @tok;

# 输出每个查询分数对应的人数
my @out;
for my $i (0 .. $k - 1) {
    my $score = shift @tok;
    push @out, $cnt[$score];
}
print join(' ', @out), "\n";
