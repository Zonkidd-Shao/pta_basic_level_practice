# 题目：1037 在霍格沃茨找零钱
#
# 题目描述：
#   如果你是哈利·波特迷，你会知道魔法世界有它自己的货币系统 —— 就如海格告诉哈利的：“十七个银西可(Sickle)兑一个加隆(Galleon)，二十九个纳特(Knut)兑一个西可，很容易。”现在，给定哈利应付的价钱 P 和他实付的钱 A，你的任务是写一个程序来计算他应该被找的零钱。
#
# 输入格式：
#   输入在 1 行中分别给出 P 和 A，格式为 `Galleon.Sickle.Knut`，其间用 1 个空格分隔。这里 `Galleon` 是 [0, 10^7] 区间内的整数，`Sickle` 是 [0, 17) 区间内的整数，`Knut` 是 [0, 29) 区间内的整数。
#
# 输出格式：
#   在一行中用与输入同样的格式输出哈利应该被找的零钱。如果他没带够钱，那么输出的应该是负数。
#
# 实现原理：
# 算法思路：
#   进制计算：模拟特殊货币体系的找零计算，
#   统一单位后进行减法运算。
#
import sys

def val(s):
    a, b, c = map(int, s.split('.')); return (a*17+b)*29+c
def show(x):
    sign = '-' if x < 0 else ''; x = abs(x); return f'{sign}{x//493}.{x//29%17}.{x%29}'
a, b = sys.stdin.read().split(); print(show(val(b)-val(a)))
