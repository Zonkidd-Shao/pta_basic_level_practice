use strict;
use warnings;

# =====================================================================
# 题目：1014 福尔摩斯的约会
# 难度：简单
# 知识点：字符串处理、字符比较、格式化输出
# =====================================================================
#
# 【题目描述】
#   给定 4 个字符串，解码约会时间：
#   1. 第 1、2 个字符串中，第 1 对相同的大写字母 A-G 代表星期几
#      （A=星期一, B=星期二, ..., G=星期日）
#   2. 第 1、2 个字符串中，上述字母之后的第 1 对相同字符
#      （0-9 或 A-N）代表小时
#      （0-9 对应 0-9 点，A-N 对应 10-23 点）
#   3. 第 3、4 个字符串中，第 1 对相同的英文字母出现的位置（从 0 计数）
#      代表分钟
#
# 【实现原理】
#   1. 星期的解码：
#      - 遍历第 1、2 个字符串的相同下标位置
#      - 找到第一对相同且为 A-G 的大写字母
#      - 字母 D 对应第 4 个（A=0, B=1, C=2, D=3 → THU=星期四）
#      - 记录该位置 day_idx，小时要从该位置之后开始找
#   2. 小时的解码：
#      - 从 day_idx + 1 位置开始继续遍历
#      - 找到第一对相同的字符
#      - 若是数字 0-9，小时值 = ord(ch) - ord('0')
#      - 若是大写字母 A-N，小时值 = ord(ch) - ord('A') + 10
#   3. 分钟的解码：
#      - 遍历第 3、4 个字符串的相同下标位置
#      - 找到第一对相同的英文字母（不区分大小写？题目说"英文字母"）
#      - 该位置的下标值就是分钟数
#   4. 格式化输出：
#      - 星期用 3 字符缩写（MON, TUE, WED, THU, FRI, SAT, SUN）
#      - 小时和分钟都用两位数字，不足补零
#   5. 时间复杂度：O(L)，L 为字符串长度。
#   6. 空间复杂度：O(1)。
#
# 【输入样例】
#   3485djDkxh4hhGE
#   2984akDfkkkkggEdsb
#   s&hgsfdk
#   d&Hyscvnm
# 【输出样例】
#   THU 14:04
#   解释：
#     第1对相同大写字母 D（位置7）→ 星期四
#     其后第1对相同字符 E（位置13）→ 第5个字母 → 10+4=14点
#     第3、4串第1对相同字母 s（位置4）→ 4分钟
# =====================================================================

# 读取 4 行输入
my @lines = <STDIN>;
chomp for @lines;
my ($s1, $s2, $s3, $s4) = @lines;

# 星期几的缩写数组，索引 0-6 对应 A-G
my @days = qw(MON TUE WED THU FRI SAT SUN);
my ($day, $hour, $min);

# 第一步：找第 1 对相同的 A-G 大写字母（确定星期几）
my $day_idx;
for my $i (0 .. length($s1) - 1) {
    my $a = substr($s1, $i, 1);
    my $b = substr($s2, $i, 1);
    # 两字符相同且在 A-G 范围内
    if ($a eq $b && $a ge 'A' && $a le 'G') {
        $day = $days[ ord($a) - ord('A') ];
        $day_idx = $i;
        last;
    }
}

# 第二步：从 day_idx 之后找第 1 对相同的 0-9 或 A-N（确定小时）
for my $i ($day_idx + 1 .. length($s1) - 1) {
    my $a = substr($s1, $i, 1);
    my $b = substr($s2, $i, 1);
    if ($a eq $b) {
        # 数字 0-9 对应 0-9 点
        if ($a ge '0' && $a le '9') {
            $hour = sprintf('%02d', ord($a) - ord('0'));
            last;
        }
        # 大写字母 A-N 对应 10-23 点
        if ($a ge 'A' && $a le 'N') {
            $hour = sprintf('%02d', ord($a) - ord('A') + 10);
            last;
        }
    }
}

# 第三步：找第 3、4 串中第 1 对相同的英文字母（确定分钟）
# 字母的位置下标即为分钟数
for my $i (0 .. length($s3) - 1) {
    my $a = substr($s3, $i, 1);
    my $b = substr($s4, $i, 1);
    # 两字符相同且为英文字母（大小写均可）
    if ($a eq $b && $a =~ /[A-Za-z]/) {
        $min = sprintf('%02d', $i);
        last;
    }
}

# 输出约会时间
print "$day $hour:$min\n";
