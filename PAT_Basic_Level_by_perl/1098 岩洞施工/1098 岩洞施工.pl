use strict;
use warnings;

# =====================================================================
# 题目：1098 岩洞施工
# 难度：中等
# 知识点：最值, 区间高度计算
# =====================================================================
#
# 【题目描述】
#   给定岩洞顶部和底部的横向采样纵坐标，判断能否水平送入
#   直径至少为 1 的管道：可以则输出最大直径，不行则输出至少需削掉的高度。
#
# 【实现原理】
#   1. 最大可通过管道直径 = 顶部最低点 - 底部最高点
#   2. 直径 >= 1 输出 Yes 和直径，否则输出 No 和补齐到 1 所需高度
#
# 【输入样例】
#   11
#   7 6 5 5 6 5 4 5 5 4 4
#   3 2 2 2 2 3 3 2 1 2 3
# 【输出样例】
#   Yes 1
# =====================================================================

my $n = <STDIN>; chomp $n;                    # 横向采样点数
my @top = split /\s+/, <STDIN>;               # 岩洞顶部各采样点高度
my @bot = split /\s+/, <STDIN>;               # 岩洞底部各采样点高度

my $min_top = $top[0];                        # 顶部最低点
for (@top) {
    $min_top = $_ if $_ < $min_top;
}
my $max_bot = $bot[0];                        # 底部最高点
for (@bot) {
    $max_bot = $_ if $_ > $max_bot;
}

my $d = $min_top - $max_bot;                  # 可送入管道的最大直径
if ($d >= 1) {
    print "Yes $d\n";
} else {
    print "No ", 1 - $d, "\n";                # 至少需削掉的高度
}