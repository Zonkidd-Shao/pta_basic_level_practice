use strict;
use warnings;

# =====================================================================
# 题目：1097 矩阵行平移
# 难度：中等
# 知识点：矩阵操作, 循环平移
# =====================================================================
#
# 【题目描述】
#   给定 n×n 矩阵。奇数行的元素整体向右依次平移 1、…、k、1、… 个位置，
#   空出的左端位置用 x 填充。计算平移后每列元素的和。
#
# 【实现原理】
#   1. 对奇数行（1 起始）按 1..k 循环计算平移量
#   2. 平移时左端补 x，其余位置取原行前面相应元素，累加到各列和
#
# 【输入样例】
#   7 2 99
#   11 87 23 67 20 75 89
#   37 94 27 91 63 50 11
#   44 38 50 26 40 26 24
#   73 85 63 28 62 18 68
#   15 83 27 97 88 25 43
#   23 78 98 20 30 81 99
#   77 36 48 59 25 34 22
# 【输出样例】
#   529 481 479 263 417 342 343
# =====================================================================

my ($n, $k, $x) = split /\s+/, <STDIN>;      # 矩阵大小、平移循环上界、填充值
my @grid;
push @grid, [split /\s+/, <STDIN>] for 1 .. $n;

my @colsum = (0) x $n;                       # 各列元素之和
my $odd = 0;                                 # 已处理的奇数行数量

for (my $i = 0; $i < $n; $i++) {
    my $row = $grid[$i];
    if ($i % 2 == 0) {                       # 0 起始的偶数行即 1 起始的奇数行
        my $s = ($odd % $k) + 1;             # 平移量按 1..k 循环递增
        for (my $j = 0; $j < $n; $j++) {
            if ($j < $s) {
                $colsum[$j] += $x;           # 左端空出的位置补 x
            } else {
                $colsum[$j] += $row->[$j - $s]; # 整体右移后取回原元素
            }
        }
        $odd++;
    } else {                                 # 偶数行不平移
        $colsum[$_] += $row->[$_] for 0 .. $n - 1;
    }
}

print join(' ', @colsum), "\n";