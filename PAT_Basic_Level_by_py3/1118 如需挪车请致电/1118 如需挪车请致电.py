# 题目：1118 如需挪车请致电
#
# 题目描述：
#   ![phone.jpg](~/f29f986f-a871-4617-8fa7-e0cf4fe1d5d5.jpg)
#   上图转自新浪微博。车主用一系列简单计算给出了自己的电话号码，即：
#   2/2=1、3+2=5、\sqrt {9} = 3、\sqrt {9} = 3、0\% = 0、叁=3、5-2=3、9/3=3、1\times 3 = 3、2^3 = 8、8/2=4，最后得到的电话号码就是 153 3033 3384。
#   本题就请你写个程序自动完成电话号码的转换，以帮助那些不会计算的人。
#
# 输入格式：
#   输入用 11 行依次给出 11 位数字的计算公式，每个公式占一行。这里仅考虑以下几种运算：加（`+`）、减（`-`）、乘（`*`）、除（`/`）、取余（`%`，注意这不是上图中的百分比）、开平方根号（`sqrt`）、指数（`^`）和文字（即 0 到 9 的全小写汉语拼音，如 `ling` 表示 0）。运算符与运算数之间无空格，运算数保证是不超过 1000 的非负整数。题目保证每个计算至多只有 1 个运算符，结果都是 1 位整数。
#
# 输出格式：
#   在一行中给出电话号码，数字间不要空格。
#
# 实现原理：
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   字符串格式化：将手机号按指定格式输出，
#   可能涉及数字转字母或特殊格式。
#
import sys,math,re

words={'ling':0,'yi':1,'er':2,'san':3,'si':4,'wu':5,'liu':6,'qi':7,'ba':8,'jiu':9}
out=[]
for s in sys.stdin.read().splitlines():
 if s in words:v=words[s]
 elif s.startswith('sqrt'):v=math.isqrt(int(s[4:]))
 else:
  a,op,b=re.match(r'(\d+)([+\-*/%^])(\d+)',s).groups();a=int(a);b=int(b);v={'+':a+b,'-':a-b,'*':a*b,'/':a//b,'%':a%b,'^':a**b}[op]
 out.append(str(v))
print(''.join(out))
