use strict;
use warnings;

# =====================================================================
# 题目：1037 在霍格沃茨找零钱
# 难度：简单
# 知识点：进制转换, 模拟货币计算
# =====================================================================
#
# 【题目描述】
#   魔法世界货币：29 纳特(Knut)兑 1 西可(Sickle)，17 西可兑 1 加隆(Galleon)。
#   给定应付的价钱 P 和实付的钱 A（格式 Galleon.Sickle.Knut），
#   计算应找零钱；若钱不够则为负数。
#
# 【实现原理】
#   1. 统一单位：将 G.S.K 全部换算成最小的纳特(Knut)单位。
#   2. 减法：计算 A - P 的差值（纳特）。
#   3. 反向换算：差值除 493 得加隆、除 29 取余得西可、取余得纳特。
#   4. 处理符号：差值为负时在前面加负号。
#
# 【输入样例】
#   10.16.27 14.1.28
# 【输出样例】
#   3.2.1
# =====================================================================

# 将 "G.S.K" 字符串换算成纳特
sub to_knuts {
    my ($s) = @_;
    my ($g, $si, $k) = split /\./, $s;
    return ($g * 17 + $si) * 29 + $k;
}

# 读取 P 和 A
my $line = <STDIN>;
chomp $line;
my ($p, $a) = split /\s+/, $line;

# 计算应找零钱（纳特），可能为负
my $diff = to_knuts($a) - to_knuts($p);

my $sign = $diff < 0 ? '-' : '';
$diff = abs $diff;

# 反向换算并输出：加隆.西可.纳特
printf "%s%d.%d.%d\n",
    $sign,
    int($diff / 493),          # 加隆（17*29=493）
    int(($diff % 493) / 29),   # 西可
    $diff % 29;                # 纳特