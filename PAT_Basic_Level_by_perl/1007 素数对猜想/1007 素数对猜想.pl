use strict;
use warnings;

# =====================================================================
# 题目：1007 素数对猜想
# 难度：简单
# 知识点：素数判定、枚举法、孪生素数
# =====================================================================
#
# 【题目描述】
#   给定正整数 N（N < 10^5），计算不超过 N 的满足"素数对猜想"的
#   素数对个数。素数对猜想指：存在无穷多对相邻且差为 2 的素数
#   （即孪生素数）。
#
# 【实现原理】
#   1. 素数判定函数 is_prime：
#      - 对于 x < 2，直接返回 0（非素数）
#      - 对于 x >= 2，从 2 遍历到 sqrt(x)，若存在能整除 x 的数则非素数
#      - 只需检查到 sqrt(x) 是因为：若 x 有大于 sqrt(x) 的因子，
#        则必然有对应的小于 sqrt(x) 的因子
#   2. 枚举统计：
#      - 遍历 i 从 2 到 N-2（因为要保证 i+2 <= N）
#      - 若 i 和 i+2 都是素数，则计数加 1
#   3. 时间复杂度：O(N * sqrt(N))，对每个数做素数判定需要 O(sqrt(N))。
#      对于 N < 10^5，此方法在 200ms 时间限制内可以通过。
#      更高效的方法是使用埃拉托斯特尼筛法（埃氏筛），时间复杂度 O(N log log N)。
#   4. 空间复杂度：O(1)，仅使用常数个变量。
#
# 【输入样例】 20
# 【输出样例】 4
#   不超过 20 的孪生素数对：
#     (3, 5), (5, 7), (11, 13), (17, 19) 共 4 对
# =====================================================================

# 读取正整数 N
my $n = <STDIN>;
chomp $n;
$n =~ s/\s+//g;

# 判断一个数是否为素数的子例程
sub is_prime {
    my $x = shift;
    # 小于 2 的数不是素数
    return 0 if $x < 2;
    # 从 2 遍历到 sqrt(x)，检查是否有因子
    for my $i (2 .. int(sqrt($x))) {
        # 若能被整除，则不是素数
        return 0 if $x % $i == 0;
    }
    # 没有找到因子，是素数
    return 1;
}

# 统计孪生素数对的个数
my $cnt = 0;
# 遍历 i 从 2 到 n-2，检查 i 和 i+2 是否都是素数
for my $i (2 .. $n - 2) {
    $cnt++ if is_prime($i) && is_prime($i + 2);
}

# 输出结果
print "$cnt\n";
