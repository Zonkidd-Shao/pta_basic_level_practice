use strict;
use warnings;

# =====================================================================
# 题目：1095 解码PAT准考证
# 难度：较难
# 知识点：字符串处理, 排序, 哈希统计
# =====================================================================
#
# 【题目描述】
#   准考证号第 1 位是级别(T/A/B)，第 2~4 位是考场，第 5~10 位是日期，
#   最后 3 位是编号。给出 N 个考生成绩和 M 个统计要求：
#   类型1：按成绩降序输出指定级别的考生（成绩并列按准考证号字典序升序）；
#   类型2：统计指定考场的考生人数和总分；
#   类型3：按日期统计，按考场统计人数，人数降序（并列按考场号升序）。
#   查询结果为空输出 NA。
#
# 【实现原理】
#   1. 存储所有 (准考证号, 成绩)
#   2. 逐条处理统计要求，用 substr 提取级别/考场/日期并过滤、排序、统计
#
# 【输入样例】
#   8 4
#   B123180908127 99
#   B102180908003 86
#   A112180318002 98
#   T107150310127 62
#   A107180908108 100
#   T123180908010 78
#   B112160918035 88
#   A107180908021 98
#   1 A
#   2 107
#   3 180908
#   2 999
# 【输出样例】
#   Case 1: 1 A
#   A107180908108 100
#   A107180908021 98
#   A112180318002 98
#   Case 2: 2 107
#   3 260
#   Case 3: 3 180908
#   107 2
#   123 2
#   102 1
#   Case 4: 2 999
#   NA
# =====================================================================

my ($n, $m) = split /\s+/, <STDIN>;          # 考生人数和统计要求个数
my @rec;                                     # 存放 (准考证号, 成绩)

for (1 .. $n) {
    my ($id, $score) = split /\s+/, <STDIN>;
    push @rec, [$id, $score];
}

for my $q (1 .. $m) {
    my ($t, $x) = split /\s+/, <STDIN>;      # 类型 指令
    print "Case $q: $t $x\n";

    if ($t eq '1') {                         # 按级别输出成绩
        my @f = grep { substr($_->[0], 0, 1) eq $x } @rec;
        if (@f) {
            # 成绩降序，成绩相同按准考证号字典序升序
            my @s = sort { $b->[1] <=> $a->[1] || $a->[0] cmp $b->[0] } @f;
            print "$_->[0] $_->[1]\n" for @s;
        } else {
            print "NA\n";
        }
    } elsif ($t eq '2') {                    # 按考场统计人数和总分
        my ($cnt, $sum) = (0, 0);
        for my $r (@rec) {
            if (substr($r->[0], 1, 3) eq $x) {  # 第 2~4 位是考场
                $cnt++;
                $sum += $r->[1];
            }
        }
        print $cnt ? "$cnt $sum\n" : "NA\n";
    } else {                                 # 类型 3：按日期分考场统计人数
        my %site;
        for my $r (@rec) {
            if (substr($r->[0], 4, 6) eq $x) {  # 第 5~10 位是日期
                $site{substr($r->[0], 1, 3)}++; # 考场计数
            }
        }
        if (%site) {
            # 人数降序，人数相同按考场号升序
            my @keys = sort { $site{$b} <=> $site{$a} || $a cmp $b } keys %site;
            print "$_ $site{$_}\n" for @keys;
        } else {
            print "NA\n";
        }
    }
}