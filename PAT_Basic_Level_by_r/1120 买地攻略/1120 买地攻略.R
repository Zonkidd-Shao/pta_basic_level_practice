# 题目名称：买地攻略
# 题目编号：PAT Basic 1120
# 实现原理：
#   给定一排土地的价格和现金M，求有多少种连续购买方案（即价格和不超过M的连续子数组个数）。
#   这是经典的"和小于等于K的子数组数目"问题，用滑动窗口（双指针）高效求解。
#   解题思路：1. 初始化左指针j=1，当前窗口和s=0，答案ans=0；
#   2. 遍历右指针i从1到n：先将a[i]加入窗口（这里代码用j推进，实际是对每个左端点i找最大右端点j）；
#   3. 对每个起点i，尽可能向右扩展j直到和超过M，那么以i开头的方案数是j-i个；
#   4. 然后减去a[i]，左指针右移，继续下一轮；5. 累加所有方案数。
#   滑动窗口法利用了价格都是正数的性质，左右指针都只向右移动，保证了线性时间。
# 时间复杂度：O(n)，n为土地块数，左右指针各遍历一次
# 空间复杂度：O(n)，存储价格数组
z<-as.numeric(scan("stdin",quiet=TRUE));n<-z[1];m<-z[2];a<-z[-c(1,2)];ans<-0;j<-1;s<-0;for(i in 1:n){while(j<=n&&s+a[j]<=m){s<-s+a[j];j<-j+1};ans<-ans+j-i;s<-s-a[i]};cat(ans,"\n")
