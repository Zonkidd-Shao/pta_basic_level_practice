use strict;
use warnings;

# =====================================================================
# 题目：1109 擅长C
# 难度：较难
# 知识点：字符串处理, 图形打印
# =====================================================================
#
# 【题目描述】
#   输入 26 个大写字母 A-Z 的 7×5 点阵（由字符 C 和 . 组成），
#   再输入一行句子，单词由连续大写字母构成、以任何非大写字母分隔。
#   把每个单词按点阵逐行输出，字母间用一列空格分隔，
#   相邻两个单词之间输出一个空行，首尾不得有多余空行。
#
# 【实现原理】
#   1. 读取 26×7 行，得到 26 个字母的点阵。
#   2. 用正则提取句子中所有连续的大写字母子串作为单词。
#   3. 对每个单词，逐行（0..6）拼接每个字母对应的行并输出，
#      单词之间插入一个空行。
#
# 【输入样例】
#   ..C..
#   .C.C.
#   ...
#   HELLO~WORLD!
# 【输出样例】
#   C...C CCCCC C.... C.... .CCC.
#   ...
# =====================================================================

# 读取 26 个字母的 7×5 点阵
my @glyph;
for (my $i = 0; $i < 26; $i++) {
    my @rows;
    for (my $j = 0; $j < 7; $j++) {
        my $l = <STDIN>;
        chomp $l;
        push @rows, $l;
    }
    push @glyph, \@rows;
}

# 读取句子并提取所有单词（连续大写字母）
my $sentence = <STDIN>;
chomp $sentence;
my @words;
while ($sentence =~ /([A-Z]+)/g) {
    push @words, $1;
}

# 逐词渲染
for (my $wi = 0; $wi < @words; $wi++) {
    print "\n" if $wi > 0;          # 相邻单词之间空一行
    my $w = $words[$wi];
    for my $r (0 .. 6) {
        my @row;
        for my $ch (split //, $w) {
            # 字母对应点阵的第 $r 行
            push @row, $glyph[ord($ch) - 65][$r];
        }
        print join(' ', @row), "\n";
    }
}
