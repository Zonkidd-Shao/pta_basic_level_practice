use strict;
use warnings;

# =====================================================================
# 题目：1049 数列的片段和
# 难度：中等
# 知识点：数学公式, 模拟
# =====================================================================
#
# 【题目描述】
#   给定一个正数数列，可从中截取任意连续片段，求所有片段包含的数的总和。
#   例如 {0.1, 0.2, 0.3, 0.4} 共 10 个片段，总和为 5.0。
#
# 【实现原理】
#   1. 数学规律：下标 i（从 0 开始）的元素会在 (i+1)*(n-i) 个片段中出现。
#   2. 直接累加每个元素乘以出现次数，避免枚举所有片段的 O(n^2) 复杂度。
#   3. 用 printf 保留两位小数输出。
#
# 【输入样例】
#   4
#   0.1 0.2 0.3 0.4
# 【输出样例】
#   5.00
# =====================================================================

my @tok = split /\s+/, <STDIN>;   # 第一行：N
my $n = $tok[0];
my @arr = split /\s+/, <STDIN>;   # 第二行：数列

my $sum = 0;
for (my $i = 0; $i < $n; $i++) {
    $sum += $arr[$i] * ($i + 1) * ($n - $i);  # 每个元素出现的片段次数
}
printf "%.2f\n", $sum;