-- 题目编号: 1070 结绳
-- 实现原理: 贪心策略。将绳子长度从小到大排序，每次取最短的两根绳子对折（相加后除以 2）连接，合并后的绳子作为新绳继续参与后续对折，最终得到的长度即为最大可能长度。
-- n: 绳子数量，a: 绳子长度数组
local n, a = tonumber(io.read()), {}
-- 读取n根绳子的长度
for i = 1, n do
    a[i] = io.read("*n")
end
table.sort(a)  -- 从小到大排序
local x = a[1]  -- 初始取最短的绳子
-- 依次与后续每根绳子对折连接
for i = 2, n do
    -- 两根绳子对折连接：(x + a[i]) / 2，取整
    x = math.floor((x + a[i]) / 2)
end
print(x)
