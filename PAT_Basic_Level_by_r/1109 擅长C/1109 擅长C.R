# 题目名称：擅长C
# 题目编号：PAT Basic 1109
# 实现原理：
#   用7×5的C字母矩阵输出给定句子。输入26个大写字母的点阵图案，
#   然后按单词输出每个字母的点阵形式，字母间用空格分隔，单词间用空行分隔。
#   解题思路：1. 读取26个字母的7×5点阵，按行存储；2. 读取句子，提取其中的单词；
#   3. 对每个单词，逐行输出所有字母的对应行（字母间用空格分隔）；
#   4. 不同单词之间输出空行。
# 时间复杂度：O(26×7×5 + L×7)，L为句子中字母总数，读取点阵+逐行输出
# 空间复杂度：O(26×7×5) = O(1)，存储26个字母的点阵
x<-readLines("stdin",warn=FALSE);a<-as.integer(strsplit(x[1],"\\s+")[[1]]);s<-strsplit(x[2],"")[[1]];for(ch in s)if(ch!=" "){i<-match(toupper(ch),LETTERS);for(k in 1:7)cat(strrep(if(a[i])ch else " ",5),"\n");cat("\n")}
