-- 题目编号: 1119 胖达与盆盆奶
-- 实现原理: 每只熊猫至少200ml奶，体重更大的相邻熊猫必须比轻的至少多100ml。从左到右和从右到左各遍历一次，保证每个位置满足约束，取两次结果的最大值，求和即为最少总奶量。

local n = tonumber(io.read())  -- 熊猫数量
local a = {}                    -- 存储每只熊猫的体重
local l = {}                    -- 从左到右遍历得到的每只熊猫的奶量
local r = {}                    -- 从右到左遍历得到的每只熊猫的奶量

-- 读取每只熊猫的体重
for i = 1, n do
    a[i] = io.read("*n")
end

-- 从左到右遍历：保证右边比左边重的熊猫奶量更多
l[1] = 200  -- 第一只至少200ml
for i = 2, n do
    -- 如果当前熊猫比左边的重，奶量比左边多100ml，否则至少200ml
    l[i] = a[i] > a[i - 1] and l[i - 1] + 100 or 200
end

-- 从右到左遍历：保证左边比右边重的熊猫奶量更多
r[n] = 200  -- 最后一只至少200ml
for i = n - 1, 1, -1 do
    -- 如果当前熊猫比右边的重，奶量比右边多100ml，否则至少200ml
    r[i] = a[i] > a[i + 1] and r[i + 1] + 100 or 200
end

-- 每个位置取两次遍历的最大值，求和得到最少总奶量
local s = 0
for i = 1, n do
    s = s + math.max(l[i], r[i])
end
print(s)
