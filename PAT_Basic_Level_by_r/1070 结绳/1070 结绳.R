# 题目名称：结绳
# 题目编号：PAT Basic 1070
# 实现原理：
#   贪心算法：每次串连两段绳子后长度减半，因此短绳子应该先串连
#   以减少长绳子被对折的次数，从而获得最大总长度。
#   先将所有绳子按长度从小到大排序，然后依次串连，
#   每次串连后取整，最终得到最大绳长。
# 时间复杂度：O(N log N)，主要为排序时间，N为绳子段数
# 空间复杂度：O(N)，存储绳子长度数组
z<-as.numeric(scan("stdin",quiet=TRUE));a<-sort(z[-1]);v<-a[1];for(i in a[-1])v<-floor((v+i)/2);cat(v,"\n")
