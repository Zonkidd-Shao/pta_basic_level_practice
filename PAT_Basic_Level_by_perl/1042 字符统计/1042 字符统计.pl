use strict;
use warnings;

# =====================================================================
# 题目：1042 字符统计
# 难度：简单
# 知识点：字符频率统计, 哈希表
# =====================================================================
#
# 【题目描述】
#   给定一行由 ASCII 可见字符及空格组成的字符串，找出出现最频繁的
#   英文字母及其出现次数。统计时不区分大小写，输出小写字母；
#   若并列，输出按字母序最小的那个。
#
# 【实现原理】
#   1. 读取整行，逐字符统计英文字母的出现次数（统一转为小写）。
#   2. 按 a~z 顺序遍历哈希，用严格大于更新最佳字母，
#      保证次数相同时保留字母序最小的。
#   3. 时间复杂度 O(L)，空间复杂度 O(26)。
#
# 【输入样例】
#   This is a simple TEST.  There ARE numbers and other symbols 1&2&3...........
# 【输出样例】
#   e 7
# =====================================================================

# 读取整行（可能含空格）
my $line = <STDIN>;
chomp $line;

# 统计每个英文字母（小写）的出现次数
my %cnt;
for my $ch (split //, $line) {
    # 只处理英文字母，其它字符忽略
    if ($ch =~ /[A-Za-z]/) {
        my $lc = lc $ch;    # 统一转小写
        $cnt{$lc}++;
    }
}

# 找出出现最频繁的字母（并列时取字母序最小）
my ($best, $max) = ('a', -1);
for my $c (qw(a b c d e f g h i j k l m n o p q r s t u v w x y z)) {
    # 严格大于，保证并列时保留先遍历到的（字母序小的）
    if (($cnt{$c} || 0) > $max) {
        $max = $cnt{$c};
        $best = $c;
    }
}

print "$best $max\n";
