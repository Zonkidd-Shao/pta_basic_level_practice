use strict;
use warnings;

# =====================================================================
# 题目：1117 数字之王
# 难度：中等
# 知识点：循环迭代, 哈希计数, 逐位处理
# =====================================================================
#
# 【题目描述】
#   给定 N1 < N2，对 N1..N2 每个数，把各位数字的立方相乘得到积，
#   再将积的各位数字求和，得到一批新数字；重复该操作直到所有数
#   都是一位数。出现次数最多的数字即为"数字之王"，输出次数及数字。
#
# 【实现原理】
#   1. 对每个数：各位数字取立方后相乘 -> 结果的各位数字求和。
#   2. 重复整批转换直到最大值小于 10（全部为一位数）。
#   3. 统计各一位数出现次数，输出最大次数及对应的数字（递增）。
#
# 【输入样例】
#   10 14
# 【输出样例】
#   2
#   0 8
# =====================================================================

# 读取 N1 和 N2
my ($lo, $hi) = split /\s+/, <STDIN>;
my @a = ($lo .. $hi);

# 当前批次最大值
my $mx = $hi;

# 重复操作直到所有数字都是一位数
while ($mx >= 10) {
    my @new;
    for my $x (@a) {
        # 各位数字取立方后相乘
        my $prod = 1;
        for my $d (split //, "$x") {
            $prod *= $d * $d * $d;
        }
        # 积的各位数字求和
        my $sum = 0;
        $sum += $_ for split //, "$prod";
        push @new, $sum;
    }
    @a = @new;
    $mx = 0;
    for my $v (@a) { $mx = $v if $v > $mx; }
}

# 统计各一位数的出现次数
my %count;
$count{$_}++ for @a;

# 找出最大出现次数
my $m = 0;
for my $v (values %count) { $m = $v if $v > $m; }
print "$m\n";

# 输出达到最大次数的数字（递增）
my @kings = sort { $a <=> $b } grep { $count{$_} == $m } keys %count;
print join(' ', @kings), "\n";
