// 1001 害死人不偿命的(3n+1)猜想
// 卡拉兹(Callatz)猜想：对正整数 n，偶数砍半，奇数砍 (3n+1) 的一半，反复直到 n=1。
// 本题统计从给定 n 计算到 1 需要的步数（n <= 1000）。
//
// 【实现原理】
// 算法思路：直接模拟卡拉兹猜想的递推过程。
//   1. 若 n 为偶数，则 n = n / 2
//   2. 若 n 为奇数，则 n = (3n + 1) / 2
//   3. 每操作一次步数 +1，直到 n == 1 为止
// 时间复杂度：O(步数)，对于 n <= 1000，步数很小，近似常数时间。
// 空间复杂度：O(1)，仅使用常数个变量。
#include <iostream>

using namespace std;

int main() {
    int n;
    if (!(cin >> n)) return 0;

    int steps = 0;
    while (n != 1) {
        if (n % 2 == 0) {
            n /= 2;            // 偶数：砍掉一半
        } else {
            n = (3 * n + 1) / 2; // 奇数：先算 (3n+1) 再砍掉一半
        }
        ++steps;
    }

    cout << steps << endl;
    return 0;
}