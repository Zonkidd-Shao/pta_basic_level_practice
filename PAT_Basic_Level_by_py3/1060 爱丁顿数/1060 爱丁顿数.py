#
# 输出格式：
#   在一行中给出 N 天的爱丁顿数。
#
# 实现原理：
#   - 排序算法
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   排序与统计：排序后找出满足条件的最大E值，
#   即有E天骑行超过E英里。
