use strict;
use warnings;

# =====================================================================
# 题目：1075 链表元素分类
# 难度：中等
# 知识点：链表, 哈希表映射, 分类排序
# =====================================================================
#
# 【题目描述】
#   给定一个单链表，将所有负值元素排在最前面，[0,K] 区间内的元素次之，
#   大于 K 的元素排在最后。每一类内部保持原有相对顺序。
#
# 【实现原理】
#   1. 用哈希表以地址为键存储每个结点的 (数据, 下一地址)。
#   2. 从表头开始沿 next 遍历链表，按数据大小将结点分别放入三类容器。
#   3. 将三类结点依次拼接，输出每个结点的地址、数据与下一地址（最后一个为 -1）。
#
# 【输入样例】
#   00100 9 10
#   23333 10 27777
#   ...
# 【输出样例】
#   33218 -4 68237
#   ...
# =====================================================================

# 读取表头、结点个数和 K
my $line = <STDIN>; chomp $line;
my ($head, $n, $k) = split /\s+/, $line;

# 用哈希表记录每个地址对应的 [数据, 下一地址]
my %d;
for (1..$n) {
    my $l = <STDIN>; chomp $l;
    my ($a, $x, $nxt) = split /\s+/, $l;
    $d{$a} = [$x, $nxt];
}

# 三类容器：负数 / [0,K] / 大于 K
my @groups = ([], [], []);

# 沿链表顺序遍历，将结点分类
while ($head ne '-1') {
    my ($x, $nxt) = @{$d{$head}};
    my $g = $x < 0 ? 0 : ($x <= $k ? 1 : 2);
    push @{$groups[$g]}, [$head, $x];
    $head = $nxt;
}

# 将三类结点按顺序拼接
my @a = (@{$groups[0]}, @{$groups[1]}, @{$groups[2]});

# 输出重排后的链表，最后一结点的 next 为 -1
for (my $i = 0; $i < @a; $i++) {
    my $nextout = $i + 1 < @a ? $a[$i + 1][0] : '-1';
    print "$a[$i][0] $a[$i][1] $nextout\n";
}
