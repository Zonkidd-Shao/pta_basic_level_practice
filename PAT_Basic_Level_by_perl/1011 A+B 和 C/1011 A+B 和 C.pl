use strict;
use warnings;

# =====================================================================
# 题目：1011 A+B 和 C
# 难度：入门
# 知识点：大整数运算、条件判断
# =====================================================================
#
# 【题目描述】
#   给定区间 [-2^31, 2^31] 内的 3 个整数 A、B 和 C，判断 A+B 是否大于 C。
#
# 【实现原理】
#   1. 大整数处理：
#      - 题目给出的范围是 [-2^31, 2^31]，即 32 位有符号整数范围
#      - 在 C/C++ 等语言中，两个 32 位整数相加可能溢出
#      - 但 Perl 原生支持任意精度的大整数运算，因此直接相加即可，
#        无需担心溢出问题
#   2. 多组测试用例：
#      - 第一行给出测试用例数 T
#      - 随后 T 行每行一组 A B C
#      - 对每组计算 A+B > C 是否成立
#   3. 输出格式：Case #i: true/false
#   4. 时间复杂度：O(T)，每组测试用例 O(1) 运算。
#   5. 空间复杂度：O(1)。
#
# 【输入样例】
#   4
#   1 2 3
#   2 3 4
#   2147483647 0 2147483646
#   0 -2147483648 -2147483647
# 【输出样例】
#   Case #1: false
#   Case #2: true
#   Case #3: true
#   Case #4: false
# =====================================================================

# 读取测试用例数 T
my $T = <STDIN>;
chomp $T;

# 遍历 T 组测试用例
for my $i (1 .. $T) {
    # 读取一行 A B C
    my $line = <STDIN>;
    chomp $line;
    my ($a, $b, $c) = split /\s+/, $line;
    # Perl 原生支持大整数，直接相加比较即可
    my $ok = ($a + $b) > $c;
    # 按格式输出结果
    print "Case #$i: ", ($ok ? 'true' : 'false'), "\n";
}
