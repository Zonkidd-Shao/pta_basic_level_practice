# 题目：1062 最简分数
#
# 题目描述：
#   一个分数一般写成两个整数相除的形式：N/M，其中 M 不为0。最简分数是指分子和分母没有公约数的分数表示形式。
#   现给定两个不相等的正分数 N_1/M_1 和 N_2/M_2，要求你按从小到大的顺序列出它们之间分母为 K 的最简分数。
#
# 输入格式：
#   输入在一行中按 N/M 的格式给出两个正分数，随后是一个正整数分母 K，其间以空格分隔。题目保证给出的所有整数都不超过 10000。
#
# 输出格式：
#   在一行中按 N/M 的格式列出两个给定分数之间分母为 K 的所有最简分数，按从小到大的顺序，其间以 1 个空格分隔。行首尾不得有多余空格。题目保证至少有 1 个输出。
#
# 实现原理：
#   - 排序算法
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   分数与最大公约数：找出指定范围内的最简分数，
#   使用辗转相除法判断是否互质。
#
import sys, math
from fractions import Fraction

a,b,n=sys.stdin.read().split(); a,b=sorted([Fraction(a),Fraction(b)]); n=int(n); print(*[f'{i}/{n}' for i in range(1,n) if a<Fraction(i,n)<b and math.gcd(i,n)==1])
