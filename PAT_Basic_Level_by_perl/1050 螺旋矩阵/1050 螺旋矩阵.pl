use strict;
use warnings;

# =====================================================================
# 题目：1050 螺旋矩阵
# 难度：中等
# 知识点：排序, 模拟
# =====================================================================
#
# 【题目描述】
#   将 N 个正整数按非递增顺序填入螺旋矩阵：从左上角开始，按顺时针螺旋方向填充。
#   矩阵规模为 m 行 n 列，满足 m*n=N、m>=n 且 m-n 最小。
#
# 【实现原理】
#   1. 对输入数字降序排序。
#   2. 求满足条件的行数 m（m>=n 且 m-n 最小），列数 n=N/m。
#   3. 维护上、下、左、右四个边界，按顺时针方向逐层填充。
#   4. 逐行输出，行内以空格分隔、行末无多余空格。
#
# 【输入样例】
#   12
#   37 76 20 98 76 42 53 95 60 81 58 93
# 【输出样例】
#   98 95 93
#   42 37 81
#   53 20 76
#   58 60 76
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);   # 读取全部输入
my $N = shift @tok;                         # 数字总数
my @a = sort { $b <=> $a } @tok;            # 降序排序

my $m = int(sqrt($N));
$m++ if $m * $m < $N;                       # 向上取整到 ceil(sqrt(N))
$m++ while $N % $m != 0;                    # 找到最小的 m 使 N 可被整除且 m>=sqrt(N)
my $n = $N / $m;                            # 列数（n = N/m，m>=n）

my @mat;
for (my $i = 0; $i < $m; $i++) {
    $mat[$i] = [ (0) x $n ];                # 初始化矩阵
}

my ($top, $bot, $left, $right) = (0, $m - 1, 0, $n - 1);
my $idx = 0;
while ($idx < $N) {
    for (my $j = $left; $j <= $right; $j++) { $mat[$top][$j] = $a[$idx++]; }  # 从左到右
    $top++;
    for (my $i = $top; $i <= $bot; $i++) { $mat[$i][$right] = $a[$idx++]; }   # 从上到下
    $right--;
    if ($top <= $bot) {                                                       # 从右到左
        for (my $j = $right; $j >= $left; $j--) { $mat[$bot][$j] = $a[$idx++]; }
        $bot--;
    }
    if ($left <= $right) {                                                    # 从下到上
        for (my $i = $bot; $i >= $top; $i--) { $mat[$i][$left] = $a[$idx++]; }
        $left++;
    }
}

for (my $i = 0; $i < $m; $i++) {
    print join(' ', @{$mat[$i]}), "\n";
}