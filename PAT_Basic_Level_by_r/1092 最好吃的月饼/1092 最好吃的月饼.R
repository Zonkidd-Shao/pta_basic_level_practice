# 题目名称：最好吃的月饼
# 题目编号：PAT Basic 1092
# 实现原理：
#   统计每种月饼在所有城市的总销量，找出销量最大的月饼种类。
#   关键步骤：
#   1. 读取月饼种类数N和城市数M
#   2. 读取M*N个销量数据（按行优先存储：每行N个数据，共M行
#   3. 由于R语言按列存储，直接将所有数据读入一维数组后，
#      每种月饼的总销量就是该位置开始每隔N个位置的数之和？
#      不，实际上scan按顺序读取，第i种月饼的销量是所有第i个位置的数之和
#   4. 找出最大销量值
#   5. 找出所有销量等于最大值的月饼种类编号
#   6. 输出最大销量和并列的种类编号
#   由于输入是M行，每行N个数，所以第i种月饼总销量需要累加每行第i个元素。
#   利用R语言向量化操作，可以用矩阵或数组更高效。
# 时间复杂度：O(N * M)，读取和计算所有月饼总销量
# 空间复杂度：O(N * M)，存储所有销量数据
z<-as.integer(scan("stdin",quiet=TRUE));n<-z[1];m<-z[2];a<-matrix(z[-c(1,2)],nrow=m,byrow=TRUE);tot<-colSums(a);mx<-max(tot);cat(mx,"\n",paste(which(tot==mx),collapse=" "),"\n",sep="")
