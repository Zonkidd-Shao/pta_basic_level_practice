use strict;
use warnings;

# =====================================================================
# 题目：1009 说反话
# 难度：入门
# 知识点：字符串分割、数组反转、字符串拼接
# =====================================================================
#
# 【题目描述】
#   给定一句英语，将句中所有单词的顺序颠倒输出。
#   单词由英文字母组成，单词之间用一个空格分隔。
#
# 【实现原理】
#   1. 字符串分割：使用 split /\s+/ 将输入字符串按空白字符分割成单词数组。
#      - \s+ 匹配一个或多个空白字符（空格、制表符等）
#      - 这样可以处理多个空格分隔的情况
#   2. 数组反转：使用 reverse 函数将单词数组的顺序反转。
#   3. 字符串拼接：使用 join ' ' 将反转后的单词数组用单个空格连接成字符串。
#   4. 输出结果。
#   5. 时间复杂度：O(L)，L 为字符串长度。
#   6. 空间复杂度：O(L)，存储单词数组。
#
# 【输入样例】 Hello World Here I Come
# 【输出样例】 Come I Here World Hello
# =====================================================================

# 读取一行输入
my $line = <STDIN>;
# 去除行尾换行符
chomp $line;
# 按空白字符分割成单词数组
my @w = split /\s+/, $line;
# 反转单词数组并用空格连接后输出
print join(' ', reverse @w), "\n";
