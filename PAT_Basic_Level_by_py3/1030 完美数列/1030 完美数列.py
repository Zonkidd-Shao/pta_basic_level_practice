# 题目：1030 完美数列
#
# 题目描述：
#   给定一个正整数数列，和正整数 p，设这个数列中的最大值是 M，最小值是 m，如果 M \le mp，则称这个数列是完美数列。
#   现在给定参数 p 和一些正整数，请你从中选择尽可能多的数构成一个完美数列。
#
# 输入格式：
#   输入第一行给出两个正整数 N 和 p，其中 N（\le 10^5）是输入的正整数的个数，p（\le 10^9）是给定的参数。第二行给出 N 个正整数，每个数不超过 10^9。
#
# 输出格式：
#   在一行中输出最多可以选择多少个数可以用它们组成一个完美数列。
#
# 实现原理：
#   - 排序算法
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   滑动窗口/双指针：排序后使用双指针法，
#   找出满足条件的最长子序列。
#
import sys

_, p = map(int, sys.stdin.readline().split()); a = sorted(map(int, sys.stdin.readline().split()))
best = i = 0
for j, x in enumerate(a):
    while x > a[i] * p: i += 1
    best = max(best, j - i + 1)
print(best)
