use strict;
use warnings;

# =====================================================================
# 题目：1105 链表合并
# 难度：中等
# 知识点：链表, 哈希表, 模拟
# =====================================================================
#
# 【题目描述】
#   给定两个单链表，把较短链表逆序后间隔并入较长链表：
#   每两个长链表结点后插入一个短链表结点（逆序）。
#   较长链表至少是较短链表的两倍长，输出合并后的链表。
#
# 【实现原理】
#   1. 用哈希表存储 地址 -> [数据, 下一地址] 的映射。
#   2. 从两个头结点分别遍历得到结点顺序数组。
#   3. 保证 $a 为较长链表，$b 为较短链表。
#   4. 遍历 $a：每两个结点（下标为奇数时）从 $b 尾部弹出一个结点插入，
#      相当于把较短链表逆序并入；剩余部分逆序补在末尾。
#   5. 按顺序输出每个结点的地址、数据和下一地址。
#
# 【输入样例】
#   00100 01000 7
#   02233 2 34891
#   00100 6 00001
#   34891 3 10086
#   01000 1 02233
#   00033 5 -1
#   10086 4 00033
#   00001 7 -1
# 【输出样例】
#   01000 1 02233
#   02233 2 00001
#   00001 7 34891
#   34891 3 10086
#   10086 4 00100
#   00100 6 00033
#   00033 5 -1
# =====================================================================

my $line = <STDIN>;
chomp $line;
my ($h1, $h2, $n) = split / +/, $line;

# 结点映射：地址 -> [数据, 下一地址]
my %node;
for (1 .. $n) {
    my $l = <STDIN>;
    chomp $l;
    my ($addr, $data, $next) = split / +/, $l;
    $node{$addr} = [$data, $next];
}

# 从头结点出发，返回链表各结点地址的顺序数组
sub walk {
    my $h = shift;
    my @r;
    while ($h ne '-1') {
        push @r, $h;
        $h = $node{$h}[1];
    }
    return @r;
}

my @a = walk($h1);
my @b = walk($h2);
# 保证 $a 是较长链表，$b 是较短链表
if (@a < @b) {
    my @tmp = @a;
    @a = @b;
    @b = @tmp;
}

# 合并：每两个长链表结点后插入一个短链表结点（从尾部弹出 = 逆序）
my @out;
for (my $i = 0; $i < @a; $i++) {
    push @out, $a[$i];
    if ($i % 2 == 1 && @b) {
        push @out, pop @b;
    }
}
# 短链表剩余部分逆序补在末尾
push @out, reverse @b;

# 按顺序输出每个结点
for (my $i = 0; $i < @out; $i++) {
    my $nxt = ($i + 1 < @out) ? $out[$i + 1] : '-1';
    print "$out[$i] $node{$out[$i]}[0] $nxt\n";
}
