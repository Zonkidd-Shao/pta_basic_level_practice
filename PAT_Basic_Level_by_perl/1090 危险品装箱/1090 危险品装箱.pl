use strict;
use warnings;

# =====================================================================
# 题目：1090 危险品装箱
# 难度：中等
# 知识点：哈希表, 模拟
# =====================================================================
#
# 【题目描述】
#   给定 N 对不相容物品（每件用 5 位数字编号），检查 M 箱货物，
#   若一箱中出现任一对不相容物品则输出 No，否则输出 Yes。
#
# 【实现原理】
#   1. 用哈希表保存所有不相容物品对（双向）
#   2. 对每箱货物，两两检查是否有不相容对
#   3. 发现不相容对即输出 No，否则输出 Yes
# =====================================================================
#
# 【输入样例】
#   6 3
#   20001 20002
#   20003 20004
#   20005 20006
#   20003 20001
#   20005 20004
#   20004 20006
#   4 00001 20004 00002 20003
#   5 98823 20002 20003 20006 10010
#   3 12345 67890 23333
# 【输出样例】
#   No
#   Yes
#   Yes
# =====================================================================

# 一次性读取全部输入
my @tok = split /\s+/, join('', <STDIN>);
my $n = shift @tok;   # 不相容对数量
my $m = shift @tok;   # 货物清单数量

my %bad;
# 读取不相容物品对，双向记录
for (1 .. $n) {
    my $u = shift @tok;
    my $v = shift @tok;
    $bad{"$u $v"} = 1;
    $bad{"$v $u"} = 1;
}

# 处理每箱货物
for (1 .. $m) {
    my $k = shift @tok;              # 货物件数
    my @g = splice(@tok, 0, $k);     # 取出本箱货物
    my $ok = 1;
    # 两两检查是否有不相容对
    OUTER:
    for my $i (0 .. $#g) {
        for my $j ($i + 1 .. $#g) {
            if ($bad{"$g[$i] $g[$j]"}) {
                $ok = 0;
                last OUTER;
            }
        }
    }
    print $ok ? "Yes\n" : "No\n";
}
