use strict;
use warnings;

# =====================================================================
# 题目：1057 数零壹
# 难度：简单
# 知识点：进制转换, 字符串处理
# =====================================================================
#
# 【题目描述】
#   给定一串字符串，将所有英文字母的序号（a-z 对应 1-26，不分大小写）
#   相加得到整数 N，再统计 N 的二进制表示中 0 和 1 的个数。
#
# 【实现原理】
#   1. 遍历字符串，累加字母序号（统一转小写计算）。
#   2. 将和转换为二进制字符串，分别统计 0 和 1 的个数。
#   3. 若没有字母则和不存在，输出 0 0。
#
# 【输入样例】
#   PAT (Basic)
# 【输出样例】
#   3 4
# =====================================================================

my $line = <STDIN>;
chomp $line;
my $sum = 0;
for my $ch (split //, $line) {
    if ($ch =~ /[a-zA-Z]/) {
        $sum += ord(lc $ch) - ord('a') + 1;   # 字母序号 1-26
    }
}
if ($sum == 0) {
    print "0 0\n";   # 不存在字母，无 0 和 1
} else {
    my $bin = sprintf("%b", $sum);            # 转为二进制
    my $z = ($bin =~ tr/0//);                 # 统计 0 的个数
    my $o = ($bin =~ tr/1//);                 # 统计 1 的个数
    print "$z $o\n";
}
