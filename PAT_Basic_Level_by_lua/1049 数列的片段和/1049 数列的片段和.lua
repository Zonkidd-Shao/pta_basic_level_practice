-- 题目编号: 1049 数列的片段和
-- 实现原理: 所有连续子序列中，第 i 个元素出现的次数为 i × (n - i + 1)。直接利用该公式累加每个元素的贡献总和，避免枚举所有子序列，时间复杂度 O(n)。

-- n: 数列长度，sum: 所有片段和的总和
local n, sum = io.read("*n"), 0

-- 遍历每个元素，计算其在所有连续子序列中出现的次数并累加
-- 第 i 个元素（1-based）出现的次数 = i * (n - i + 1)
-- 解释：左边有 i 种选择（包含第 i 个元素的左端点），右边有 n-i+1 种选择（右端点）
for i = 1, n do
    sum = sum + io.read("*n") * i * (n - i + 1)
end

-- 输出结果，保留两位小数
print(string.format("%.2f", sum))
