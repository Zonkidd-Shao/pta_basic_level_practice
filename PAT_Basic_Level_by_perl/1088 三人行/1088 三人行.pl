use strict;
use warnings;

# =====================================================================
# 题目：1088 三人行
# 难度：中等
# 知识点：数学, 条件判断
# =====================================================================
#
# 【题目描述】
#   甲是 2 位正整数，乙是甲的数字调换位置所得；
#   |甲-乙| = X * 丙，乙 = Y * 丙。
#   给定你自己的能力值 M、X、Y，求满足条件的最大甲，
#   并输出甲、乙、丙与你的关系（强 Cong / 等 Ping / 弱 Gai）。
#
# 【实现原理】
#   1. 从大到小枚举甲 a（99..10）
#   2. 乙 b = 甲的数字反转，丙 c = |a-b|
#   3. 判断条件：c*y == b*x（即 |甲-乙|/X == 乙/Y）
#   4. 命中即输出甲的数值及甲乙丙三者与 M 的关系
#   5. 无解输出 No Solution
# =====================================================================
#
# 【输入样例】
#   48 3 7
# 【输出样例】
#   48 Ping Cong Gai
# =====================================================================

# 读取 M、X、Y
my @tok = split /\s+/, <STDIN>;
my ($m, $x, $y) = @tok;

my $found = 0;
# 从大到小枚举甲，保证取最大解
for (my $a = 99; $a >= 10; $a--) {
    # 乙 = 甲数字调换
    my $b = reverse "$a";
    $b += 0;
    # 丙 = |甲 - 乙|
    my $c = abs($a - $b);
    # 判断关系：|甲-乙| 是丙的 X 倍，乙是丙的 Y 倍
    if ($c * $y == $b * $x) {
        # 依次判断甲、乙、丙与 M 的关系
        my @rel;
        for my $v ($a, $b, $c) {
            if    ($v == $m) { push @rel, 'Ping'; }
            elsif ($v >  $m) { push @rel, 'Cong'; }
            else             { push @rel, 'Gai';  }
        }
        print "$a @rel\n";
        $found = 1;
        last;
    }
}

# 无解时输出 No Solution
print "No Solution\n" unless $found;
