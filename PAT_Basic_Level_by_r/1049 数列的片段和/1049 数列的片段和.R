# 题目名称：数列的片段和
# 题目编号：PAT Basic 1049
# 实现原理：
#   数学推导：对于第 i 个数（1 开始索引），它出现在多少个片段中？
#   片段的左端点可以是 1~i（共 i 种选择），
#   片段的右端点可以是 i~n（共 n-i+1 种选择），
#   因此第 i 个数总共出现 i*(n-i+1) 次。
#   总和 = sum(a[i] * i * (n-i+1))。
#   利用向量化运算一次性计算所有数的贡献，时间复杂度最优。
# 时间复杂度：O(N)，N 为数列长度
# 空间复杂度：O(N)
z<-scan("stdin",what=double(),quiet=TRUE);n<-z[1];a<-z[-1];cat(sprintf("%.2f\n",sum(a*seq_len(n)*(n:1))))
