use strict;
use warnings;

# =====================================================================
# 题目：1020 月饼
# 难度：简单
# 知识点：排序, 贪心算法
# =====================================================================
#
# 【题目描述】
#   给定 N 种月饼的库存量、总售价以及市场最大需求量 D，
#   允许只卖出部分库存，求可获得的最大收益（亿元，保留两位小数）。
#
# 【实现原理】
#   1. 按单价（总售价/库存量）从高到低对月饼排序。
#   2. 依次取单价最高的月饼，尽量满足需求，累加收益。
#   3. 需求满足后立即停止，输出两位小数。
#
# 【输入样例】
#   3 20
#   18 15 10
#   75 72 45
# 【输出样例】
#   94.50
# =====================================================================

# 读取所有数字
my @tok = split /\s+/, join('', <STDIN>);
my $n   = shift @tok;
my $cap = shift @tok;

my @stocks = ();
my @values = ();
for my $i (0 .. $n-1) { $stocks[$i] = shift @tok; }
for my $i (0 .. $n-1) { $values[$i] = shift @tok; }

# 按单价降序排列（值/库存）
my @idx = sort { $values[$b]/$stocks[$b] <=> $values[$a]/$stocks[$a] } 0 .. $n-1;

my $ans = 0;
for my $i (@idx) {
    my $take = $stocks[$i] < $cap ? $stocks[$i] : $cap;   # 最多取 min(库存, 需求)
    $ans += $take * $values[$i] / $stocks[$i];
    $cap -= $take;
    last if $cap <= 0;                                    # 需求满足则停止
}

printf "%.2f\n", $ans;