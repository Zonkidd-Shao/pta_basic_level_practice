use strict;
use warnings;

# =====================================================================
# 题目：1060 爱丁顿数
# 难度：中等
# 知识点：排序, 贪心算法
# =====================================================================
#
# 【题目描述】
#   给定某人 N 天的骑车距离，求爱丁顿数 E，即满足有 E 天骑车超过
#   E 英里的最大整数 E（E <= N）。
#
# 【实现原理】
#   1. 将骑车距离按从大到小排序。
#   2. 第 i 天（1 起）对应第 i 大的距离，若该距离 > i，则 E 至少为 i。
#   3. 遍历并记录满足 a[i-1] > i 的最大 i，即为答案。
#
# 【输入样例】
#   10
#   6 7 6 9 3 10 8 2 7 8
# 【输出样例】
#   6
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
shift @tok;                            # 去掉 N
my @a = sort { $b <=> $a } @tok;       # 降序排序
my $e = 0;
for my $i (1 .. scalar @a) {
    if ($a[$i - 1] > $i) {             # 第 i 大的距离 > i
        $e = $i;
    } else {
        last;
    }
}
print "$e\n";
