use strict;
use warnings;

# =====================================================================
# 题目：1100 校庆
# 难度：中等
# 知识点：哈希查找, 生日比较
# =====================================================================
#
# 【题目描述】
#   已知校友身份证号集合和到场来宾身份证号集合。统计到场校友人数；
#   第二行输出最年长的到场校友身份证号（身份证第 7~14 位是 yyyymmdd 生日），
#   若没有校友到场则输出最年长的来宾身份证号。
#
# 【实现原理】
#   1. 用哈希表存储校友身份证号
#   2. 过滤出到场的校友，按身份证第 7~14 位生日取最小者；
#      无校友到场时在所有来宾中按生日取最小者
#
# 【输入样例】
#   5
#   372928196906118710
#   610481197806202213
#   440684198612150417
#   13072819571002001X
#   150702193604190912
#   6
#   530125197901260019
#   150702193604190912
#   220221196701020034
#   610481197806202213
#   440684198612150417
#   370205198709275042
# 【输出样例】
#   3
#   150702193604190912
# =====================================================================

my $n = <STDIN>; chomp $n;                     # 校友人数
my %alumni;                                    # 校友身份证号集合
for (1 .. $n) {
    my $id = <STDIN>; chomp $id;
    $alumni{$id} = 1;
}

my $m = <STDIN>; chomp $m;                     # 到场来宾人数
my @guests;
for (1 .. $m) {
    my $id = <STDIN>; chomp $id;
    push @guests, $id;
}

my @attend = grep { $alumni{$_} } @guests;     # 到场的校友
print scalar(@attend), "\n";

if (@attend) {
    # 按生日 yyyymmdd（身份证第 7~14 位，0 起始下标 6 起取 8 位）取最小者
    my $oldest = $attend[0];
    for (@attend) {
        $oldest = $_ if substr($_, 6, 8) lt substr($oldest, 6, 8);
    }
    print "$oldest\n";
} else {
    # 无校友到场，在所有来宾中取最年长者
    my $oldest = $guests[0];
    for (@guests) {
        $oldest = $_ if substr($_, 6, 8) lt substr($oldest, 6, 8);
    }
    print "$oldest\n";
}