use strict;
use warnings;

# =====================================================================
# 题目：1022 D进制的A+B
# 难度：简单
# 知识点：进制转换
# =====================================================================
#
# 【题目描述】
#   输入两个非负十进制整数 A、B 及进制 D，
#   输出 A+B 的 D 进制表示。
#
# 【实现原理】
#   1. 求出和 n = A + B。
#   2. 用除基取余法将 n 逐位转换为 D 进制。
#   3. 若和为 0，直接输出 0。
#
# 【输入样例】
#   123 456 8
# 【输出样例】
#   1103
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
my ($a, $b, $d) = @tok;

my $n = $a + $b;
if ($n == 0) {
    print "0\n";
} else {
    my $out = '';
    while ($n > 0) {
        $out = ($n % $d) . $out;   # 取最低位，拼到结果前面
        $n = int($n / $d);
    }
    print "$out\n";
}