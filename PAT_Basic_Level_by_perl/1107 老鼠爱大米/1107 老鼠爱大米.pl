use strict;
use warnings;

# =====================================================================
# 题目：1107 老鼠爱大米
# 难度：简单
# 知识点：最大值查找, 循环
# =====================================================================
#
# 【题目描述】
#   N 组、每组 M 只老鼠，第一行输出每组最重老鼠的体重，
#   第二行输出所有分组冠军中最重的体重。
#
# 【实现原理】
#   1. 每组读取 M 个体重，取最大值作为分组冠军。
#   2. 收集所有分组冠军，再求最大值。
#   3. 分两行输出。
#
# 【输入样例】
#   3 5
#   62 53 88 72 81
#   12 31 9 0 2
#   91 42 39 6 48
# 【输出样例】
#   88 31 91
#   91
# =====================================================================

my $line = <STDIN>;
chomp $line;
my ($n, $m) = split / +/, $line;

my @champs;
for (1 .. $n) {
    my $l = <STDIN>;
    chomp $l;
    my @w = split / +/, $l;
    # 求本组最大值
    my $mx = 0;
    for (@w) {
        $mx = $_ if $_ > $mx;
    }
    push @champs, $mx;
}

# 分组冠军中的最大值
my $top = 0;
for (@champs) {
    $top = $_ if $_ > $top;
}

print join(' ', @champs), "\n";
print "$top\n";
