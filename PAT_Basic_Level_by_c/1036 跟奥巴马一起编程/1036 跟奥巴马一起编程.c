/*
 * 题目：1036 跟奥巴马一起编程
 * 实现原理：
 *   输出一个矩形图案，行数为(n+1)/2，每行n个字符。
 *   图案规则：
 *   - 第一行和最后一行全部为字符c
 *   - 中间行只有首尾两个字符为c，其余为空格
 *   算法步骤：
 *   1. 计算行数rows = (n + 1) / 2（向下取整）
 *   2. 遍历每一行，判断当前位置是否在边界
 *   3. 边界位置输出c，非边界位置输出空格
 */
#include <stdio.h>

int main() {
    int n;
    char c;
    scanf("%d %c", &n, &c);
    int rows = (n + 1) / 2;  // 行数取列数的一半（四舍五入）
    for (int i = 0; i < rows; i++) {  // 逐行输出
        for (int j = 0; j < n; j++) {  // 每行 n 个位置
            if (i == 0 || i == rows - 1 || j == 0 || j == n - 1) {  // 首行/末行/首列/末列 → 边界输出字符
                printf("%c", c);
            } else {
                printf(" ");  // 内部输出空格
            }
        }
        printf("\n");
    }
    return 0;
}