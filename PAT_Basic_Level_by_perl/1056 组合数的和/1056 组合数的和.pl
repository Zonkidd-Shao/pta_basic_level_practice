use strict;
use warnings;

# =====================================================================
# 题目：1056 组合数的和
# 难度：简单
# 知识点：数学公式, 循环迭代
# =====================================================================
#
# 【题目描述】
#   给定 N 个非 0 的个位数字，用其中任意 2 个数字都可以组合成一个
#   2 位的数字，要求所有可能组合出来的 2 位数字之和。
#
# 【实现原理】
#   1. 每个数字作为十位会出现 (N-1) 次，作为个位也会出现 (N-1) 次。
#   2. 因此每个数字的贡献为 x*10*(N-1) + x*(N-1) = x*11*(N-1)。
#   3. 总和 = 11 * (N-1) * sum(所有数字)。
#
# 【输入样例】
#   3 2 8 5
# 【输出样例】
#   330
# =====================================================================

my @tok = split /\s+/, <STDIN>;
shift @tok;            # 去掉开头的 N
my $n = scalar @tok;   # 实际数字个数
my $sum = 0;
$sum += $_ for @tok;   # 累加所有数字
print $sum * 11 * ($n - 1), "\n";
