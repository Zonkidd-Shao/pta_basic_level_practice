use strict;
use warnings;

# =====================================================================
# 题目：1082 射击比赛
# 难度：简单
# 知识点：距离计算, 极值查找
# =====================================================================
#
# 【题目描述】
#   每个运动员打一枪，弹洞坐标为 (x,y)，靶心在原点 (0,0)。
#   距离靶心最近的是冠军，最远的是菜鸟。输出冠军和菜鸟的编号。
#
# 【实现原理】
#   1. 距离平方 d = x^2 + y^2 可直接用于比较大小。
#   2. 遍历所有运动员，记录最小距离对应的编号（冠军）和
#      最大距离对应的编号（菜鸟）。
#   3. 输出"冠军 菜鸟"。
#
# 【输入样例】
#   3
#   0001 5 7
#   1020 -1 3
#   0233 0 -1
# 【输出样例】
#   0233 0001
# =====================================================================

# 读取运动员人数 N
my $n = <STDIN>; chomp $n;

my ($minid, $maxid, $mind, $maxd);
my $first = 1;

for (1..$n) {
    my $l = <STDIN>; chomp $l;
    my ($id, $x, $y) = split /\s+/, $l;

    # 距离的平方，用于比较远近
    my $d = $x * $x + $y * $y;

    if ($first) {
        # 初始化第一个运动员
        $minid = $maxid = $id;
        $mind = $maxd = $d;
        $first = 0;
    } else {
        # 更新最近（冠军）
        if ($d < $mind) { $mind = $d; $minid = $id; }
        # 更新最远（菜鸟）
        if ($d > $maxd) { $maxd = $d; $maxid = $id; }
    }
}

print "$minid $maxid\n";
