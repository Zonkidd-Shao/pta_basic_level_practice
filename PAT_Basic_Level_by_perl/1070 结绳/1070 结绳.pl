use strict;
use warnings;

# =====================================================================
# 题目：1070 结绳
# 难度：简单
# 知识点：排序, 贪心算法
# =====================================================================
#
# 【题目描述】
#   每次把两段绳子对折后连接，长度减半。给定 N 段绳长，
#   求能串成的最大长度（结果向下取整）。
#
# 【实现原理】
#   1. 按长度升序排序。
#   2. 每次都把最短的两段打结，等价于从短到长依次叠加折半：
#      ans = (ans + 下一段) / 2。
#   3. 输出 ans 的整数部分（向下取整）。
#
# 【输入样例】
#   8
#   10 15 12 3 4 13 1 15
# 【输出样例】
#   14
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
shift @tok;                       # 跳过 N
my @a = sort { $a <=> $b } @tok;  # 绳长升序

my $ans = shift @a;
for my $x (@a) {
    $ans = ($ans + $x) / 2;       # 与下一段对折连接
}
print int($ans), "\n";            # 向下取整