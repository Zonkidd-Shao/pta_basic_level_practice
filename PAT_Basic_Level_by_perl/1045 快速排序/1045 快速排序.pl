use strict;
use warnings;

# =====================================================================
# 题目：1045 快速排序
# 难度：中等
# 知识点：前缀最大值, 后缀最小值, 数组
# =====================================================================
#
# 【题目描述】
#   快速排序的划分中，主元的左边都比它小、右边都比它大。
#   给定 N 个互不相同的正整数的排列，求所有可能作为主元的元素，
#   输出个数并按递增顺序输出这些元素。
#
# 【实现原理】
#   1. 后缀最小值数组 suffix[i]：表示 a[i] 之后所有元素的最小值。
#   2. 从左到右扫描，维护前缀最大值 m（当前元素之前所有元素的最大值）。
#   3. 若 a[i] > m 且 a[i] < suffix[i]，则该元素可能是主元。
#   4. 因元素互不相同，收集到的主元已按原序递增，直接输出。
#   5. 时间复杂度 O(N)，空间复杂度 O(N)。
#
# 【输入样例】
#   5
#   1 3 2 4 5
# 【输出样例】
#   3
#   1 4 5
# =====================================================================

# 读取元素个数 N
my $n = <STDIN>;
chomp $n;

# 读取 N 个元素
my @a = split /\s+/, <STDIN>;

# suffix[i] = a[i] 之后（不含 i）所有元素的最小值
my @suffix = (0) x $n;
my $min = 1e18;                 # 初始为无穷大
for (my $i = $n - 1; $i >= 0; $i--) {
    $suffix[$i] = $min;
    $min = $a[$i] < $min ? $a[$i] : $min;
}

# 从左到右扫描，维护前缀最大值
my @ans;
my $max = -1;                   # 初始为无穷小
for my $i (0 .. $n - 1) {
    # 该元素比左边所有元素大，且比右边所有元素小 → 主元
    if ($a[$i] > $max && $a[$i] < $suffix[$i]) {
        push @ans, $a[$i];
    }
    $max = $a[$i] if $a[$i] > $max;
}

# 输出主元个数
print scalar(@ans), "\n";
# 输出主元列表（互不相同，按原序即递增）
print join(' ', @ans), "\n";
