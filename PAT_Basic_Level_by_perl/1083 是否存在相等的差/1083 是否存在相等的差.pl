use strict;
use warnings;

# =====================================================================
# 题目：1083 是否存在相等的差
# 难度：简单
# 知识点：哈希表, 排序
# =====================================================================
#
# 【题目描述】
#   有 N 张卡片，正面分别写 1..N，背面也写 1..N。
#   每张牌正反面数字相减（大减小）得到一个非负差值，
#   输出所有重复出现的差值（按差值从大到小）及出现次数。
#
# 【实现原理】
#   1. 读取洗牌后的排列，第 i 个数表示正面写 i 的卡片背面的数字
#   2. 计算 abs(背面数字 - 位置)，用哈希统计各差值出现次数
#   3. 按差值从大到小输出出现次数大于 1 的差值及其次数
# =====================================================================
#
# 【输入样例】
#   8
#   3 5 8 6 2 1 4 7
# 【输出样例】
#   5 2
#   3 3
#   2 2
# =====================================================================

# 一次性读取全部输入并按空白切分
my @tok = split /\s+/, join('', <STDIN>);
# 第一个数为卡片数量 N
my $n = shift @tok;

my %cnt;
# 遍历每个位置：第 i 个元素对应位置 (i+1)
for my $i (0 .. $#tok) {
    my $d = $tok[$i] - ($i + 1);
    $d = -$d if $d < 0;   # 取绝对值（大减小）
    $cnt{$d}++;
}

# 按差值从大到小输出出现次数大于 1 的差值
for my $d (sort { $b <=> $a } keys %cnt) {
    print "$d $cnt{$d}\n" if $cnt{$d} > 1;
}
