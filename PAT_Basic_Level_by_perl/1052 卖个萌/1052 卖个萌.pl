use strict;
use warnings;

# =====================================================================
# 题目：1052 卖个萌
# 难度：中等
# 知识点：字符串处理, 模拟
# =====================================================================
#
# 【题目描述】
#   表情由 [左手]([左眼][口][右眼])[右手] 构成。前 3 行分别给出手、眼、口的
#   可选符号集合（每个符号括在 [] 中）。随后给出 K 个请求，每行 5 个数表示
#   左手、左眼、口、右眼、右手在对应集合中的序号（从 1 开始）。序号非法则
#   输出 "Are you kidding me? @\/@"。
#
# 【实现原理】
#   1. 用正则逐个提取每行 [] 内的符号，存入手/眼/口三个数组。
#   2. 对每个请求检查 5 个序号是否都在有效范围内。
#   3. 按顺序拼接输出；含多字节符号，按字节读取与输出、不加 utf8。
#
# 【输入样例】
#   [╮][╭][o][~\][/~]  [<][>]
#    [╯][╰][^][-][=][>][<][@][⊙]
#   [Д][▽][_][ε][^]  ...
#   4
#   1 1 2 2 2
#   6 8 1 5 5
#   3 3 4 3 3
#   2 10 3 9 3
# 【输出样例】
#   ╮(╯▽╰)╭
#   <(@Д=)/~
#   o(^ε^)o
#   Are you kidding me? @\/@
# =====================================================================

my @lines;
while (defined(my $l = <STDIN>)) { chomp $l; push @lines, $l; }

# 提取 [] 内的符号
sub parse_set {
    my ($line) = @_;
    my @set;
    while ($line =~ /\[([^\]]*)\]/g) { push @set, $1; }
    return @set;
}

my @hand = parse_set($lines[0]);   # 手
my @eye  = parse_set($lines[1]);   # 眼
my @mouth = parse_set($lines[2]);  # 口

my $K = $lines[3];
for my $i (4 .. $#lines) {
    my @sel = split /\s+/, $lines[$i];
    # 校验 5 个序号是否合法
    my ($h1, $e1, $m, $e2, $h2) = @sel;
    my $ok =
        $h1 >= 1 && $h1 <= @hand && $h2 >= 1 && $h2 <= @hand &&
        $e1 >= 1 && $e1 <= @eye  && $e2 >= 1 && $e2 <= @eye &&
        $m  >= 1 && $m  <= @mouth;
    if (!$ok) {
        print "Are you kidding me? \@\\/\@\n";
    } else {
        print $hand[$h1-1], '(', $eye[$e1-1], $mouth[$m-1], $eye[$e2-1], ')', $hand[$h2-1], "\n";
    }
}