# 题目名称：卖个萌
# 题目编号：PAT Basic 1052
# 实现原理：
#   读取输入字符串，按下划线 _ 分割成多个部分。
#   输出格式为：先输出 (^_^)，然后对每个分割后的部分用括号包裹并拼接起来。
#   使用 scan 读取输入，strsplit 分割字符串，paste0 拼接结果。
# 时间复杂度：O(n)，n 为输入字符串长度
# 空间复杂度：O(n)
x<-scan("stdin",what="",quiet=TRUE);p<-strsplit(x,"_")[[1]];cat("(^_^)",paste0("(",p, ")",collapse=""),"\n")
