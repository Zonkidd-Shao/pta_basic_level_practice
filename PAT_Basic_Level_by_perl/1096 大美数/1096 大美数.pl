use strict;
use warnings;

# =====================================================================
# 题目：1096 大美数
# 难度：中等
# 知识点：因数枚举, 整除性, 组合枚举
# =====================================================================
#
# 【题目描述】
#   若正整数 N 可以整除它的 4 个不同正因数之和，则称 N 为“大美数”。
#   判断给定的每个正整数是否为“大美数”。
#
# 【实现原理】
#   1. 枚举 N 的所有正因数
#   2. 穷举 4 个不同因数的组合，若存在组合其和能被 N 整除则输出 Yes
#
# 【输入样例】
#   3
#   18 29 40
# 【输出样例】
#   Yes
#   No
#   Yes
# =====================================================================

my $k = <STDIN>; chomp $k;
my @nums = split /\s+/, <STDIN>;             # 待检测的正整数

# 枚举正整数 x 的所有正因数
sub divisors {
    my $x = shift;
    my @d;
    for (my $i = 1; $i * $i <= $x; $i++) {
        if ($x % $i == 0) {
            push @d, $i;
            push @d, $x / $i if $i != $x / $i;  # 避免平方根重复
        }
    }
    return @d;
}

for my $x (@nums) {
    my @d = divisors($x);
    my $ok = 0;
    my $cnt = scalar @d;

    # 穷举 4 个不同因数的组合，检查其和能否被 x 整除
    OUTER:
    for (my $i = 0; $i < $cnt; $i++) {
        for (my $j = $i + 1; $j < $cnt; $j++) {
            for (my $p = $j + 1; $p < $cnt; $p++) {
                for (my $l = $p + 1; $l < $cnt; $l++) {
                    if (($d[$i] + $d[$j] + $d[$p] + $d[$l]) % $x == 0) {
                        $ok = 1;
                        last OUTER;
                    }
                }
            }
        }
    }
    print $ok ? "Yes\n" : "No\n";
}