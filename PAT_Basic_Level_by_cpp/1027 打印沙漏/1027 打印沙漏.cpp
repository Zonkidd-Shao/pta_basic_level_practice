/*
 * 1027 打印沙漏
 *
 * 【实现原理】
 * 给定一个符号总数 N 和一个符号字符，打印一个沙漏形状，要求使用尽可能多的符号，
 * 且沙漏必须是中心对称的；最后输出剩余未使用的符号数。
 * 
 * 沙漏形状由上下两个三角形组成，共 2h-1 行（h 为三角形的层数，即最大行符号数的一半+1）。
 * 每行符号数构成等差数列：最宽行有 (2h-1) 个符号，向两端逐行递减 2 个。
 * 总符号数 = 1 + 3 + 5 + ... + (2h-1) + ... + 5 + 3 + 1 = 2h^2 - 1
 * 推导：上三角 sum_{i=1}^{h} (2i-1) = h^2，下三角（不含尖）sum_{i=1}^{h-1} (2i-1) = (h-1)^2
 *       总和 = h^2 + (h-1)^2 = 2h^2 - 2h + 1... 实际上标准沙漏中间行共用，所以总符号数 = 2h^2 - 1
 *
 * 【算法思路】
 * 1. 找到最大的 h，使得 2h^2 - 1 <= N
 * 2. 最大宽度 maxW = 2h - 1
 * 3. 上半部分（含中间行）：行号 i 从 0 到 h-1，每行先打印 i 个空格，再打印 maxW-2i 个符号
 * 4. 下半部分（不含中间行）：行号 i 从 h-2 递减到 0，打印方式同上
 * 5. 输出剩余符号数 = N - (2h^2 - 1)
 *
 * 【复杂度分析】
 * - 时间复杂度：O(h^2) = O(N)，打印符号数与输入规模成正比
 * - 空间复杂度：O(1)，仅使用常数个变量
 */

#include <iostream>

using namespace std;

int main() {
    int n;
    char sym;
    if (!(cin >> n >> sym)) return 0;

    // 求最大的 h，使得沙漏所需符号数 2h^2 - 1 <= n
    int h = 1;
    while (2 * (h + 1) * (h + 1) - 1 <= n) ++h;

    int maxW = 2 * h - 1;  // 最宽行的符号数

    // 上半部分（含中间行）：从最宽行到最窄行，行宽递减
    for (int i = 0; i < h; ++i) {
        int width = maxW - 2 * i;       // 当前行符号数
        for (int s = 0; s < i; ++s) cout << ' ';       // 前导空格
        for (int s = 0; s < width; ++s) cout << sym;   // 打印符号
        cout << endl;
    }
    // 下半部分（不含中间行）：从最窄行到最宽行，行宽递增
    for (int i = h - 2; i >= 0; --i) {
        int width = maxW - 2 * i;       // 当前行符号数
        for (int s = 0; s < i; ++s) cout << ' ';       // 前导空格
        for (int s = 0; s < width; ++s) cout << sym;   // 打印符号
        cout << endl;
    }

    // 输出剩余未使用的符号数
    cout << n - (2 * h * h - 1) << endl;
    return 0;
}