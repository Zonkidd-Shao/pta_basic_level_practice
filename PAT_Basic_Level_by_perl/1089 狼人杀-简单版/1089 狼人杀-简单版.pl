use strict;
use warnings;

# =====================================================================
# 题目：1089 狼人杀-简单版
# 难度：中等
# 知识点：枚举, 逻辑推理
# =====================================================================
#
# 【题目描述】
#   N 名玩家中有 2 个狼人、2 个说假话，且狼人中恰有 1 个说假话
#   （有狼人撒谎但并非所有狼人都在撒谎）。
#   每个玩家指出某人是好人(+)或狼人(-)，求最小序列解的 2 个狼人编号。
#
# 【实现原理】
#   1. 暴力枚举所有狼人组合 (i, j)
#   2. 对每组组合，统计说谎者：其言论与事实不符
#   3. 验证：说谎者恰 2 个，且其中恰 1 个是狼人
#   4. 按枚举顺序（递增），第一个满足的即最小解
# =====================================================================
#
# 【输入样例】
#   5
#   -2
#   +3
#   -4
#   +5
#   +4
# 【输出样例】
#   1 4
# =====================================================================

# 一次性读取全部输入
my @tok = split /\s+/, join('', <STDIN>);
my $n = shift @tok;
my @a = @tok;   # 0 索引，a[k] 表示玩家 k+1 说的话

my $found = 0;
# 枚举狼人组合 (i, j)，i<j
for my $i (0 .. $n - 1) {
    for my $j ($i + 1 .. $n - 1) {
        # 统计说谎者
        my @lie;
        for my $k (0 .. $n - 1) {
            my $said_wolf = ($a[$k] < 0);          # 该玩家声称目标为狼人
            my $target    = abs($a[$k]) - 1;       # 目标玩家索引
            my $is_wolf   = ($target == $i || $target == $j);
            # 言论与事实不符即为说谎
            push @lie, $k if $said_wolf != $is_wolf;
        }
        # 恰好 2 人说谎，且其中恰有 1 个狼人
        if (@lie == 2) {
            my $liewolf = 0;
            for my $k (@lie) {
                $liewolf++ if ($k == $i || $k == $j);
            }
            if ($liewolf == 1) {
                print(($i + 1), " ", ($j + 1), "\n");
                $found = 1;
                last;
            }
        }
    }
    last if $found;
}

# 无解输出 No Solution
print "No Solution\n" unless $found;
