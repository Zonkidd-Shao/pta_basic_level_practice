use strict;
use warnings;

# =====================================================================
# 题目：1116 多二了一点
# 难度：简单
# 知识点：字符串, 大数比较
# =====================================================================
#
# 【题目描述】
#   若正整数有偶数个数位，后一半数位组成的数恰好比前一半数位
#   组成的数多 2，则称"多二了一点"。判断输入整数的情况并输出。
#
# 【实现原理】
#   1. 若位数为奇数，输出 Error: X digit(s)。
#   2. 否则取前后两半数字，判断后一半减前一半是否等于 2。
#   3. 按 Yes/No 对应格式输出。
#
# 【输入样例】
#   233235
# 【输出样例】
#   Yes: 235 - 233 = 2
# =====================================================================

# 读取输入字符串（可能很长，不能转成数值）
my $s = <STDIN>;
chomp $s;

if (length($s) % 2) {
    # 奇数个数位
    print "Error: ", length($s), " digit(s)\n";
}
else {
    my $h = int(length($s) / 2);
    my $a = substr($s, 0, $h) + 0;    # 前一半
    my $b = substr($s, $h) + 0;       # 后一半
    if ($b - $a == 2) {
        print "Yes: $b - $a = 2\n";
    }
    else {
        print "No: $b - $a != 2\n";
    }
}
