use strict;
use warnings;

# =====================================================================
# 题目：1080 MOOC期终成绩
# 难度：中等
# 知识点：哈希表映射, 排序, 四舍五入
# =====================================================================
#
# 【题目描述】
#   合并在线编程、期中和期末三张成绩单。若期中 > 期末，
#   总评 = 期中*40% + 期末*60%（四舍五入），否则总评 = 期末。
#   只有编程分 >= 200 且总评 >= 60 的学生合格。
#   按总评降序输出，总评相同按学号升序。
#
# 【实现原理】
#   1. 用哈希表以学号为键，存储 [编程分, 期中, 期末]。
#   2. 计算每个学生的总评，筛选合格者。
#   3. 按 (总评降序, 学号升序) 排序并输出。
#
# 【输入样例】
#   6 6 7
#   01234 880
#   ...
# 【输出样例】
#   missing 400 -1 99 99
#   ...
# =====================================================================

# 读取三块成绩单的行数
my $line = <STDIN>; chomp $line;
my ($p, $m, $n) = split /\s+/, $line;

my %d;   # 学号 -> [编程分, 期中, 期末]

# 在线编程成绩
for (1..$p) {
    my $l = <STDIN>; chomp $l;
    my ($id, $g) = split /\s+/, $l;
    $d{$id} = [$g, -1, -1];
}
# 期中成绩
for (1..$m) {
    my $l = <STDIN>; chomp $l;
    my ($id, $g) = split /\s+/, $l;
    $d{$id} = [-1, -1, -1] unless exists $d{$id};
    $d{$id}[1] = $g;
}
# 期末成绩
for (1..$n) {
    my $l = <STDIN>; chomp $l;
    my ($id, $g) = split /\s+/, $l;
    $d{$id} = [-1, -1, -1] unless exists $d{$id};
    $d{$id}[2] = $g;
}

my @ans;

# 计算总评并筛选合格学生
for my $id (keys %d) {
    my ($g, $mid, $fin) = @{$d{$id}};
    # 期中 > 期末 时按加权公式，否则总评即期末
    my $final = $mid <= $fin ? $fin : int($mid * 0.4 + $fin * 0.6 + 0.5);
    push @ans, [$id, $g, $mid, $fin, $final] if $g >= 200 && $final >= 60;
}

# 按总评降序，相同则学号升序
@ans = sort { $b->[4] <=> $a->[4] || $a->[0] cmp $b->[0] } @ans;

for my $x (@ans) {
    print "$x->[0] $x->[1] $x->[2] $x->[3] $x->[4]\n";
}
