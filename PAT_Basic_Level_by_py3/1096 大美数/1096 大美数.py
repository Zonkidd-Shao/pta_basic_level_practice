# 题目：1096 大美数
#
# 题目描述：
#   若正整数 N 可以整除它的 4 个不同正因数之和，则称这样的正整数为“大美数”。本题就要求你判断任一给定的正整数是否是“大美数”。
#
# 输入格式：
#   输入在第一行中给出正整数 K（\le 10），随后一行给出 K 个待检测的、不超过 10^4 的正整数。
#
# 输出格式：
#   对每个需要检测的数字，如果它是大美数就在一行中输出 `Yes`，否则输出 `No`。
#
# 实现原理：
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   因数与整除性：判断一个数是否为大美数，
#   检查是否存在至少两对因数之和也是该数的因数。
#
import sys

for x in map(int,sys.stdin.read().split()[1:]):
 print('Yes' if all(x%int(c)==0 for c in str(x) if c!='0') else 'No')
