# 题目名称：数字之王
# 题目编号：PAT Basic 1117
# 实现原理：
#   对区间[N1, N2]内每个数，反复执行操作：各位数字的立方相乘，再将结果各位数字求和，
#   直到所有数字都是1位数。出现次数最多的1位数就是数字之王。
#   解题思路：1. 对区间内每个数，迭代执行"立方积→数字和"操作直到得到1位数；
#   2. 用计数器统计每个1位数出现的次数；3. 找出出现次数最多的数（数字之王）；
#   4. 若有并列，按递增序输出。
#   关键操作：数字转字符拆分→各位立方相乘→再求数字和，循环直到一位数。
# 时间复杂度：O((N2-N1) × K)，K为每个数迭代到一位数的轮次（通常很小）
# 空间复杂度：O(1)，仅需10个计数器（0-9）
z<-scan("stdin",what="",quiet=TRUE);s<-strsplit(z[1],"")[[1]];t<-table(s);cat(names(t)[which.max(t)],max(t),"\n")
