/*
 * 1036 跟奥巴马一起编程
 *
 * 【实现原理】
 * 给定正方形的列数 N 和字符 C，输出一个由 C 组成的空心正方形。
 * 列数为 N，行数为 N/2 四舍五入的结果。
 * 正方形的边框用字符 C 填充，内部为空格。
 *
 * 【算法思路】
 * 1. 计算行数 rows = (N + 1) / 2（整数除法实现四舍五入）
 * 2. 双重循环遍历每个位置：
 *    - 第一行、最后一行、第一列、最后一列输出字符 C
 *    - 其余位置输出空格
 * 3. 逐行输出
 *
 * 【关键点】
 * - 行数的四舍五入：由于 N 是整数且 N >= 3，(N + 1) / 2 等价于 round(N/2.0)
 * - 空心正方形的判断条件：i == 0 || i == rows-1 || j == 0 || j == n-1
 *
 * 【复杂度分析】
 * - 时间复杂度：O(N^2)，需要遍历整个正方形区域
 * - 空间复杂度：O(1)，仅使用常数个变量
 */

#include <iostream>

using namespace std;

int main() {
    int n;
    char c;
    if (!(cin >> n >> c)) return 0;

    // 计算行数：N/2 四舍五入，(N+1)/2 在整数除法下等价于 round(N/2)
    int rows = (n + 1) / 2;
    for (int i = 0; i < rows; ++i) {
        for (int j = 0; j < n; ++j) {
            // 空心条件：在边框上（第一/最后一行 或 第一/最后一列）输出字符，否则输出空格
            if (i == 0 || i == rows - 1 || j == 0 || j == n - 1) cout << c;
            else cout << ' ';
        }
        cout << endl;
    }
    return 0;
}