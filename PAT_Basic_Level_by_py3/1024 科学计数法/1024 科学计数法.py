# 题目：1024 科学计数法
#
# 题目描述：
#   科学计数法是科学家用来表示很大或很小的数字的一种方便的方法，其满足正则表达式 [+-][1-9]`.`[0-9]+E[+-][0-9]+，即数字的整数部分只有 1 位，小数部分至少有 1 位，该数字及其指数部分的正负号即使对正数也必定明确给出。
#   现以科学计数法的格式给出实数 A，请编写程序按普通数字表示法输出 A，并保证所有有效位都被保留。
#
# 输入格式：
#   每个输入包含 1 个测试用例，即一个以科学计数法表示的实数 A。该数字的存储长度不超过 9999 字节，且其指数的绝对值不超过 9999。
#
# 输出格式：
#   对每个测试用例，在一行中按普通数字表示法输出 A，并保证所有有效位都被保留，包括末尾的 0。
#
# 实现原理：
#   - 列表操作
#
# 算法思路：
#   字符串解析：解析科学计数法表示的数字，
#   根据指数部分移动小数点位置输出普通表示。
#
import sys

s = sys.stdin.readline().strip(); mantissa, exp = s[1:].split('E'); exp = int(exp); digits = mantissa.replace('.', '')
if s[0] == '-': print('-', end='')
pos = 1 + exp
if pos <= 0: print('0.' + '0' * (-pos) + digits)
elif pos >= len(digits): print(digits + '0' * (pos-len(digits)))
else: print(digits[:pos] + '.' + digits[pos:])
