# 题目名称：复数乘法
# 题目编号：PAT Basic 1051
# 实现原理：
#   两个复数相乘的常规形式计算：(a1 + b1i) * (a2 + b2i) = (a1*a2 - b1*b2) + (a1*b2 + a2*b1)i
#   读入四个参数，直接按照复数乘法公式计算实部和虚部。
#   处理浮点数精度问题：如果绝对值小于 0.005 则视为 0，避免输出 -0.00 这样的格式。
#   使用 sprintf 的 %+ 格式自动处理正负号输出。
# 时间复杂度：O(1)
# 空间复杂度：O(1)
z<-scan("stdin",what=double(),quiet=TRUE);a<-z[1]*z[3]-z[2]*z[4];b<-z[1]*z[4]+z[2]*z[3];cat(sprintf("%.2f%+.2fi\n",ifelse(abs(a)<.005,0,a),ifelse(abs(b)<.005,0,b)))
