use strict;
use warnings;

# =====================================================================
# 题目：1072 开学寄语
# 难度：简单
# 知识点：集合, 字符串处理
# =====================================================================
#
# 【题目描述】
#   检查每个学生携带的物品，列出携带了被查缴物品的学生及其物品编号，
#   最后统计有问题学生人数与被查缴物品总数。
#
# 【实现原理】
#   1. 用哈希记录需要被查缴的物品编号（保持 4 位前导零）。
#   2. 逐个检查学生物品，收集命中的违禁品。
#   3. 输出该生信息并累加人数与物品数。
#
# 【输入样例】
#   4 2
#   2333 6666
#   CYLL 3 1234 2345 3456
#   U 4 9966 6666 8888 6666
#   GG 2 2333 7777
#   JJ 3 0012 6666 2333
# 【输出样例】
#   U: 6666 6666
#   GG: 2333
#   JJ: 6666 2333
#   3 5
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
my $n = shift @tok;   # 学生人数
my $m = shift @tok;   # 违禁品种类数

my %bad;
for (1 .. $m) { $bad{shift @tok} = 1; }

my $people = 0;
my $items  = 0;
for (1 .. $n) {
    my $name = shift @tok;
    my $k    = shift @tok;
    my @found;
    for (1 .. $k) {
        my $it = shift @tok;
        push @found, $it if $bad{$it};
    }
    if (@found) {
        print "$name: ", join(' ', @found), "\n";
        $people++;
        $items += scalar @found;
    }
}
print "$people $items\n";