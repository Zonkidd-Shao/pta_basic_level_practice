/*
 * 题目：1124 最近的斐波那契数
 * 实现原理：
 *   找出与给定数字N最接近的斐波那契数。如果有两个斐波那契数距离相等，取较小的那个。
 *   斐波那契数列定义：F(0)=0, F(1)=1, F(n)=F(n-1)+F(n-2)
 *   算法步骤：
 *   1. 初始化f0=0, f1=1
 *   2. 循环计算直到f1 >= N
 *   3. 此时f0 < N <= f1，比较N-f0和f1-N的大小
 *   4. 如果N-f0 <= f1-N，输出f0；否则输出f1
 */
#include <stdio.h>

int main() {
    int N;
    scanf("%d", &N);        // 目标数字
    int f0 = 0, f1 = 1;     // 相邻的两个斐波那契数
    while (f1 < N) {        // 递增直到 f1 不小于 N，使 f0 < N <= f1
        int temp = f1;
        f1 = f0 + f1;
        f0 = temp;
    }
    if (N - f0 <= f1 - N) {     // 距离相等时取较小的 f0
        printf("%d\n", f0);
    } else {
        printf("%d\n", f1);
    }
    return 0;
}