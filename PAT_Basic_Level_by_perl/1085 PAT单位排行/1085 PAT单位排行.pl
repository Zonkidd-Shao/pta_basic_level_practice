use strict;
use warnings;

# =====================================================================
# 题目：1085 PAT单位排行
# 难度：中等
# 知识点：哈希表, 排序
# =====================================================================
#
# 【题目描述】
#   给定若干考生信息（准考证号、得分、学校），按学校汇总加权总分并排名。
#   加权总分 = 乙级(B)/1.5 + 甲级(A) + 顶级(T)*1.5 的整数部分。
#   排名按总分降序；并列则同排名，按考生人数升序；仍并列按学校字典序。
#
# 【实现原理】
#   1. 按准考证首字母区分级别，把分数乘以对应权重累加到学校总分
#      (B:*1/1.5, A:*1, T:*1.5)
#   2. 用哈希集合统计每所学校考生人数（去重）
#   3. 取各校总分整数部分，按 (总分降序, 人数升序, 学校名升序) 排序
#   4. 分数相同时共享排名，按排名输出
# =====================================================================
#
# 【输入样例】
#   10
#   A57908 85 Au
#   B57908 54 LanX
#   A37487 60 au
#   T28374 67 CMU
#   T32486 24 hypu
#   A66734 92 cmu
#   B76378 71 AU
#   A47780 45 lanx
#   A72809 100 pku
#   A03274 45 hypu
# 【输出样例】
#   5
#   1 cmu 192 2
#   1 au 192 3
#   3 pku 100 1
#   4 hypu 81 2
#   4 lanx 81 2
# =====================================================================

# 读取考生人数 N
my $n = <STDIN>;
chomp $n;

# %total: 学校 -> 加权总分（浮点累加）
# %num:   学校 -> 考生人数（去重计数）
my (%total, %num);
my %seen;

for (1 .. $n) {
    my $l = <STDIN>;
    chomp $l;
    my ($id, $sc, $sch) = split /\s+/, $l;
    $sch = lc $sch;                      # 学校名转小写
    my $weight = 1 / 1.5;                # 默认乙级 B
    $weight = 1    if substr($id, 0, 1) eq 'A';   # 甲级
    $weight = 1.5  if substr($id, 0, 1) eq 'T';   # 顶级
    $total{$sch} += $sc * $weight;       # 累加加权分数
    if (!$seen{"$sch $id"}) {            # 考生去重计数
        $seen{"$sch $id"} = 1;
        $num{$sch}++;
    }
}

# 构造结果列表：[总分整数, 学校, 人数]
my @rows;
for my $k (keys %total) {
    push @rows, [ int($total{$k}), $k, $num{$k} ];
}

# 排序：总分降序，人数升序，学校字典序升序
@rows = sort {
    $b->[0] <=> $a->[0] || $a->[2] <=> $b->[2] || $a->[1] cmp $b->[1]
} @rows;

# 输出单位个数
print scalar(@rows), "\n";

# 输出排名（并列共享排名）
my $rank = 0;
my $last = -1;
for my $i (0 .. $#rows) {
    if ($rows[$i][0] != $last) {
        $rank = $i + 1;
        $last = $rows[$i][0];
    }
    print "$rank $rows[$i][1] $rows[$i][0] $rows[$i][2]\n";
}
