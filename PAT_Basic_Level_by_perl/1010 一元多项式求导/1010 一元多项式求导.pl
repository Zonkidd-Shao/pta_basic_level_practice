use strict;
use warnings;

# =====================================================================
# 题目：1010 一元多项式求导
# 难度：简单
# 知识点：数组操作、多项式求导
# =====================================================================
#
# 【题目描述】
#   设计函数求一元多项式的导数。
#   输入格式：以指数递降方式输入多项式非零项的系数和指数。
#   输出格式：以相同格式输出导数多项式的非零项。
#   注意：零多项式表示为 "0 0"。
#
# 【实现原理】
#   1. 求导规则：
#      - 对于 x^n（n 为整数），一阶导数为 n * x^(n-1)
#      - 即：项 (c, e) 的导数为 (c*e, e-1)
#      - 指数为 0 的项（常数项）导数为 0，直接丢弃
#   2. 输入处理：
#      - 输入是一长串数字，按"系数 指数 系数 指数 ..."交替排列
#      - 每两个数字组成一项，步长为 2 遍历
#   3. 逐项求导：
#      - 跳过指数为 0 的项（常数项求导后消失）
#      - 其他项计算新系数和新指数，加入结果数组
#   4. 边界处理：
#      - 若结果数组为空（即原多项式是常数多项式），输出 "0 0"
#      - 否则输出所有非零项的系数和指数
#   5. 时间复杂度：O(N)，N 为项数。
#   6. 空间复杂度：O(N)，存储结果。
#
# 【输入样例】 3 4 -5 2 6 1 -2 0
#   表示多项式：3x^4 - 5x^2 + 6x - 2
# 【输出样例】 12 3 -10 1 6 0
#   导数多项式：12x^3 - 10x + 6
#   计算过程：
#     3x^4   -> 3*4 x^(4-1) = 12x^3
#     -5x^2  -> -5*2 x^(2-1) = -10x
#     6x^1   -> 6*1 x^(1-1) = 6x^0 = 6
#     -2x^0  -> （常数项，导数为 0，丢弃）
# =====================================================================

# 读取整行输入
my $line = <STDIN>;
chomp $line;
# 按空白分割为数字数组
my @t = split /\s+/, $line;

# 存储求导结果的数组
my @out;

# 每两个元素为一组（系数、指数），步长为 2 遍历
for (my $i = 0; $i < @t; $i += 2) {
    # 当前项的系数 c 和指数 e
    my ($c, $e) = ($t[$i], $t[$i + 1]);
    # 指数为 0 的项是常数项，导数为 0，跳过
    next if $e == 0;
    # 求导：新系数 = c*e，新指数 = e-1
    push @out, $c * $e, $e - 1;
}

# 若结果为空（零多项式），输出 "0 0"
if (@out == 0) {
    print "0 0\n";
}
# 否则输出所有项
else {
    print join(' ', @out), "\n";
}
