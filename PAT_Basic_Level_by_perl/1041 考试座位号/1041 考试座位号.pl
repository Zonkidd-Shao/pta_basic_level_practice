use strict;
use warnings;

# =====================================================================
# 题目：1041 考试座位号
# 难度：简单
# 知识点：哈希表, 映射查找
# =====================================================================
#
# 【题目描述】
#   每个考生有准考证号、试机座位号、考试座位号。给出 N 名考生信息，
#   再给出 M 个待查询的试机座位号，对每个查询输出对应考生的
#   准考证号和考试座位号。
#
# 【实现原理】
#   1. 用哈希 %map 建立 "试机座位号 → (准考证号, 考试座位号)" 的映射。
#   2. 读取 M 个待查询的试机座位号，直接查表输出。
#   3. 时间复杂度 O(N + M)，空间复杂度 O(N)。
#
# 【输入样例】
#   4
#   3310120150912233 2 4
#   3310120150912119 4 1
#   3310120150912126 1 3
#   3310120150912002 3 2
#   2
#   3 4
# 【输出样例】
#   3310120150912002 2
#   3310120150912119 1
# =====================================================================

# 读取考生人数 N
my $n = <STDIN>;
chomp $n;

# %map: 试机座位号 → [准考证号, 考试座位号]
my %map;
for my $i (1 .. $n) {
    my $line = <STDIN>;
    chomp $line;
    my ($id, $try_seat, $exam_seat) = split /\s+/, $line;
    $map{$try_seat} = [$id, $exam_seat];
}

# 读取查询个数 M（该行通常只含一个数，忽略）
my $m_line = <STDIN>;

# 读取 M 个待查询的试机座位号
my @queries = split /\s+/, <STDIN>;

# 逐个查询并输出
for my $q (@queries) {
    my $rec = $map{$q};
    print "$rec->[0] $rec->[1]\n";
}
