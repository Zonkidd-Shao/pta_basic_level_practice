use strict;
use warnings;

# =====================================================================
# 题目：1025 反转链表
# 难度：中等
# 知识点：链表, 模拟
# =====================================================================
#
# 【题目描述】
#   给定单链表 L 的每个结点地址、数据与后继地址，将链表中每 K 个结点
#   为一组进行反转，最后一组不足 K 个则不反转，输出反转后的链表。
#
# 【实现原理】
#   1. 用哈希表记录每个地址的数据和后继。
#   2. 从链头沿 Next 遍历，得到结点地址顺序。
#   3. 每 K 个一组做就地反转。
#   4. 按新顺序输出每个结点的地址、数据和下一个地址。
#
# 【输入样例】
#   00100 6 4
#   00000 4 99999
#   00100 1 12309
#   68237 6 -1
#   33218 3 00000
#   99999 5 68237
#   12309 2 33218
# 【输出样例】
#   00000 4 33218
#   33218 3 12309
#   12309 2 00100
#   00100 1 99999
#   99999 5 68237
#   68237 6 -1
# =====================================================================

my $line = <STDIN>;
chomp $line;
my ($head, $n, $k) = split / +/, $line;

my (%data, %next);
for (1 .. $n) {
    my $l = <STDIN>;
    chomp $l;
    my ($addr, $d, $nx) = split / +/, $l;
    $data{$addr} = $d;
    $next{$addr} = $nx;
}

# 沿链得到结点地址顺序
my @order = ();
my $cur = $head;
while ($cur ne '-1') {
    push @order, $cur;
    $cur = $next{$cur};
}

# 每 K 个一组反转
for (my $i = 0; $i + $k <= scalar(@order); $i += $k) {
    my @seg = reverse @order[$i .. $i + $k - 1];
    @order[$i .. $i + $k - 1] = @seg;
}

# 输出反转后的链表
for my $i (0 .. $#order) {
    my $nx = $i + 1 < scalar(@order) ? $order[$i + 1] : '-1';
    print "$order[$i] $data{$order[$i]} $nx\n";
}