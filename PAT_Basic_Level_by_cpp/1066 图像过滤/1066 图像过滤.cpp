// 1066 图像过滤
//
// 实现原理：
// 给定一个 M 列 N 行的图像，每个像素为 0~255 的灰度值。
// 将落在指定区间 [A, B] 内的像素值替换为指定值 rep，其余像素保持不变。
// 按 3 位宽输出处理后的图像。
//
// 关键步骤：
// 1. 读取图像尺寸 M×N、过滤区间 [A, B] 和替换值 rep
// 2. 逐像素读取，若值在 [A, B] 范围内则替换
// 3. 按 %03d 格式输出（3 位宽，不足补零）
//
// 注意：
// 这里读取顺序是外层循环 n（行）、内层循环 m（列），
// 与通常的 m×n 表示略有不同，但本质是逐个处理所有像素。
//
// 复杂度分析：
// 时间复杂度：O(N*M)，遍历所有像素一次。
// 空间复杂度：O(1)，只使用常数额外空间（逐像素处理，无需存储整张图）。
#include <iostream>
#include <cstdio>

using namespace std;

int main() {
    int m, n, a, b, rep;
    if (!(cin >> m >> n >> a >> b >> rep)) return 0;

    // M行N列：M为行数，N为列数
    for (int i = 0; i < m; ++i) {
        for (int j = 0; j < n; ++j) {
            int v;
            cin >> v;
            if (v >= a && v <= b) v = rep;  // 在区间内则替换
            if (j) cout << ' ';
            printf("%03d", v);  // 3 位宽输出，不足补零
        }
        cout << endl;
    }
    return 0;
}