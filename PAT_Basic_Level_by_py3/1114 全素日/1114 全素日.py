# 题目：1114 全素日
#
# 题目描述：
#   ![wbfg.JPG](~/f4c6f880-b7ed-4893-b10f-045937586870.JPG)
#   以上图片来自新浪微博，展示了一个非常酷的“全素日”：2019年5月23日。即不仅`20190523`本身是个素数，它的任何以末尾数字`3`结尾的子串都是素数。
#   本题就请你写个程序判断一个给定日期是否是“全素日”。
#
# 输入格式：
#   输入按照 `yyyymmdd` 的格式给出一个日期。题目保证日期在0001年1月1日到9999年12月31日之间。
#
# 输出格式：
#   从原始日期开始，按照子串长度递减的顺序，每行首先输出一个子串和一个空格，然后输出 `Yes`，如果该子串对应的数字是一个素数，否则输出 `No`。如果这个日期是一个全素日，则在最后一行输出 `All Prime!`。
#
# 实现原理：
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   素数判断与日期：判断一个日期的年、月、日、
#   以及各种组合是否都是素数。
#
import sys

s=sys.stdin.readline().strip()
def p(n):return n>1 and all(n%i for i in range(2,int(n**.5)+1))
ok=True
for i in range(len(s)):
 x=s[i:];q=p(int(x));print(x,'Yes' if q else 'No');ok&=q
if ok:print('All Prime!')
