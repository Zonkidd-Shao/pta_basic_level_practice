use strict;
use warnings;

# =====================================================================
# 题目：1036 跟奥巴马一起编程
# 难度：简单
# 知识点：循环, 字符串重复, 矩阵打印
# =====================================================================
#
# 【题目描述】
#   给定正方形边长 N 和字符 C，用 C 画出正方形。由于行间距比列间距大，
#   为使结果更像正方形，输出的行数为列数的 50%（四舍五入取整）。
#
# 【实现原理】
#   1. 计算行数 rows = round(N/2)（四舍五入）。
#   2. 打印第一行：由 N 个字符 C 组成。
#   3. 打印中间 rows-2 行：两端各一个 C，中间 N-2 个空格。
#   4. 打印最后一行：由 N 个字符 C 组成（rows>1 时）。
#
# 【输入样例】
#   10 a
# 【输出样例】
#   aaaaaaaaaa
#   a        a
#   a        a
#   a        a
#   aaaaaaaaaa
# =====================================================================

# 读取边长 N 和字符 C
my $line = <STDIN>;
chomp $line;
my ($n, $c) = split /\s+/, $line;

# 行数为列数的 50%，四舍五入取整
my $rows = int($n / 2 + 0.5);

# 第一行：N 个字符
print $c x $n, "\n";

# 中间 rows-2 行：两端字符，中间空格
for (1 .. $rows - 2) {
    print $c, ' ' x ($n - 2), $c, "\n";
}

# 最后一行（rows>1 时）
print $c x $n, "\n" if $rows > 1;