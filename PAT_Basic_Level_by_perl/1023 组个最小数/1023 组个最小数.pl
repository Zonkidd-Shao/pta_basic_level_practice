use strict;
use warnings;

# =====================================================================
# 题目：1023 组个最小数
# 难度：简单
# 知识点：贪心算法, 字符串处理
# =====================================================================
#
# 【题目描述】
#   给定数字 0-9 各若干个，全部使用它们排列成一个最小的数，
#   注意 0 不能做首位。
#
# 【实现原理】
#   1. 先取一个最小的非零数字作为首位。
#   2. 其余数字按升序全部拼接在后。
#
# 【输入样例】
#   2 2 0 0 0 3 0 0 1 0
# 【输出样例】
#   10015558
# =====================================================================

my @tok = split /\s+/, join('', <STDIN>);
my @cnt = @tok;                       # cnt[i] 表示数字 i 的个数

my $out = '';
# 找最小的非零数字作为首位
for my $i (1 .. 9) {
    if ($cnt[$i] > 0) {
        $out = "$i";
        $cnt[$i]--;
        last;
    }
}

# 其余数字按升序全部使用
for my $i (0 .. 9) {
    $out .= $i x $cnt[$i];
}

print "$out\n";