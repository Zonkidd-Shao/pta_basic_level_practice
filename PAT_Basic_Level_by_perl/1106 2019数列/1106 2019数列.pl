use strict;
use warnings;

# =====================================================================
# 题目：1106 2019数列
# 难度：简单
# 知识点：递推, 循环
# =====================================================================
#
# 【题目描述】
#   数列前 4 项为 2,0,1,9，之后每一项等于前 4 项之和的个位数字，
#   输出前 n 项（数字间无空格）。
#
# 【实现原理】
#   1. 初始化数列为 [2,0,1,9]。
#   2. 从第 5 项起，每次求末 4 项之和并对 10 取模，追加到末尾。
#   3. 拼接前 n 项并输出。
#
# 【输入样例】
#   10
# 【输出样例】
#   2019224758
# =====================================================================

my $line = <STDIN>;
chomp $line;
my $n = $line + 0;

my @a = (2, 0, 1, 9);
while (@a < $n) {
    # 前 4 项之和的个位数字
    my $s = 0;
    $s += $_ for @a[-4 .. -1];
    push @a, $s % 10;
}

# 输出前 n 项
print join('', @a[0 .. $n - 1]), "\n";
