# 题目：1113 钱串子的加法
#
# 题目描述：
#   ![qcz.JPG](~/3f9ac9be-c2a5-444f-a83c-e45f76303613.JPG)
#   人类习惯用 10 进制，可能因为大多数人类有 10 根手指头，可以用于计数。这个世界上有一种叫“钱串子”（学名“蚰蜒”）的生物，有 30 只细长的手/脚，在它们的世界里，数字应该是 30 进制的。本题就请你实现钱串子世界里的加法运算。
#
# 输入格式：
#   输入在一行中给出两个钱串子世界里的非负整数，其间以空格分隔。
#   所谓“钱串子世界里的整数”是一个 30 进制的数字，其数字 0 到 9 跟人类世界的整数一致，数字 10 到 29 用小写英文字母 a 到 t 顺次表示。
#   输入给出的两个整数都不超过 10^5 位。
#
# 输出格式：
#   在一行中输出两个整数的和。注意结果数字不得有前导零。
#
# 实现原理：
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   大数加法：处理带千分位的数字加法，
#   去掉分隔符后相加再格式化输出。
#
import sys

a,b=sys.stdin.read().split();out=[];carry=0
for i in range(1,max(len(a),len(b))+1):
 x=int(a[-i],30) if i<=len(a) else 0;y=int(b[-i],30) if i<=len(b) else 0;carry,x=divmod(x+y+carry,30);out.append('0123456789abcdefghijklmnopqrst'[x])
if carry:out.append('1')
print(''.join(out[::-1]).lstrip('0') or '0')
