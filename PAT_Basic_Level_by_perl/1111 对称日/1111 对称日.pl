use strict;
use warnings;

# =====================================================================
# 题目：1111 对称日
# 难度：简单
# 知识点：字符串回文, 日期格式化
# =====================================================================
#
# 【题目描述】
#   给定若干日期（英文习惯格式 Month Day, Year），判断按
#   年年年年月月日日 格式组成的字符串是否为回文（对称日）。
#
# 【实现原理】
#   1. 用哈希表将月份缩写映射为数字。
#   2. 将年份、月份、日期格式化为 8 位数字串。
#   3. 判断该串与其逆序是否相同，输出 Y 或 N。
#
# 【输入样例】
#   5
#   Feb 2, 2020
#   ...
# 【输出样例】
#   Y 20200202
#   N 20200307
#   ...
# =====================================================================

# 月份缩写 -> 数字
my %months = (
    Jan => 1, Feb => 2,  Mar => 3,  Apr => 4,
    May => 5, Jun => 6,  Jul => 7,  Aug => 8,
    Sep => 9, Oct => 10, Nov => 11, Dec => 12,
);

# 读取日期个数
my $n = <STDIN>;
chomp $n;

for (1 .. $n) {
    my $l = <STDIN>;
    chomp $l;
    $l =~ s/,//g;                    # 去掉逗号
    my ($m, $d, $y) = split /\s+/, $l;
    # 格式化为 年年年年月月日日
    my $s = sprintf "%04d%02d%02d", $y, $months{$m}, $d;
    my $rev = reverse $s;
    # 判断是否为回文并输出
    print(($s eq $rev) ? 'Y ' : 'N ');
    print "$s\n";
}
