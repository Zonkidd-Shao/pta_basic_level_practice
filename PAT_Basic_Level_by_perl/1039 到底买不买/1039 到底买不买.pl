use strict;
use warnings;

# =====================================================================
# 题目：1039 到底买不买
# 难度：简单
# 知识点：字符计数, 哈希表
# =====================================================================
#
# 【题目描述】
#   小红想买一串珠子，摊主的珠串（第 1 行）和小红想要的珠串（第 2 行）
#   分别由 [0-9][a-z][A-Z] 字符表示。判断摊主的珠串是否包含了
#   全部想要的珠子：
#   - 包含：输出 Yes 以及多余的珠子数；
#   - 不包含：输出 No 以及缺少的珠子数。
#
# 【实现原理】
#   1. 统计摊主珠串中各字符的出现次数。
#   2. 遍历想要的珠串，逐字符检查摊主是否还有剩余；
#      - 有剩余则消耗一颗，多余珠子数加一；
#      - 无剩余则缺少珠子数加一。
#   3. 缺少数 > 0 输出 No，否则输出 Yes 和多余数。
#   4. 时间复杂度 O(L)，空间复杂度 O(字符集大小)。
#
# 【输入样例 1】
#   ppRYYGrrYBR2258
#   YrR8RrY
# 【输出样例 1】
#   Yes 8
# =====================================================================

# 读取摊主的珠串
my $shop = <STDIN>;
chomp $shop;
# 读取小红想要的珠串
my $want = <STDIN>;
chomp $want;

# 统计摊主珠串中各字符的个数
my %cnt;
for my $ch (split //, $shop) {
    $cnt{$ch}++;
}

# 遍历想要的珠串，判断是否足够，并统计缺少数
my $lack = 0;
for my $ch (split //, $want) {
    if (($cnt{$ch} || 0) > 0) {
        # 摊主有该珠子，消耗一颗
        $cnt{$ch}--;
    } else {
        # 摊主缺该珠子
        $lack++;
    }
}

# 缺少数非零输出 No，否则输出 Yes 及多余珠子数
if ($lack) {
    print "No $lack\n";
} else {
    # 全部满足时，多余珠子数 = 摊主珠串长度 - 想要的珠串长度
    my $extra = length($shop) - length($want);
    print "Yes $extra\n";
}
