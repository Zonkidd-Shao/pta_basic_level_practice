# 题目：1056 组合数的和
#
# 题目描述：
#   给定 N 个非 0 的个位数字，用其中任意 2 个数字都可以组合成 1 个 2 位的数字。要求所有可能组合出来的 2 位数字的和。例如给定 2、5、8，则可以组合出：25、28、52、58、82、85，它们的和为330。
#
# 输入格式：
#   输入在一行中先给出 N（1 < N < 10），随后给出 N 个不同的非 0 个位数字。数字间以空格分隔。
#
# 输出格式：
#   输出所有可能组合出来的2位数字的和。
#
# 实现原理：
#   - 循环迭代处理
#   - 列表操作
#
# 算法思路：
#   数学计算：计算所有可能的两位数组合之和，
#   利用数学公式简化计算。
#
import sys

a=list(map(int,sys.stdin.read().split()))[1:]; print(sum(x*11*(len(a)-1) for x in a))
