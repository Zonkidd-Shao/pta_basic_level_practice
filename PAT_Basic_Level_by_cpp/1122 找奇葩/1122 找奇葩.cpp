// 1122 找奇葩
//
// 实现原理：
// 在一个正整数序列中，所有的奇数都出现了偶数次，只有一个奇葩奇数出现了奇数次。
// 任务就是找出这个奇葩。由于偶数次出现的奇数在异或运算中会相互抵消，
// 因此只需对所有奇数做异或，剩下的结果就是出现奇数次的奇葩。
//
// 关键步骤：
// 1. 遍历序列，仅对奇数进行异或运算。
// 2. 偶数次出现的奇数异或后抵消为 0，最终结果即为出现奇数次的奇葩。
//
// 复杂度分析：
// 时间复杂度：O(N)，一次遍历。
// 空间复杂度：O(1)，仅使用常数个变量。
#include <iostream>

using namespace std;

int main() {
    int n;
    if (!(cin >> n)) return 0;

    int ans = 0;
    for (int i = 0; i < n; ++i) {
        int x;
        cin >> x;
        if (x % 2 == 1) ans ^= x;   // 只对奇数异或，偶数次出现会抵消
    }
    cout << ans << endl;
    return 0;
}
