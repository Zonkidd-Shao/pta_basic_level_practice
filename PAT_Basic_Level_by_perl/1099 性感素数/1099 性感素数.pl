use strict;
use warnings;

# =====================================================================
# 题目：1099 性感素数
# 难度：中等
# 知识点：素数判定, 数学
# =====================================================================
#
# 【题目描述】
#   形如 (p, p+6) 的一对素数称为“性感素数”。判断给定 N 是否为
#   性感素数：是则输出配对的那个（不唯一取较小者）；
#   否则输出 No 和大于 N 的最小性感素数。
#
# 【实现原理】
#   1. 素数判定采用试除法（界为平方根）
#   2. N 为素数且 N-6 或 N+6 为素数即性感素数；
#      否则从 N+1 起逐个递增寻找第一个性感素数
#
# 【输入样例】
#   47
# 【输出样例】
#   Yes
#   41
# =====================================================================

my $n = <STDIN>; chomp $n;
$n = 0 + $n;                                   # 转为整数

# 素数判定：x 为 2 及以上且无因子即素数
sub is_prime {
    my $x = shift;
    return 0 if $x < 2;                        # 0、1 不是素数
    return 1 if $x == 2;
    return 0 if $x % 2 == 0;                   # 偶数直接排除
    for (my $i = 3; $i * $i <= $x; $i += 2) {
        return 0 if $x % $i == 0;
    }
    return 1;
}

if (is_prime($n) && (is_prime($n - 6) || is_prime($n + 6))) {
    print "Yes\n";
    if (is_prime($n - 6)) {                    # 配对不唯一时取较小者
        print $n - 6, "\n";
    } else {
        print $n + 6, "\n";
    }
} else {
    my $m = $n;
    # 从 N 起递增，找到第一个性感素数
    while (!(is_prime($m) && (is_prime($m - 6) || is_prime($m + 6)))) {
        $m++;
    }
    print "No\n", $m, "\n";
}